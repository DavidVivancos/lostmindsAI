# 8. FULL DEMONSTRATION + SELF-TESTS
# ---------------------------------------------------------------------------
def run_self_tests():
    t0 = time.time()
    rng = np.random.default_rng(RNG_SEED)

    # --- 8.1 mandatory gradient check -------------------------------------
    P = init_params(rng)
    X0, yN0, yH0 = generate_environment(64, RNG_SEED)
    err, n_checked = gradient_check(P, X0, yN0, yH0)
    print(f"[1] gradient check: max rel. error = {err:.2e} over {n_checked} probes")
    assert err < 2e-3, "GRADIENT CHECK FAILED"

    # --- 8.2 train on the normal ('adah-intact) regime ---------------------
    X_train, yN_train, yH_train = generate_environment(4000, RNG_SEED)
    hist = train(P, X_train, yN_train, yH_train, epochs=250, seed=1)
    print(f"[2] trained: loss {hist[0]:.3f} -> {hist[-1]:.3f}")
    assert hist[-1] < hist[0] * 0.5, "TRAINING DID NOT CONVERGE"

    # --- 8.3 doubt engine on held-out, same-distribution data --------------
    X_val, yN_val, yH_val = generate_environment(2000, RNG_SEED + 1)
    report = doubt_engine(P, X_val, yN_val, yH_val)
    verdicts = necessity_verdict(report)
    print(f"[3] doubt engine: necessary={report['necessary']}, habitual={report['habitual']}")
    print(f"    verdicts: {verdicts}")
    assert verdicts["necessary"].startswith("NECESSARY")
    assert verdicts["habitual"].startswith("HABITUAL")
    assert report["necessary"]["mean_acc"] > 0.98
    assert 0.80 < report["habitual"]["mean_acc"] < 0.97

    # --- 8.4 consolidation + domain boundary --------------------------------
    frozen = consolidate(P, report)
    boundary = fit_domain_boundary(X_train)
    mind = GhazaliMind(P, report, boundary, frozen)
    print(f"[4] consolidated params: {frozen or '(none)'}")
    assert frozen, "NECESSARY HEAD SHOULD HAVE CONSOLIDATED"

    # --- 8.5 in-distribution behaviour: gated vs naive baseline -------------
    X_id, yN_id, yH_id = generate_environment(2000, RNG_SEED + 2)
    pn_id, ph_id, _ = forward(P, X_id)
    baseline_acc_id = ((ph_id > 0.5).astype(float) == yH_id).mean()
    print(f"[5] in-distribution habitual accuracy (raw model): {baseline_acc_id:.3f}")
    assert baseline_acc_id > 0.85

    # --- 8.6 the shift: 'adah interrupted -----------------------------------
    X_shift, yN_shift, yH_shift = generate_environment(3000, RNG_SEED + 3, shift=True)
    pn_s, ph_s, _ = forward(P, X_shift)
    baseline_conf_s = np.maximum(ph_s, 1 - ph_s).mean()          # naive model's stated confidence
    baseline_acc_s = ((ph_s > 0.5).astype(float) == yH_shift).mean()
    naive_confidently_wrong = ((ph_s > 0.5).astype(float) != yH_shift).mean() * baseline_conf_s
    print(f"[6] SHIFT: naive baseline stays {baseline_conf_s:.1%} confident "
          f"but accuracy collapses to {baseline_acc_s:.1%} "
          f"(confidently-wrong mass \u2248 {naive_confidently_wrong:.1%})")
    assert baseline_acc_s < 0.60, "SHIFT SHOULD BREAK THE HABITUAL CHANNEL"
    assert baseline_conf_s > 0.75, "NAIVE MODEL SHOULD STILL SOUND CONFIDENT (epistemic overreach)"

    # necessary channel must be untouched by the shift (it never depended on it)
    necessary_acc_shift = ((pn_s > 0.5).astype(float) == yN_shift).mean()
    print(f"    necessary channel under shift: {necessary_acc_shift:.3f} (should be ~unchanged)")
    assert necessary_acc_shift > 0.98

    # --- 8.7 rolling doubt audit: does the mind notice, and stop asserting? -
    detected_at = None
    window = 150
    for start in range(0, X_shift.shape[0], window):
        xb = X_shift[start:start + window]
        yb = yH_shift[start:start + window]
        if xb.shape[0] < window:
            break
        acc = mind.rolling_audit(xb, yb)
        if mind.habitual_suspended and detected_at is None:
            detected_at = start + window
    print(f"[7] rolling doubt audit suspended the habitual channel after "
          f"{detected_at} examples of the shifted stream")
    assert detected_at is not None and detected_at <= 900, "AUDIT DID NOT CATCH THE BROKEN HABIT IN TIME"

    # gated system's stated confidence for 'habitual' after suspension is None
    # (it refuses to assert), so its confidently-wrong mass on the *remaining*
    # post-detection stream is exactly zero, unlike the naive baseline above.
    post_detect = X_shift[detected_at:]
    assert mind.habitual_suspended
    print(f"[8] after suspension, {post_detect.shape[0]} further examples are "
          f"answered with SUSPENDED on the habitual channel (0% confidently-wrong "
          f"by construction), vs a naive model that stays ~{baseline_conf_s:.0%} confident throughout")

    # --- 8.9 domain boundary: out-of-support novelty ------------------------
    X_novel, _, _ = generate_environment(300, RNG_SEED + 4, novelty=True)
    flagged = out_of_domain(boundary, X_novel).mean()
    print(f"[9] novelty probes flagged SUSPENDED (out of domain): {flagged:.1%}")
    assert flagged > 0.80, "DOMAIN BOUNDARY FAILED TO CATCH OUT-OF-SUPPORT INPUTS"

    dt = time.time() - t0
    print(f"\nALL SELF-TESTS PASSED in {dt:.2f}s")
    return True


if __name__ == "__main__":
    ok = run_self_tests()
    sys.exit(0 if ok else 1)
