def make_extended_clan(rng: np.random.Generator, n_generations: int = 6, branch: int = 2):
    """Build one large multi-generation family tree (not used for training --
    only for the ablation below). Returns adjacency lists suitable for
    `_bfs_reachable`, plus alive flags. Every member who is a blood relative
    at all is wired in, with no role restriction -- this graph deliberately
    has no notion of 'eligible role', only kinship distance, so that raw
    hop-limited reachability can be measured on something bigger than the
    N_NODES=10 cases used for training."""
    nodes = [0]
    parent_of = {0: None}
    generation = {0: 0}
    frontier = [0]
    for g in range(1, n_generations + 1):
        new_frontier = []
        for p in list(frontier):
            n_children = rng.integers(1, branch + 1)
            for _ in range(n_children):
                nid = len(nodes)
                nodes.append(nid)
                parent_of[nid] = p
                generation[nid] = g
                new_frontier.append(nid)
        # also give the victim's own direct line a sibling at each
        # generation so the tree isn't a pure single lineage
        frontier = new_frontier
    # add siblings: for every non-root node, w.p. 0.5 give its parent one
    # more child (a sibling of that node) to create sibling edges
    sib_pairs = []
    for nid, p in list(parent_of.items()):
        if p is not None and rng.random() < 0.5:
            sid = len(nodes)
            nodes.append(sid)
            parent_of[sid] = p
            generation[sid] = generation[nid]
            sib_pairs.append((nid, sid))

    n = len(nodes)
    adj_list = [set() for _ in range(n)]
    for nid, p in parent_of.items():
        if p is not None:
            adj_list[nid].add(p)
            adj_list[p].add(nid)
    for a, b in sib_pairs:
        adj_list[a].add(b)
        adj_list[b].add(a)

    alive = np.array([1.0 if rng.random() < 0.55 else 0.0 for _ in range(n)])
    alive[0] = 1.0
    return adj_list, alive, n


def selftest_unbounded_vs_bounded(net: ContainmentFallbackNet, verbose=True):
    """Ablation in two independent parts.

    Part 1 (the actual point): on a LARGE multi-generation clan with no
    role restriction, plain hop-limited reachability is measured directly
    from the graph (not from the trained network) at increasing hop
    budgets. This shows the pool of "alive and within H hops" kin growing
    as H grows -- exactly the unbounded blast radius Article 1's enumerated
    list (equivalent to a hard H=2 cap PLUS a role filter) is built to
    avoid. A simple branching-process bound then shows why an ever-growing
    eligible pool is dangerous in expectation, independent of any specific
    graph.

    Part 2 (a sanity check, not an ablation): confirms the TRAINED network
    -- which by construction is only ever invoked at its architectural cap
    of two hops, see `forward_case` -- reproduces the role-based ground
    truth on ordinary-sized cases. The network is never run past its
    design depth in this file; Part 1 measures what the underlying RULE
    would allow if the cap were removed, not what the trained weights do
    out of distribution.
    """
    rng = np.random.default_rng(77)
    adj_list, alive, n = make_extended_clan(rng, n_generations=7, branch=2)

    def reachable_alive_count(max_hops):
        reach = _bfs_reachable(adj_list, 0, max_hops)
        return sum(1 for i in reach if alive[i] > 0.5)

    depths = (1, 2, 3, 4, 6, 8, 10, 14)
    counts = {d: reachable_alive_count(d) for d in depths}

    r = 1.15
    bounded_cap = 2
    unbounded_cap = 14
    expected_bounded = sum(r ** k for k in range(bounded_cap + 1))
    expected_unbounded = sum(r ** k for k in range(unbounded_cap + 1))

    if verbose:
        print(f"    extended clan: {n} members across 7 generations, no role restriction")
        print("    TRUE alive-and-reachable count as a function of hop budget (graph, not network):")
        for d in depths:
            tag = "  <- Article 1's actual hop budget" if d == 2 else ""
            print(f"      hops<= {d:2d}: {counts[d]:3d} people would nominally qualify{tag}")
        print(f"    branching-process bound (r={r} new retaliations per act): "
              f"expected participants if capped at 2 hops ~ {expected_bounded:.2f}, "
              f"if allowed to {unbounded_cap} hops ~ {expected_unbounded:.1f}")

        rng2 = np.random.default_rng(555)
        n_ok, n_tot = 0, 0
        for _ in range(40):
            X, A_pc, A_sib, elig_true, y_true = make_kinship_case(rng2)
            cache = net.forward_case(X, A_pc, A_sib)
            pred = 1 if cache["p_contained"] > 0.5 else 0
            n_ok += int(pred == y_true)
            n_tot += 1
        print(f"    sanity check: trained network (always run at its D=2 cap) matches "
              f"the role-based rule on {n_ok}/{n_tot} fresh cases")
    return counts, expected_bounded, expected_unbounded


def selftest_robust_vs_naive(net: RobustHedgeNet, verbose=True):
    rng = np.random.default_rng(88)
    n_test = 300
    errs_robust, errs_naive = [], []
    for _ in range(n_test):
        clean = rng.normal(0, 1, size=K_CHANNELS - 1)
        true_mu = float(clean.mean())
        corrupt_val = true_mu + rng.choice([-1, 1]) * rng.uniform(4, 10)
        x = np.concatenate([clean, [corrupt_val]])
        rng.shuffle(x)
        out, _irls, _h1, mu_robust = net.forward_full(x)
        errs_robust.append(abs(mu_robust - true_mu))
        errs_naive.append(abs(RobustHedgeNet.naive_mean(x) - true_mu))
    mean_robust = float(np.mean(errs_robust))
    mean_naive = float(np.mean(errs_naive))
    improvement = (mean_naive - mean_robust) / mean_naive * 100
    if verbose:
        print(f"    mean |error| vs. true clean consensus, one corrupted channel in {K_CHANNELS}:")
        print(f"      naive mean of all channels : {mean_naive:.3f}")
        print(f"      robust unrolled fusion     : {mean_robust:.3f}")
        print(f"      improvement                : {improvement:.1f}%")
    return mean_robust, mean_naive, improvement


def selftest_historical_replay(net: ContainmentFallbackNet, verbose=True):
    """Small qualitative capstone: hand-built cases echoing the category
    distinctions the Pravda actually draws (not literal historical persons,
    but the TYPE distinctions it makes), checked against the trained net."""
    cases = []

    # Case 1: victim with a living brother -> should be CONTAINED (eligible avenger exists)
    X = np.zeros((N_NODES, F_IN))
    X[0] = [1, 0, 0.0, 1, 0.0]
    X[1] = [1, 0, 0.1, 0, 0.0]
    A_pc = np.zeros((N_NODES, N_NODES))
    A_sib = np.zeros((N_NODES, N_NODES))
    A_sib[0, 1] = A_sib[1, 0] = 1
    cases.append(("victim has a living brother", X, A_pc, A_sib, 1))

    # Case 2: victim's only kin (a brother) is already dead -> FALLBACK
    X2 = X.copy()
    X2[1, 0] = 0  # brother not alive
    cases.append(("victim's only brother is already dead", X2, A_pc, A_sib, 0))

    # Case 3: father dead; the only LIVING kin are an uncle (2 hops, same
    # graph distance as a nephew) and a cousin (3 hops) -- neither is an
    # enumerated role, so this must resolve to FALLBACK even though the
    # graph "looks" no sparser than Case 4 below. gen offsets follow the
    # gen_raw/2.0 convention used throughout: father=-0.5, uncle=-0.5
    # (same generation as father), cousin=0 (same generation as victim).
    X3 = np.zeros((N_NODES, F_IN))
    X3[0] = [1, 0.0, 0.0, 1, 0.0]
    X3[1] = [0, -0.5, 0.0, 0, 0.0]   # father, dead
    X3[2] = [1, -0.5, 0.0, 0, 0.0]   # father's brother (uncle) -- NOT an enumerated role
    X3[3] = [1, 0.0, 0.0, 0, 0.0]    # uncle's child (cousin) -- NOT an enumerated role
    A_pc3 = np.zeros((N_NODES, N_NODES))
    A_sib3 = np.zeros((N_NODES, N_NODES))
    A_pc3[0, 1] = A_pc3[1, 0] = 1
    A_sib3[1, 2] = A_sib3[2, 1] = 1
    A_pc3[2, 3] = A_pc3[3, 2] = 1
    cases.append(("father dead; only a living uncle (2 hops) and cousin (3 hops) survive", X3, A_pc3, A_sib3, 0))

    # Case 4: victim has a living sister's son (nephew via sister) -> CONTAINED.
    # Same graph distance as Case 3's uncle (2 hops via a sibling edge then
    # a parent-child edge) but the OTHER direction -- nephew=+0.5, not -0.5.
    X4 = np.zeros((N_NODES, F_IN))
    X4[0] = [1, 0.0, 0.0, 1, 0.0]
    X4[1] = [0, 0.0, 0.0, 0, 0.0]    # sister, already dead
    X4[2] = [1, 0.5, 0.0, 0, 0.0]    # sister's son (nephew), alive
    A_pc4 = np.zeros((N_NODES, N_NODES))
    A_sib4 = np.zeros((N_NODES, N_NODES))
    A_sib4[0, 1] = A_sib4[1, 0] = 1
    A_pc4[1, 2] = A_pc4[2, 1] = 1
    cases.append(("sister already dead, but her son (nephew, same 2-hop distance as Case 3's uncle) is alive", X4, A_pc4, A_sib4, 1))

    n_correct = 0
    for name, X, A_pc, A_sib, y_true in cases:
        cache = net.forward_case(X, A_pc, A_sib)
        pred = 1 if cache["p_contained"] > 0.5 else 0
        ok = int(pred == y_true)
        n_correct += ok
        if verbose:
            outcome = "CONTAINED (avenger eligible)" if pred == 1 else "FALLBACK (guaranteed payment)"
            mark = "OK" if ok else "MISS"
            print(f"      [{mark}] {name:48s} -> model says: {outcome}  "
                  f"(p={cache['p_contained']:.2f})")
    return n_correct, len(cases)


