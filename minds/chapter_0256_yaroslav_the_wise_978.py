def sigmoid(x: np.ndarray) -> np.ndarray:
    """Numerically stable logistic sigmoid."""
    out = np.empty_like(x, dtype=np.float64)
    pos = x >= 0
    out[pos] = 1.0 / (1.0 + np.exp(-x[pos]))
    ex = np.exp(x[~pos])
    out[~pos] = ex / (1.0 + ex)
    return out


def softplus(x: np.ndarray) -> np.ndarray:
    """Numerically stable log(1 + exp(x))."""
    return np.maximum(x, 0.0) + np.log1p(np.exp(-np.abs(x)))


def xavier(rng: np.random.Generator, fan_in: int, fan_out: int) -> np.ndarray:
    scale = np.sqrt(2.0 / (fan_in + fan_out))
    return rng.normal(0.0, scale, size=(fan_in, fan_out))


class Adam:
    """A minimal, from-scratch Adam optimizer over a flat parameter vector."""

    def __init__(self, n_params: int, lr: float = 0.02, b1: float = 0.9,
                 b2: float = 0.999, eps: float = 1e-8):
        self.lr, self.b1, self.b2, self.eps = lr, b1, b2, eps
        self.m = np.zeros(n_params)
        self.v = np.zeros(n_params)
        self.t = 0

    def step(self, theta: np.ndarray, grad: np.ndarray) -> np.ndarray:
        self.t += 1
        self.m = self.b1 * self.m + (1 - self.b1) * grad
        self.v = self.b2 * self.v + (1 - self.b2) * (grad ** 2)
        mhat = self.m / (1 - self.b1 ** self.t)
        vhat = self.v / (1 - self.b2 ** self.t)
        return theta - self.lr * mhat / (np.sqrt(vhat) + self.eps)


# ==============================================================================
# SECTION 1 -- MODULE A: ContainmentFallbackNet
#   "Two hops, then a guaranteed number."
# ==============================================================================
#
# Graph convention per case:
#   N = 10 fixed node slots. Node 0 is always the victim.
#   Node features X_raw[i] = [is_alive, generation_offset, status, is_victim, noise]
#   A_pc[i,j]  = 1 iff i,j are in a direct parent-child relation (symmetric)
#   A_sib[i,j] = 1 iff i,j are siblings (symmetric)
#   Ground truth eligibility (used only to LABEL synthetic data, never seen
#   by the network directly) = alive AND holding one of the four Article-1
#   ROLES {father, sibling, son, nephew}. Every eligible role sits within 2
#   hops through {A_pc, A_sib} edges, which is why the architecture's hop
#   cap is set to 2 -- but 2-hop reachability alone is NOT a sufficient
#   rule: "uncle" also sits at exactly 2 hops (up via father, then sideways)
#   and is NOT on Article 1's list. Distance sets the cap; kinship ROLE
#   (direction, not just distance) decides membership within it. See
#   `make_kinship_case` below for exactly how role is tracked and labelled.

N_NODES = 10
F_IN = 5
HIDDEN = 12


def _bfs_reachable(adj_list: list[set[int]], src: int, max_hops: int) -> set[int]:
    """Plain graph BFS used ONLY to generate ground-truth labels for
    synthetic training data -- this is not part of the trainable model."""
    frontier = {src}
    seen = {src}
    for _ in range(max_hops):
        nxt = set()
        for u in frontier:
            nxt |= adj_list[u]
        nxt -= seen
        seen |= nxt
        frontier = nxt
        if not frontier:
            break
    seen.discard(src)
    return seen


def make_kinship_case(rng: np.random.Generator):
    """Build one synthetic kinship case around a victim (node 0).

    Randomly wires a plausible small family and labels each node with an
    explicit ROLE (father / sibling / son / nephew / uncle / grandparent /
    cousin). Ground-truth eligibility is read off the role, not off raw
    graph distance: {father, sibling, son, nephew} are eligible (Article
    1's enumerated list); {uncle, grandparent, cousin} are NOT, even
    though "uncle" sits at exactly the same 2-hop graph distance as
    "nephew". This is what makes the learning task genuinely nontrivial --
    a rule that only counted hops could not tell uncle and nephew apart;
    the network has to use kinship DIRECTION (captured in the generation-
    offset feature) as well as distance.
    """
    N = N_NODES
    adj_pc = np.zeros((N, N))
    adj_sib = np.zeros((N, N))
    alive = np.zeros(N)
    gen = np.zeros(N)
    status = rng.normal(0, 1, size=N)
    role = ["victim"] + [None] * (N - 1)

    slot = 1

    def link_pc(a, b):
        adj_pc[a, b] = adj_pc[b, a] = 1.0

    def link_sib(a, b):
        adj_sib[a, b] = adj_sib[b, a] = 1.0

    # father (1 hop), present with prob 0.7
    father = None
    if slot < N and rng.random() < 0.7:
        father = slot
        link_pc(0, father)
        alive[father] = float(rng.random() < 0.6)
        gen[father] = -1
        role[father] = "father"
        slot += 1

    # 0-3 siblings (1 hop via sibling edge), each independently alive w.p. 0.75
    n_sib = rng.integers(0, 4)
    siblings = []
    for _ in range(n_sib):
        if slot >= N:
            break
        s = slot
        link_sib(0, s)
        alive[s] = float(rng.random() < 0.75)
        gen[s] = 0
        role[s] = "sibling"
        siblings.append(s)
        slot += 1

    # 0-2 of the victim's own sons (1 hop), each alive w.p. 0.7
    n_son = rng.integers(0, 3)
    for _ in range(n_son):
        if slot >= N:
            break
        s = slot
        link_pc(0, s)
        alive[s] = float(rng.random() < 0.7)
        gen[s] = 1
        role[s] = "son"
        slot += 1

    # nephews: children of siblings (2 hops, DOWNWARD), each sibling has 0-2
    for sib in siblings:
        if slot >= N:
            break
        n_nephew = rng.integers(0, 3)
        for _ in range(n_nephew):
            if slot >= N:
                break
            nph = slot
            link_pc(sib, nph)
            alive[nph] = float(rng.random() < 0.75)
            gen[nph] = 1
            role[nph] = "nephew"
            slot += 1

    # distractors: an uncle (father's sibling, 2 hops UPWARD via father) and
    # a grandparent (1 hop up from father), plus sometimes a cousin (child
    # of the uncle, 3 hops). All are plausible, often-alive kin; NONE are
    # eligible under Article 1's enumerated list. These exist specifically
    # so the model has a real discrimination to learn, not a free pass.
    if father is not None and slot < N and rng.random() < 0.7:
        grandparent = slot
        link_pc(father, grandparent)
        alive[grandparent] = float(rng.random() < 0.3)
        gen[grandparent] = -2
        role[grandparent] = "grandparent"
        slot += 1
        if slot < N and rng.random() < 0.8:
            uncle = slot
            link_sib(father, uncle)
            alive[uncle] = float(rng.random() < 0.6)
            gen[uncle] = -1
            role[uncle] = "uncle"
            slot += 1
            if slot < N and rng.random() < 0.5:
                cousin = slot
                link_pc(uncle, cousin)
                alive[cousin] = float(rng.random() < 0.7)
                gen[cousin] = 0
                role[cousin] = "cousin"
                slot += 1

    is_victim = np.zeros(N)
    is_victim[0] = 1.0
    noise = rng.normal(0, 0.15, size=N)
    X = np.stack([alive, gen / 2.0, status, is_victim, noise], axis=1)  # [N, F_IN]

    ELIGIBLE_ROLES = {"father", "sibling", "son", "nephew"}
    elig_true = np.zeros(N)
    for i in range(1, N):
        if role[i] in ELIGIBLE_ROLES and alive[i] > 0.5:
            elig_true[i] = 1.0
    contained_true = float(elig_true[1:].max() > 0.5) if N > 1 else 0.0

    return X, adj_pc, adj_sib, elig_true, contained_true


# ---- status tiers for the fallback head -------------------------------------
# Two tiers are drawn directly from the attested Pravda tariff (see Sources):
#   "knyaz's man" (a prince's retainer/official) -> 80 grivna
#   ordinary free person (rusin / merchant / etc.) -> 40 grivna
# A third, "disputed status" tier is a SYNTHETIC augmentation for training
# variety (interpolated), flagged here explicitly as not a historical figure.
STATUS_TIERS = np.array([
    [1.0, 0.0, 0.0],  # prince's man/official
    [0.0, 1.0, 0.0],  # ordinary free person
    [0.0, 0.0, 1.0],  # synthetic "disputed status" tier (illustrative only)
])
STATUS_TARGETS = np.array([80.0, 40.0, 58.0])  # grivna; third value is illustrative


class ContainmentFallbackNet:
    """Depth-2 bounded graph network + fallback regression head."""

    def __init__(self, rng: np.random.Generator):
        self.rng = rng
        self.W_proj = xavier(rng, F_IN, HIDDEN)
        self.b_proj = np.zeros(HIDDEN)
        self.W_pc = xavier(rng, HIDDEN, HIDDEN)
        self.W_sib = xavier(rng, HIDDEN, HIDDEN)
        self.W_self = xavier(rng, HIDDEN, HIDDEN)
        self.b_hop = np.zeros(HIDDEN)
        self.w_read = rng.normal(0, 0.3, size=HIDDEN)
        self.b_read = np.zeros(1)
        # fallback head: 3 status-tier inputs -> 8 hidden -> 1 grivna amount.
        # Larger init scale than the graph layers: with only three one-hot
        # inputs, a small-init MLP takes many epochs to break symmetry
        # between tiers (verified by isolated ablation during development);
        # a wider initial spread lets the three tiers separate quickly.
        self.W_f1 = rng.normal(0, 0.9, size=(3, 8))
        self.b_f1 = np.zeros(8)
        self.W_f2 = rng.normal(0, 0.9, size=(8, 1))
        self.b_f2 = np.array([float(STATUS_TARGETS.mean())])

    # -- parameter (un)packing, needed for the flat-vector gradient check ----
    def param_list(self):
        return [self.W_proj, self.b_proj, self.W_pc, self.W_sib, self.W_self,
                self.b_hop, self.w_read, self.b_read, self.W_f1, self.b_f1,
                self.W_f2, self.b_f2]

    def set_param_list(self, plist):
        (self.W_proj, self.b_proj, self.W_pc, self.W_sib, self.W_self,
         self.b_hop, self.w_read, self.b_read, self.W_f1, self.b_f1,
         self.W_f2, self.b_f2) = plist

    def forward_case(self, X, A_pc, A_sib):
        """Forward one case at the architectural hop cap (D=2). Returns the
        per-node eligibility, p_contained, and cached activations for backprop."""
        H0 = np.tanh(X @ self.W_proj + self.b_proj)
        msg1 = (A_pc @ H0) @ self.W_pc + (A_sib @ H0) @ self.W_sib + H0 @ self.W_self + self.b_hop
        H1 = np.tanh(msg1)
        msg2 = (A_pc @ H1) @ self.W_pc + (A_sib @ H1) @ self.W_sib + H1 @ self.W_self + self.b_hop
        H2 = np.tanh(msg2)
        logit = H2 @ self.w_read + self.b_read[0]
        s = sigmoid(logit)
        alive = X[:, 0]
        elig = s * alive
        elig_c = np.clip(elig, 1e-7, 1 - 1e-7)
        Q = np.prod(1 - elig_c[1:])
        p_contained = 1 - Q
        cache = dict(X=X, A_pc=A_pc, A_sib=A_sib, H0=H0, H1=H1, H2=H2,
                     msg1=msg1, msg2=msg2, logit=logit, s=s, alive=alive,
                     elig=elig_c, Q=Q, p_contained=np.clip(p_contained, 1e-7, 1 - 1e-7))
        return cache

    def backward_case(self, cache, y_true: float, grads: dict):
        """Hand-derived backprop for one case; accumulates into `grads`."""
        p = cache["p_contained"]
        Q = cache["Q"]
        elig = cache["elig"]
        N = elig.shape[0]

        dL_dp = (p - y_true) / (p * (1 - p) + 1e-12)
        dL_dQ = -dL_dp
        dL_delig = np.zeros(N)
        # dQ/de_i = -Q/(1-e_i) for i in 1..N-1
        for i in range(1, N):
            dQ_dei = -Q / (1 - elig[i] + 1e-12)
            dL_delig[i] = dL_dQ * dQ_dei

        s = cache["s"]
        alive = cache["alive"]
        dL_dlogit = dL_delig * alive * s * (1 - s)

        H2 = cache["H2"]
        grads["w_read"] += H2.T @ dL_dlogit
        grads["b_read"] += np.array([dL_dlogit.sum()])
        dL_dH2 = np.outer(dL_dlogit, self.w_read)

        dL_dmsg2 = dL_dH2 * (1 - H2 ** 2)
        H1 = cache["H1"]
        A_pc, A_sib = cache["A_pc"], cache["A_sib"]
        M_pc2 = A_pc @ H1
        M_sib2 = A_sib @ H1
        grads["W_pc"] += M_pc2.T @ dL_dmsg2
        grads["W_sib"] += M_sib2.T @ dL_dmsg2
        grads["W_self"] += H1.T @ dL_dmsg2
        grads["b_hop"] += dL_dmsg2.sum(axis=0)
        dL_dH1 = (A_pc.T @ (dL_dmsg2 @ self.W_pc.T)
                  + A_sib.T @ (dL_dmsg2 @ self.W_sib.T)
                  + dL_dmsg2 @ self.W_self.T)

        dL_dmsg1 = dL_dH1 * (1 - H1 ** 2)
        H0 = cache["H0"]
        M_pc1 = A_pc @ H0
        M_sib1 = A_sib @ H0
        grads["W_pc"] += M_pc1.T @ dL_dmsg1
        grads["W_sib"] += M_sib1.T @ dL_dmsg1
        grads["W_self"] += H0.T @ dL_dmsg1
        grads["b_hop"] += dL_dmsg1.sum(axis=0)
        dL_dH0 = (A_pc.T @ (dL_dmsg1 @ self.W_pc.T)
                  + A_sib.T @ (dL_dmsg1 @ self.W_sib.T)
                  + dL_dmsg1 @ self.W_self.T)

        dL_dZ0 = dL_dH0 * (1 - H0 ** 2)
        X = cache["X"]
        grads["W_proj"] += X.T @ dL_dZ0
        grads["b_proj"] += dL_dZ0.sum(axis=0)

    def forward_fallback(self, status_batch: np.ndarray):
        F1 = np.tanh(status_batch @ self.W_f1 + self.b_f1)
        out = F1 @ self.W_f2 + self.b_f2
        return out.ravel(), F1

    def backward_fallback(self, status_batch, F1, pred, target, grads):
        n = status_batch.shape[0]
        dL_dout = (2.0 / n) * (pred - target)
        grads["W_f2"] += F1.T @ dL_dout.reshape(-1, 1)
        grads["b_f2"] += np.array([dL_dout.sum()])
        dL_dF1 = np.outer(dL_dout, self.W_f2.ravel())
        dL_dpre = dL_dF1 * (1 - F1 ** 2)
        grads["W_f1"] += status_batch.T @ dL_dpre
        grads["b_f1"] += dL_dpre.sum(axis=0)

    def loss_and_grads(self, cases, status_batch, status_target):
        grads = {k: np.zeros_like(v) for k, v in zip(
            ["W_proj", "b_proj", "W_pc", "W_sib", "W_self", "b_hop", "w_read",
             "b_read", "W_f1", "b_f1", "W_f2", "b_f2"], self.param_list())}
        total_bce = 0.0
        for (X, A_pc, A_sib, _elig_true, y) in cases:
            cache = self.forward_case(X, A_pc, A_sib)
            p = cache["p_contained"]
            bce = -(y * np.log(p) + (1 - y) * np.log(1 - p))
            total_bce += bce
            self.backward_case(cache, y, grads)
        n = len(cases)
        total_bce /= n
        for k in grads:
            if k in ("W_f1", "b_f1", "W_f2", "b_f2"):
                continue
            grads[k] /= n

        pred, F1 = self.forward_fallback(status_batch)
        mse = float(np.mean((pred - status_target) ** 2))
        self.backward_fallback(status_batch, F1, pred, status_target, grads)

        total_loss = total_bce + 0.08 * mse
        for k in ("W_f1", "b_f1", "W_f2", "b_f2"):
            grads[k] *= 0.08
        grad_list = [grads[k] for k in
                     ["W_proj", "b_proj", "W_pc", "W_sib", "W_self", "b_hop",
                      "w_read", "b_read", "W_f1", "b_f1", "W_f2", "b_f2"]]
        return total_loss, grad_list, dict(bce=total_bce, mse=mse)


# ==============================================================================
# SECTION 2 -- MODULE B: RobustHedgeNet
#   "Never one channel: a bounded, unrolled robust fusion of many."
# ==============================================================================

K_CHANNELS = 5
IRLS_STEPS = 3


class RobustHedgeNet:
    """Fixed-length (T=3) differentiable IRLS fusion of K noisy channels,
    followed by a tiny calibration MLP. `alpha` (the redescending weight's
    scale) is trained; the fixed-point recursion itself is not learned, it
    is the architecture -- the same way the Pravda's payment schedule is a
    fixed default, not a matter of per-case judgment."""

    def __init__(self, rng: np.random.Generator):
        self.log_alpha = np.array([0.0])  # alpha = exp(log_alpha), kept positive
        self.W1 = rng.normal(0, 0.4, size=(1, 8))
        self.b1 = np.zeros(8)
        self.W2 = rng.normal(0, 0.4, size=(8, 1))
        self.b2 = np.zeros(1)

    def param_list(self):
        return [self.log_alpha, self.W1, self.b1, self.W2, self.b2]

    def set_param_list(self, plist):
        self.log_alpha, self.W1, self.b1, self.W2, self.b2 = plist

    def forward_irls(self, x: np.ndarray):
        """Unrolled robust fusion with forward-mode sensitivity tracking of
        mu_t w.r.t. the scalar alpha (see file docstring / chapter for the
        derivation -- this is exact, not an approximation)."""
        alpha = float(np.exp(self.log_alpha[0]))
        mu = float(np.mean(x))
        g = 0.0  # d(mu)/d(alpha), accumulated across the unrolled steps
        cache = dict(steps=[])
        for _t in range(IRLS_STEPS):
            r = x - mu  # [K]
            w = np.exp(-alpha * r ** 2)  # [K]
            dw_dalpha = w * (-(r ** 2)) + w * alpha * 2.0 * r * g
            S = w.sum()
            P = (w * x).sum()
            dS = dw_dalpha.sum()
            dP = (dw_dalpha * x).sum()
            mu_new = P / S
            g_new = (dP * S - P * dS) / (S ** 2)
            cache["steps"].append(dict(r=r, w=w, S=S, P=P, mu=mu_new, g=g_new,
                                        mu_prev=mu, g_prev=g))
            mu, g = mu_new, g_new
        cache["mu_final"] = mu
        cache["g_final"] = g  # d(mu_final)/d(alpha), exact via forward accumulation
        cache["alpha"] = alpha
        return cache

    def forward_full(self, x: np.ndarray):
        irls = self.forward_irls(x)
        mu = irls["mu_final"]
        z1 = mu * self.W1[0] + self.b1
        h1 = np.tanh(z1)
        out = float(h1 @ self.W2[:, 0] + self.b2[0])
        return out, irls, h1, mu

    def loss_and_grads_batch(self, X_batch: np.ndarray, targets: np.ndarray):
        n = X_batch.shape[0]
        grads = {k: np.zeros_like(v) for k, v in zip(
            ["log_alpha", "W1", "b1", "W2", "b2"], self.param_list())}
        total = 0.0
        for i in range(n):
            out, irls, h1, mu = self.forward_full(X_batch[i])
            target = targets[i]
            err = out - target
            total += err ** 2
            dL_dout = 2.0 * err / n
            grads["W2"] += (dL_dout * h1).reshape(-1, 1)
            grads["b2"] += np.array([dL_dout])
            dL_dh1 = dL_dout * self.W2[:, 0]
            dL_dz1 = dL_dh1 * (1 - h1 ** 2)
            grads["W1"] += np.outer(np.array([mu]), dL_dz1)
            grads["b1"] += dL_dz1
            dL_dmu = float(dL_dz1 @ self.W1[0])
            # chain into alpha via the exact forward-mode sensitivity g_final,
            # then into log_alpha via d(alpha)/d(log_alpha) = alpha
            dL_dalpha = dL_dmu * irls["g_final"]
            grads["log_alpha"] += np.array([dL_dalpha * irls["alpha"]])
        return total / n, [grads[k] for k in ["log_alpha", "W1", "b1", "W2", "b2"]]

    @staticmethod
    def naive_mean(x: np.ndarray) -> float:
        return float(np.mean(x))


