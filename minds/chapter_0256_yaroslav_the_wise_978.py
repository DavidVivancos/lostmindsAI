# SECTION 3 -- MODULE C: LadderRankNet
#   "A learned order, and how fast it slips once no one enforces it."
# ==============================================================================

class LadderRankNet:
    """Tiny pairwise-ranking scorer over (seniority, city_rank, izgoi_flag)."""

    def __init__(self, rng: np.random.Generator):
        self.W1 = xavier(rng, 3, 8)
        self.b1 = np.zeros(8)
        self.W2 = xavier(rng, 8, 1)
        self.b2 = np.zeros(1)

    def param_list(self):
        return [self.W1, self.b1, self.W2, self.b2]

    def set_param_list(self, plist):
        self.W1, self.b1, self.W2, self.b2 = plist

    def score(self, feats: np.ndarray):
        """feats: [M, 3] -> scores [M], plus cache for backprop."""
        z1 = feats @ self.W1 + self.b1
        h1 = np.tanh(z1)
        s = (h1 @ self.W2 + self.b2).ravel()
        return s, h1

    def loss_and_grads(self, feats: np.ndarray, pairs: list[tuple[int, int]]):
        """`pairs` is a list of (i, j) meaning 'i should outrank j'."""
        s, h1 = self.score(feats)
        grads = {k: np.zeros_like(v) for k, v in zip(
            ["W1", "b1", "W2", "b2"], self.param_list())}
        total = 0.0
        dL_ds = np.zeros_like(s)
        for (i, j) in pairs:
            d = s[j] - s[i]
            total += float(softplus(np.array([d]))[0])
            g = float(sigmoid(np.array([d]))[0])
            dL_ds[i] += -g
            dL_ds[j] += g
        n_pairs = max(1, len(pairs))
        total /= n_pairs
        dL_ds /= n_pairs

        dL_dh1 = np.outer(dL_ds, self.W2.ravel())
        grads["W2"] += h1.T @ dL_ds.reshape(-1, 1)
        grads["b2"] += np.array([dL_ds.sum()])
        dL_dz1 = dL_dh1 * (1 - h1 ** 2)
        grads["W1"] += feats.T @ dL_dz1
        grads["b1"] += dL_dz1.sum(axis=0)
        return total, [grads[k] for k in ["W1", "b1", "W2", "b2"]], s


def make_ladder_case(rng: np.random.Generator, n_cand: int, defection_p: float):
    """Build one succession scenario: n_cand candidates with seniority,
    city rank, and an izgoi (excluded-lineage) flag. True order is
    lexicographic: non-izgoi before izgoi, then seniority desc, then city
    rank desc. Training PAIRS are drawn from that true order but, with
    probability `defection_p` per pair, the pair is flipped -- modelling a
    lower-ranked prince seizing precedence, which is exactly the pattern
    attested repeatedly in Rus' succession politics after 1054 (see
    Sources). defection_p=0 models "the enforcer is alive"; defection_p>0
    models the world after he is not."""
    seniority = rng.permutation(np.arange(n_cand))[:, None].astype(float)
    city_rank = rng.permutation(np.arange(n_cand))[:, None].astype(float) * 0.3 \
        + rng.normal(0, 0.2, size=(n_cand, 1))
    izgoi = (rng.random(size=(n_cand, 1)) < 0.15).astype(float)
    feats = np.concatenate([seniority / max(1, n_cand - 1),
                             city_rank / max(1, n_cand - 1),
                             izgoi], axis=1)

    true_key = list(zip(-izgoi[:, 0], -seniority[:, 0], -city_rank[:, 0], range(n_cand)))
    true_order = [t[3] for t in sorted(true_key)]

    pairs = []
    for a in range(len(true_order)):
        for b in range(a + 1, len(true_order)):
            i, j = true_order[a], true_order[b]  # true: i outranks j
            if rng.random() < defection_p:
                pairs.append((j, i))  # defection: flip the pair
            else:
                pairs.append((i, j))
    return feats, pairs, true_order


