def train_module_a(epochs: int = 180, n_train: int = 220, n_val: int = 60, verbose=True):
    rng = np.random.default_rng(11)
    net = ContainmentFallbackNet(rng)
    train_cases = [make_kinship_case(rng) for _ in range(n_train)]
    val_cases = [make_kinship_case(rng) for _ in range(n_val)]
    n_params = sum(np.asarray(p).size for p in net.param_list())
    opt = Adam(n_params, lr=0.05)

    def flat(net):
        return np.concatenate([np.asarray(p).ravel() for p in net.param_list()])

    def unflat(net, theta):
        shapes = [np.asarray(p).shape for p in net.param_list()]
        parts, idx = [], 0
        for s in shapes:
            size = int(np.prod(s)) if s else 1
            parts.append(theta[idx:idx + size].reshape(s))
            idx += size
        net.set_param_list(parts)

    history = []
    for ep in range(epochs):
        loss, grads, parts = net.loss_and_grads(train_cases, STATUS_TIERS, STATUS_TARGETS)
        theta = flat(net)
        grad_flat = np.concatenate([g.ravel() for g in grads])
        theta = opt.step(theta, grad_flat)
        unflat(net, theta)
        history.append(loss)
        if verbose and (ep % 30 == 0 or ep == epochs - 1):
            print(f"    epoch {ep:3d}  train_loss={loss:.4f}  "
                  f"(bce={parts['bce']:.4f}, mse={parts['mse']:.3f})")

    val_loss, _, val_parts = net.loss_and_grads(val_cases, STATUS_TIERS, STATUS_TARGETS)
    correct = 0
    for (X, A_pc, A_sib, _e, y) in val_cases:
        cache = net.forward_case(X, A_pc, A_sib)
        pred = 1.0 if cache["p_contained"] > 0.5 else 0.0
        correct += int(pred == y)
    val_acc = correct / len(val_cases)
    if verbose:
        print(f"    held-out: bce={val_parts['bce']:.4f}  fallback_mse={val_parts['mse']:.3f}"
              f"  contained-vs-fallback accuracy={val_acc:.1%}")
    return net, history, val_acc, val_parts["mse"]


def train_module_b(epochs: int = 80, n_train: int = 240, verbose=True):
    rng = np.random.default_rng(22)
    net = RobustHedgeNet(rng)
    X = rng.normal(0, 1, size=(n_train, K_CHANNELS))
    corrupt_mask = rng.random(n_train) < 0.5
    corrupt_col = rng.integers(0, K_CHANNELS, size=n_train)
    for i in range(n_train):
        if corrupt_mask[i]:
            X[i, corrupt_col[i]] += rng.choice([-1, 1]) * rng.uniform(3, 8)
    # target: mean of the channels EXCLUDING whichever one was corrupted
    # (for clean rows, this is just the ordinary mean)
    targets = np.zeros(n_train)
    for i in range(n_train):
        if corrupt_mask[i]:
            keep = [c for c in range(K_CHANNELS) if c != corrupt_col[i]]
            targets[i] = X[i, keep].mean()
        else:
            targets[i] = X[i].mean()

    n_params = sum(np.asarray(p).size for p in net.param_list())
    opt = Adam(n_params, lr=0.06)

    def flat(net):
        return np.concatenate([np.asarray(p).ravel() for p in net.param_list()])

    def unflat(net, theta):
        shapes = [np.asarray(p).shape for p in net.param_list()]
        parts, idx = [], 0
        for s in shapes:
            size = int(np.prod(s)) if s else 1
            parts.append(theta[idx:idx + size].reshape(s))
            idx += size
        net.set_param_list(parts)

    history = []
    for ep in range(epochs):
        loss, grads = net.loss_and_grads_batch(X, targets)
        theta = flat(net)
        theta = opt.step(theta, np.concatenate([g.ravel() for g in grads]))
        unflat(net, theta)
        history.append(loss)
        if verbose and (ep % 20 == 0 or ep == epochs - 1):
            print(f"    epoch {ep:3d}  train_mse={loss:.4f}  alpha={np.exp(net.log_alpha[0]):.3f}")
    return net, history


def train_module_c(defection_p: float, epochs: int = 150, n_scenarios: int = 40, verbose=True):
    rng = np.random.default_rng(33 + int(defection_p * 1000))
    net = LadderRankNet(rng)
    scenarios = [make_ladder_case(rng, rng.integers(3, 6), defection_p) for _ in range(n_scenarios)]

    n_params = sum(np.asarray(p).size for p in net.param_list())
    opt = Adam(n_params, lr=0.08)

    def flat(net):
        return np.concatenate([np.asarray(p).ravel() for p in net.param_list()])

    def unflat(net, theta):
        shapes = [np.asarray(p).shape for p in net.param_list()]
        parts, idx = [], 0
        for s in shapes:
            size = int(np.prod(s)) if s else 1
            parts.append(theta[idx:idx + size].reshape(s))
            idx += size
        net.set_param_list(parts)

    history = []
    for ep in range(epochs):
        ep_loss = 0.0
        grad_accum = None
        for feats, pairs, _true in scenarios:
            loss, grads, _s = net.loss_and_grads(feats, pairs)
            ep_loss += loss
            if grad_accum is None:
                grad_accum = [g.copy() for g in grads]
            else:
                for a, g in zip(grad_accum, grads):
                    a += g
        ep_loss /= len(scenarios)
        grad_flat = np.concatenate([g.ravel() / len(scenarios) for g in grad_accum])
        theta = flat(net)
        theta = opt.step(theta, grad_flat)
        unflat(net, theta)
        history.append(ep_loss)
        if verbose and (ep % 30 == 0 or ep == epochs - 1):
            print(f"    epoch {ep:3d}  train_pairwise_loss={ep_loss:.4f}")
    return net, history


def rank_accuracy_against_truth(net: LadderRankNet, rng: np.random.Generator, n_eval=200):
    """Evaluate a trained scorer against the TRUE (noise-free) intended
    order on freshly sampled scenarios -- never the noisy training labels."""
    correct, total = 0, 0
    for _ in range(n_eval):
        feats, _pairs, true_order = make_ladder_case(rng, rng.integers(3, 6), defection_p=0.0)
        s, _h = net.score(feats)
        pred_order = list(np.argsort(-s))
        for a in range(len(true_order)):
            for b in range(a + 1, len(true_order)):
                i, j = true_order[a], true_order[b]
                total += 1
                if pred_order.index(i) < pred_order.index(j):
                    correct += 1
    return correct / total


