# SECTION 4 -- combined flat-parameter vector, for ONE gradient check across
#              all three modules at once.
# ==============================================================================

class CombinedModel:
    """Wraps all three modules and exposes one flat parameter vector and one
    scalar loss over a fixed evaluation batch, purely so that a single
    finite-difference check can certify the whole architecture at once."""

    def __init__(self, seed: int = RNG_SEED):
        rng = np.random.default_rng(seed)
        self.A = ContainmentFallbackNet(rng)
        self.B = RobustHedgeNet(rng)
        self.C = LadderRankNet(rng)
        self._build_fixed_eval_batch(rng)

    def _build_fixed_eval_batch(self, rng):
        self.eval_cases = [make_kinship_case(rng) for _ in range(6)]
        self.eval_status = STATUS_TIERS.copy()
        self.eval_status_target = STATUS_TARGETS.copy()
        self.eval_B_x = rng.normal(0, 1, size=(6, K_CHANNELS))
        self.eval_B_x[:, 0] += rng.normal(0, 4, size=6)  # corrupt one channel
        self.eval_B_target = self.eval_B_x[:, 1:].mean(axis=1)  # target = clean mean
        self.eval_C_feats, self.eval_C_pairs, _ = make_ladder_case(rng, 5, defection_p=0.2)

    def flat_params(self) -> np.ndarray:
        parts = []
        for p in self.A.param_list() + self.B.param_list() + self.C.param_list():
            parts.append(np.asarray(p).ravel())
        return np.concatenate(parts)

    def _shapes(self):
        return [np.asarray(p).shape for p in
                self.A.param_list() + self.B.param_list() + self.C.param_list()]

    def load_flat(self, theta: np.ndarray):
        shapes = self._shapes()
        parts = []
        idx = 0
        for shp in shapes:
            size = int(np.prod(shp)) if shp else 1
            parts.append(theta[idx:idx + size].reshape(shp))
            idx += size
        nA = len(self.A.param_list())
        nB = len(self.B.param_list())
        self.A.set_param_list(parts[:nA])
        self.B.set_param_list(parts[nA:nA + nB])
        self.C.set_param_list(parts[nA + nB:])

    def loss_and_grad(self):
        lossA, gradsA, _ = self.A.loss_and_grads(self.eval_cases, self.eval_status,
                                                   self.eval_status_target)
        lossB, gradsB = self.B.loss_and_grads_batch(self.eval_B_x, self.eval_B_target)
        lossC, gradsC, _ = self.C.loss_and_grads(self.eval_C_feats, self.eval_C_pairs)
        total = lossA + 0.5 * lossB + lossC
        grad_flat = np.concatenate(
            [g.ravel() for g in gradsA] + [0.5 * g.ravel() for g in gradsB]
            + [g.ravel() for g in gradsC])
        return total, grad_flat


def run_full_gradient_check(eps: float = 1e-5, tol: float = 2e-4, verbose: bool = True):
    """Central-difference numeric gradient vs. the hand-derived analytic
    gradient, over EVERY parameter of ALL three modules, evaluated on one
    fixed batch. This is the mandatory check for this file."""
    model = CombinedModel()
    theta0 = model.flat_params()
    _, analytic = model.loss_and_grad()

    numeric = np.zeros_like(theta0)
    for i in range(theta0.shape[0]):
        tp = theta0.copy()
        tp[i] += eps
        model.load_flat(tp)
        lp, _ = model.loss_and_grad()
        tm = theta0.copy()
        tm[i] -= eps
        model.load_flat(tm)
        lm, _ = model.loss_and_grad()
        numeric[i] = (lp - lm) / (2 * eps)
    model.load_flat(theta0)

    denom = np.maximum(np.abs(analytic), np.abs(numeric)) + 1e-8
    rel_err = np.abs(analytic - numeric) / denom
    max_err = float(rel_err.max())
    mean_err = float(rel_err.mean())
    passed = max_err < tol
    if verbose:
        print(f"  [grad-check] {theta0.shape[0]} parameters across modules A+B+C")
        print(f"  [grad-check] max relative error  = {max_err:.3e}")
        print(f"  [grad-check] mean relative error = {mean_err:.3e}")
        print(f"  [grad-check] PASS (< {tol:.0e})" if passed else
              f"  [grad-check] FAIL (>= {tol:.0e})")
    return passed, max_err, mean_err


