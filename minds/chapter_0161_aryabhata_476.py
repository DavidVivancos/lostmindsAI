# =============================================================================
# PART I.  THE PULVERIZER  (kuttaka)  -- exact integer number theory
# =============================================================================
# Aryabhata's most distinctive algorithm.  "Kuttaka" = to pulverise: reduce a
# hard congruence to an easier one with smaller coefficients, recurse, then
# back-substitute.  It is the extended Euclidean algorithm.  We keep the
# "Valli" (the ladder/creeper of quotients) because Aryabhata's own method is
# organised around that column of quotients.

def kuttaka(a: int, b: int):
    """Extended Euclidean 'pulverizer'.

    Returns (g, x, y, valli) with  a*x + b*y = g = gcd(a, b),
    where 'valli' is the list of quotients produced while grinding a, b down
    (Aryabhata's ladder).  Iterative, so it never overflows the stack.
    """
    valli = []
    old_r, r = int(a), int(b)
    old_s, s = 1, 0          # coefficients of 'a'
    old_t, t = 0, 1          # coefficients of 'b'
    while r != 0:
        q = old_r // r
        valli.append(q)
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
        old_t, t = t, old_t - q * t
    g = old_r
    # sign convention: make gcd non-negative
    if g < 0:
        g, old_s, old_t = -g, -old_s, -old_t
    return g, old_s, old_t, valli


def solve_linear_diophantine(a: int, b: int, c: int):
    """Solve a*x + b*y = c in integers, or return None if unsolvable.

    Returns one particular solution (x0, y0) plus the step (dx, dy): the full
    family is (x0 + k*dx, y0 + k*dy) for integer k.
    """
    g, x, y, _ = kuttaka(a, b)
    if c % g != 0:
        return None
    factor = c // g
    x0, y0 = x * factor, y * factor
    dx, dy = b // g, -a // g
    return (x0, y0, dx, dy)


def modinv(a: int, m: int):
    """Multiplicative inverse of a modulo m via the pulverizer (or None)."""
    g, x, _, _ = kuttaka(a % m, m)
    if g != 1:
        return None
    return x % m


def crt_kuttaka(r1: int, m1: int, r2: int, m2: int):
    """Chinese Remainder via kuttaka: smallest t>=0 with
    t == r1 (mod m1) and t == r2 (mod m2).  Returns (t, lcm) or None.

    This is the 'conjunction epoch' problem of Indian astronomy: given two
    bodies whose cycles have lengths m1, m2 and whose current phases are r1,
    r2, find WHEN the joint phase repeats -- pure prediction by calculation.
    """
    g, p, q, _ = kuttaka(m1, m2)
    if (r2 - r1) % g != 0:
        return None
    lcm = m1 // g * m2
    # t = r1 + m1 * k, where k solves m1*k == (r2 - r1) (mod m2)
    k = ((r2 - r1) // g * p) % (m2 // g)
    t = (r1 + m1 * k) % lcm
    return t, lcm


# =============================================================================
# PART II.  PLACE VALUE  (positional recurrence)
# =============================================================================
# "sthanat sthanam dasagunam syat" -- from place to place, each is ten times
# the preceding (Ganitapada v.2).  Evaluating a number from its digits is
# Horner's rule: a recurrence  v <- v*base + digit.  Aryabhata's own numeral
# notation alternated squared/non-squared places (base-100 groups); we keep
# the general positional recurrence, the essential idea.

def horner_encode(digits, base: int = 10) -> int:
    """Most-significant-digit-first list -> integer, by the positional
    recurrence v <- v*base + d  (the 'tenfold place' rule)."""
    v = 0
    for d in digits:
        v = v * base + int(d)
    return v


def horner_decode(v: int, base: int = 10):
    """Integer -> most-significant-first digit list (inverse recurrence)."""
    v = int(v)
    if v == 0:
        return [0]
    out = []
    while v > 0:
        out.append(v % base)
        v //= base
    return out[::-1]


# =============================================================================
# PART III.  THE JYA ENGINE  (learnable oscillator bank)
# =============================================================================
# A rotational linear state-space model.  State s in R^{2K} is K planar
# oscillators.  Each oscillator k advances by a scaled rotation
#
#     A_k = rho_k * [[ cos th_k, -sin th_k],
#                    [ sin th_k,  cos th_k]] ,   rho_k = exp(lr_k)
#
# The autonomous roll  s[t] = A s[t-1]  with readout  y[t] = C s[t] + b  is
# EXACTLY Aryabhata's generative move: a whole (quasi-)periodic trajectory is
# regenerated from a seed state s0 and the local rule A.  Learning the rule =
# learning the frequencies (th_k) that make the world calculable.
#
# Parameters (all learnable):
#   th   : (K,)     angular frequency of each oscillator
#   lr   : (K,)     log-radius; rho = exp(lr)  (rho ~ 1 => pure oscillation)
#   C    : (D, 2K)  linear readout from state to observation
#   b    : (D,)     output bias
#   s0   : (2K,)    initial (seed) state
# =============================================================================

class JyaEngine:
    def __init__(self, K: int, D: int = 1, seed: int = 476):
        self.K, self.D = K, D
        rng = np.random.default_rng(seed)
        # Spread initial frequencies across (0, pi); small so rollouts are smooth.
        self.th = rng.uniform(0.05, 1.2, size=K)
        self.lr = np.zeros(K)                       # rho = 1 at init (undamped)
        self.C = rng.normal(0, 0.3, size=(D, 2 * K))
        self.b = np.zeros(D)
        self.s0 = rng.normal(0, 1.0, size=2 * K)

    # ---- parameter <-> flat vector helpers (used by the gradient checker) ----
    def get_params(self):
        return {"th": self.th, "lr": self.lr, "C": self.C, "b": self.b, "s0": self.s0}

    def _block(self, k):
        """Return the 2x2 transition block A_k and its pieces."""
        c, s = np.cos(self.th[k]), np.sin(self.th[k])
        rho = np.exp(self.lr[k])
        R = np.array([[c, -s], [s, c]])
        return rho * R, rho, c, s, R

    def _A(self):
        """Assemble the (2K x 2K) block-diagonal transition matrix."""
        K = self.K
        A = np.zeros((2 * K, 2 * K))
        for k in range(K):
            Ak, *_ = self._block(k)
            A[2 * k:2 * k + 2, 2 * k:2 * k + 2] = Ak
        return A

    # ------------------------------------------------------------------ forward
    def forward(self, T: int):
        """Roll the recurrence for T steps. Returns (Y, cache).
        Y has shape (T, D): Y[t] = C s[t+1] + b for t = 0..T-1 (states s1..sT).
        """
        A = self._A()
        S = np.zeros((T + 1, 2 * self.K))
        S[0] = self.s0
        for t in range(1, T + 1):
            S[t] = A @ S[t - 1]
        Y = S[1:] @ self.C.T + self.b          # (T, D)
        cache = (A, S, T)
        return Y, cache

    # ------------------------------------------------------- loss + backward
    def loss_and_grad(self, target, weight=None):
        """MSE loss between the rolled output and `target` (T, D).

        `weight` (T,) optionally down-weights steps (e.g. 0 outside the warm-up
        window so we fit only what we've 'observed' and truly EXTRAPOLATE the
        rest).  Returns (loss, grads dict) with grads for every parameter,
        derived by hand (reverse-mode BPTT).
        """
        target = np.asarray(target, dtype=float)
        if target.ndim == 1:
            target = target[:, None]
        T = target.shape[0]
        if weight is None:
            weight = np.ones(T)
        Y, (A, S, _) = self.forward(T)

        diff = Y - target                               # (T, D)
        wdiff = diff * weight[:, None]                  # w * (y - t)
        denom = weight.sum() * self.D
        loss = np.sum(wdiff * diff) / denom             # sum(w*(y-t)^2)/denom

        # dL/dY  (consistent with the weighted loss above)
        dY = 2.0 * wdiff / denom                        # (T, D)

        # Grads for readout
        gC = dY.T @ S[1:]                               # (D, 2K)
        gb = dY.sum(axis=0)                             # (D,)

        # Backprop through the recurrence to get dL/dA and dL/ds0.
        gA = np.zeros_like(A)
        delta = np.zeros(2 * self.K)                    # dL/ds_{t}, carried back
        AT = A.T
        CT = self.C.T
        for t in range(T, 0, -1):
            # gradient into state s[t] : from this step's output + future states
            delta = CT @ dY[t - 1] + AT @ delta
            gA += np.outer(delta, S[t - 1])
        gs0 = AT @ delta                                # dL/ds0 via s1 = A s0
        # NOTE: after the loop, `delta` holds dL/ds_1's contribution already
        # folded; the outer accumulation used s[t-1] correctly for each t.

        # Map dL/dA (only diagonal 2x2 blocks are real parameters) to th, lr.
        gth = np.zeros(self.K)
        glr = np.zeros(self.K)
        for k in range(self.K):
            Ak, rho, c, s, R = self._block(k)
            Gk = gA[2 * k:2 * k + 2, 2 * k:2 * k + 2]
            # dA_k/dth = rho * [[-s,-c],[c,-s]]
            dth = rho * np.array([[-s, -c], [c, -s]])
            # dA_k/dlr = A_k  (rho = exp(lr) => drho/dlr = rho)
            gth[k] = np.sum(Gk * dth)
            glr[k] = np.sum(Gk * Ak)

        grads = {"th": gth, "lr": glr, "C": gC, "b": gb, "s0": gs0}
        return loss, grads


