# PART IV.  MANDATORY FINITE-DIFFERENCE GRADIENT CHECK
# =============================================================================

def grad_check(verbose=True):
    """Central finite differences vs analytic grads on every parameter."""
    K, D, T = 3, 2, 18
    net = JyaEngine(K=K, D=D, seed=11)
    # slightly damp so the roll doesn't blow up during the check
    net.lr = RNG.normal(-0.02, 0.02, size=K)
    target = RNG.normal(0, 1, size=(T, D))
    weight = RNG.uniform(0.3, 1.0, size=T)

    loss0, grads = net.loss_and_grad(target, weight)
    h = 1e-6
    max_rel = 0.0
    worst = None
    for name in ["th", "lr", "C", "b", "s0"]:
        P = net.get_params()[name]
        flat = P.ravel()
        g_an = grads[name].ravel()
        for i in range(flat.size):
            orig = flat[i]
            flat[i] = orig + h
            lp, _ = net.loss_and_grad(target, weight)
            flat[i] = orig - h
            lm, _ = net.loss_and_grad(target, weight)
            flat[i] = orig
            g_fd = (lp - lm) / (2 * h)
            denom = max(1.0, abs(g_fd) + abs(g_an[i]))
            rel = abs(g_fd - g_an[i]) / denom
            if rel > max_rel:
                max_rel, worst = rel, f"{name}[{i}]"
    if verbose:
        print(f"  gradient check   : max relative error = {max_rel:.3e}  "
              f"(worst: {worst})")
        print(f"                     {'PASS' if max_rel < 1e-5 else 'FAIL'} "
              f"(threshold 1e-5)")
    return max_rel


