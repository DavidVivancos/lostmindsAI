# PART VII.  CONJUNCTION: kuttaka predicts, the JyaEngine confirms
# =============================================================================

def conjunction_demo(verbose=True):
    """Two bodies with integer periods and phase offsets.  The pulverizer
    predicts the epoch of joint-phase recurrence; the oscillator engine is
    rolled forward to CONFIRM they coincide there. Number theory + harmonic
    generation, unified -- the whole architecture in miniature.
    """
    m1, m2 = 12, 20                       # cycle lengths (steps)
    r1, r2 = 5, 9                          # current phases within each cycle
    res = crt_kuttaka(r1, m1, r2, m2)
    ok_bruteforce = None
    predicted = None
    if res is not None:
        predicted, lcm = res
        # brute-force verify
        found = None
        for t in range(lcm):
            if t % m1 == r1 and t % m2 == r2:
                found = t
                break
        ok_bruteforce = (found == predicted)

    # Cross-check with the engine: two pure oscillators whose phases at step t
    # are (t mod m). They "coincide" (both at phase 0) at t = lcm(m1,m2).
    g, _, _, _ = kuttaka(m1, m2)
    lcm = m1 // g * m2
    net = JyaEngine(K=2, D=2, seed=7)
    net.lr = np.zeros(2)
    net.th = np.array([2 * np.pi / m1, 2 * np.pi / m2])
    # read each oscillator's x-coordinate
    net.C = np.array([[1., 0., 0., 0.], [0., 0., 1., 0.]])
    net.b = np.zeros(2)
    net.s0 = np.array([1., 0., 1., 0.])   # both start at phase 0
    Y, _ = net.forward(lcm)
    # both back to +1 (phase 0) exactly at t = lcm
    at_lcm = np.allclose(Y[lcm - 1], [1., 1.], atol=1e-6)

    if verbose:
        print("  conjunction (pulverizer predicts, oscillators confirm):")
        print(f"      t == {r1} (mod {m1}) and t == {r2} (mod {m2})")
        print(f"      kuttaka epoch  = {predicted}   brute-force match: {ok_bruteforce}")
        print(f"      lcm({m1},{m2}) = {lcm}; oscillators realign at lcm: {at_lcm}")
    return ok_bruteforce, at_lcm


