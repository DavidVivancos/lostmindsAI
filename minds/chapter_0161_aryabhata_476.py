# PART V.  A TINY ADAM OPTIMISER (from scratch) + TRAINING DEMO
# =============================================================================

class Adam:
    def __init__(self, params, lr=0.02, b1=0.9, b2=0.999, eps=1e-8):
        self.lr, self.b1, self.b2, self.eps = lr, b1, b2, eps
        self.m = {k: np.zeros_like(v) for k, v in params.items()}
        self.v = {k: np.zeros_like(v) for k, v in params.items()}
        self.t = 0

    def step(self, params, grads):
        self.t += 1
        for k in params:
            self.m[k] = self.b1 * self.m[k] + (1 - self.b1) * grads[k]
            self.v[k] = self.b2 * self.v[k] + (1 - self.b2) * grads[k] ** 2
            mhat = self.m[k] / (1 - self.b1 ** self.t)
            vhat = self.v[k] / (1 - self.b2 ** self.t)
            params[k] -= self.lr * mhat / (np.sqrt(vhat) + self.eps)


def train_demo(verbose=True):
    """Learn a multi-periodic 'planetary longitude' from a short warm-up
    window, then EXTRAPOLATE. This is Aryabhata's core act: fit the rule on a
    little, regenerate the rest by calculation.
    """
    # --- synthesise a target: three commensurate-ish 'planets' ---------------
    T_total = 160
    T_warm = 90                    # only these steps are 'observed'
    tt = np.arange(1, T_total + 1)
    true_freqs = [0.18, 0.41, 0.77]
    amps = [1.0, 0.5, 0.3]
    phases = [0.4, 1.1, 2.0]
    signal = sum(a * np.sin(f * tt + p) for a, f, p in zip(amps, true_freqs, phases))
    signal = signal[:, None]                         # (T,1)

    weight = np.zeros(T_total)
    weight[:T_warm] = 1.0                            # fit warm-up only

    net = JyaEngine(K=4, D=1, seed=476)              # 4 oscillators (>3 needed)
    net.lr = np.full(net.K, -0.001)                 # near-undamped
    opt = Adam(net.get_params(), lr=0.03)

    params = net.get_params()
    hist = []
    n_iter = 5000
    for it in range(n_iter):
        loss, grads = net.loss_and_grad(signal, weight)
        # cosine-style learning-rate decay for a stable final fit
        opt.lr = 0.03 * (0.5 * (1 + np.cos(np.pi * it / n_iter)))
        opt.step(params, grads)
        # keep oscillators from decaying/exploding: clamp log-radius gently
        params["lr"][:] = np.clip(params["lr"], -0.05, 0.02)
        if it % 1000 == 0 or it == n_iter - 1:
            hist.append((it, loss))

    Y, _ = net.forward(T_total)
    warm_mse = np.mean((Y[:T_warm, 0] - signal[:T_warm, 0]) ** 2)
    extrap_mse = np.mean((Y[T_warm:, 0] - signal[T_warm:, 0]) ** 2)

    # Rank the K oscillators by how much output energy they carry, so we read
    # off the frequencies the model actually relies on (K=4 fits 3 tones, so a
    # spare oscillator carries ~0 energy).
    freqs = np.abs(net.th) % np.pi
    energy = np.array([np.hypot(net.C[0, 2 * k], net.C[0, 2 * k + 1])
                       for k in range(net.K)])
    order = np.argsort(-energy)
    ranked = [(round(float(freqs[k]), 3), round(float(energy[k]), 3)) for k in order]

    if verbose:
        print(f"  training (fit on {T_warm}/{T_total} steps, extrapolate rest):")
        for it, l in hist:
            print(f"      iter {it:5d}   warm-up loss = {l:.6e}")
        print(f"  warm-up   MSE    : {warm_mse:.3e}")
        print(f"  EXTRAPOLATION MSE: {extrap_mse:.3e}   "
              f"(future predicted by rolling the learned rule)")
        print(f"  true frequencies : {sorted(true_freqs)}")
        print(f"  learned (freq, readout-energy), ranked:")
        for f, e in ranked:
            print(f"                     freq={f:.3f}  energy={e:.3f}")
    return warm_mse, extrap_mse


