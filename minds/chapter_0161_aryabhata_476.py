# His historical 24 R-sines (radius R = 3438), Ganitapada v.12.

ARYABHATA_RSINES = [225, 449, 671, 890, 1105, 1315, 1520, 1719, 1910, 2093,
                    2267, 2431, 2585, 2728, 2859, 2978, 3084, 3177, 3256,
                    3321, 3372, 3409, 3431, 3438]


def aryabhata_sine_table(verbose=True):
    """Regenerate the 24 R-sines by the SAME local rule Aryabhata used:
    the second sine-difference is proportional to the sine, i.e. the exact
    oscillator recurrence  S[n+1] = 2 cos(eps) S[n] - S[n-1].
    """
    R = 3438.0
    eps = 225.0 / R                    # step of 3 deg 45' in radians (= 225'/R)
    two_cos = 2.0 * np.cos(eps)

    S = np.zeros(25)
    S[0] = 0.0
    S[1] = R * np.sin(eps)             # seed = first half-chord
    for n in range(1, 24):
        S[n + 1] = two_cos * S[n] - S[n - 1]
    regen = [int(v) for v in np.round(S[1:])]

    true_vals = np.array([R * np.sin(n * eps) for n in range(1, 25)])
    err_vs_true = float(np.max(np.abs(S[1:] - true_vals)))
    err_vs_hist = int(np.max(np.abs(np.array(regen) - np.array(ARYABHATA_RSINES))))

    if verbose:
        print("  sine table regenerated from the 2nd-difference recurrence:")
        print(f"      first 8 regen : {regen[:8]}")
        print(f"      first 8 hist. : {ARYABHATA_RSINES[:8]}")
        print(f"      last  value   : regen={regen[-1]} hist={ARYABHATA_RSINES[-1]} (=R)")
        print(f"      max |regen - exact R*sin| = {err_vs_true:.2e}")
        print(f"      max |regen - Aryabhata's integers| = {err_vs_hist} unit(s)")
    return err_vs_true, err_vs_hist


