    print(f"  [training] final held-out accuracy = {final_te:.3f}")
    print()

    # SELF-TEST 3: aggregate balance moved toward the 17-series
    a_mean = model.forward(Xtr)["a"].mean(axis=(0, 1))
    print("  [balance prior] aggregate manifest natures vs canonical:")
