from __future__ import annotations
import numpy as np

RNG = np.random.default_rng(721)   # seeded with Jabir's traditional birth year

NATURES = ("hot", "cold", "wet", "dry")
K = len(NATURES)                    # K = 4 natures

CANONICAL = np.array([1.0, 3.0, 5.0, 8.0])   # the 17-series
CANONICAL = CANONICAL / CANONICAL.sum()       # normalised: the "perfect balance"


# -----------------------------------------------------------------------------
#  Numerically-stable primitives
# -----------------------------------------------------------------------------
def softmax_last(z: np.ndarray) -> np.ndarray:
    """Softmax over the LAST axis. Turns each nature-vector into a simplex point."""
    z = z - z.max(axis=-1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=-1, keepdims=True)


def col_softmax(M: np.ndarray) -> np.ndarray:
    """Column-wise softmax over axis=-2 for a stack of matrices (..., K, K).
    Each COLUMN sums to 1 -> column-stochastic -> a mass-conserving balance."""
    M = M - M.max(axis=-2, keepdims=True)
    e = np.exp(M)
    return e / e.sum(axis=-2, keepdims=True)


def kl(p: np.ndarray, q: np.ndarray, eps: float = 1e-12) -> float:
    p = np.clip(p, eps, 1.0); q = np.clip(q, eps, 1.0)
    return float(np.sum(p * (np.log(p) - np.log(q))))


# =============================================================================
#  THE MIZAN BALANCE ENGINE  (H parallel conserved vessels)
# =============================================================================
class MizanBalanceEngine:
    def __init__(self, d_in, n_classes, n_vessels=8, lam=0.05, scale=0.5):
        self.d_in = d_in
        self.C = n_classes
        self.H = n_vessels
        self.lam = lam
        H = n_vessels
        # Encoder: one direction-set per vessel -> H manifest simplices.
        self.W_enc = RNG.normal(0, scale, size=(H, K, d_in))
        self.b_enc = np.zeros((H, K))
        # One balance seed per vessel. T = col_softmax(M), T_inv = col_softmax(-M).
        self.M = RNG.normal(0, scale, size=(H, K, K))
        # Readout over the joined [manifest ; hidden] state of all vessels.
        self.W_out = RNG.normal(0, scale, size=(n_classes, 2 * H * K))
        self.b_out = np.zeros(n_classes)

    def get_params(self):
        return {"W_enc": self.W_enc, "b_enc": self.b_enc, "M": self.M,
                "W_out": self.W_out, "b_out": self.b_out}

    # ------------------------------------------------------------------ FORWARD
    def forward(self, X):
        N = X.shape[0]
        # 1) Encode raw surface -> H manifest simplices (N,H,K).
        z = np.einsum("hkd,nd->nhk", self.W_enc, X) + self.b_enc
        a = softmax_last(z)                                   # manifest natures
        # 2) THE BALANCE: redistribute mass per vessel (column-stochastic).
        T = col_softmax(self.M)                              # (H,K,K)
        mp = np.einsum("hkj,nhj->nhk", T, a)                 # manifest', mass=1
        # 3) INVERSION: hidden face = inverse balance of the manifest.
        T_inv = col_softmax(-self.M)                         # (H,K,K)
        b = np.einsum("hkj,nhj->nhk", T_inv, mp)             # hidden natures
        # 4) Join both faces of every vessel and read out.
        f = np.concatenate([mp.reshape(N, -1), b.reshape(N, -1)], axis=1)
        logits = f @ self.W_out.T + self.b_out
        yhat = softmax_last(logits)
        return dict(X=X, a=a, T=T, mp=mp, T_inv=T_inv, b=b, f=f,
                    logits=logits, yhat=yhat, N=N)

    def loss(self, X, y):
        c = self.forward(X)
        yhat, N = c["yhat"], c["N"]
        ce = -np.mean(np.log(yhat[np.arange(N), y] + 1e-12))
        a_mean = c["a"].mean(axis=(0, 1))                    # aggregate balance
        mizan_pen = kl(a_mean, CANONICAL)
        c.update(y=y, ce=ce, mizan_pen=mizan_pen)
        return ce + self.lam * mizan_pen, c

    # ----------------------------------------------------------------- BACKWARD
    def _dz_from_da(self, a, da):
        """Backprop through the per-vessel softmax over natures."""
        return a * (da - (da * a).sum(axis=-1, keepdims=True))

    def backward(self, c):
        X, a, T, mp, T_inv = c["X"], c["a"], c["T"], c["mp"], c["T_inv"]
        yhat, y, N, H = c["yhat"], c["y"], c["N"], self.H

        Y = np.zeros_like(yhat); Y[np.arange(N), y] = 1.0
        dlogits = (yhat - Y) / N
        dW_out = dlogits.T @ c["f"]
        db_out = dlogits.sum(axis=0)
        df = dlogits @ self.W_out                            # (N, 2HK)
        dmp = df[:, :H * K].reshape(N, H, K).copy()
        db = df[:, H * K:].reshape(N, H, K).copy()

        # hidden inversion:  b = T_inv @ mp  (per vessel)
        dmp += np.einsum("nhk,hkj->nhj", db, T_inv)
        dT_inv = np.einsum("nhk,nhj->hkj", db, mp)

        # the balance:  mp = T @ a  (per vessel)
        da = np.einsum("nhk,hkj->nhj", dmp, T)
        dT = np.einsum("nhk,nhj->hkj", dmp, a)

        # 17-series prior on the aggregate manifest
        a_mean = a.mean(axis=(0, 1))
        dmizan = np.log(np.clip(a_mean, 1e-12, 1.0)) - np.log(CANONICAL) + 1.0
        da += self.lam * dmizan[None, None, :] / (N * H)

        dz = self._dz_from_da(a, da)
        dW_enc = np.einsum("nhk,nd->hkd", dz, X)
        db_enc = dz.sum(axis=0)

        # M generates BOTH T and T_inv -> accumulate both paths, per vessel.
        sT = (dT * T).sum(axis=-2, keepdims=True)
        dM_from_T = T * (dT - sT)
        sU = (dT_inv * T_inv).sum(axis=-2, keepdims=True)
        dU = T_inv * (dT_inv - sU)
        dM = dM_from_T - dU

        return {"W_enc": dW_enc, "b_enc": db_enc, "M": dM,
                "W_out": dW_out, "b_out": db_out}

    def grad_input(self, X, y_target):
        _, c = self.loss(X, y_target)
        a, T, T_inv = c["a"], c["T"], c["T_inv"]
        yhat, N, H = c["yhat"], c["N"], self.H
        Y = np.zeros_like(yhat); Y[np.arange(N), y_target] = 1.0
        dlogits = (yhat - Y) / N
        df = dlogits @ self.W_out
        dmp = df[:, :H * K].reshape(N, H, K).copy()
        db = df[:, H * K:].reshape(N, H, K).copy()
        dmp += np.einsum("nhk,hkj->nhj", db, T_inv)
        da = np.einsum("nhk,hkj->nhj", dmp, T)
        a_mean = a.mean(axis=(0, 1))
        dmizan = np.log(np.clip(a_mean, 1e-12, 1.0)) - np.log(CANONICAL) + 1.0
        da += self.lam * dmizan[None, None, :] / (N * H)
        dz = self._dz_from_da(a, da)
        return np.einsum("nhk,hkd->nd", dz, self.W_enc)

    def predict(self, X):
        return self.forward(X)["yhat"].argmax(axis=1)

    def natures_of(self, X):
        c = self.forward(X)
        return c["mp"], c["b"]


# =============================================================================
#  GRADIENT CHECK  (mandatory)
# =============================================================================
def gradient_check(model, X, y, eps=1e-6):
    _, c = model.loss(X, y)
    analytic = model.backward(c)
    worst, report = 0.0, []
    for name, P in model.get_params().items():
        g_num = np.zeros_like(P)
        it = np.nditer(P, flags=["multi_index"])
        while not it.finished:
            idx = it.multi_index
            orig = P[idx]
            P[idx] = orig + eps; lp, _ = model.loss(X, y)
            P[idx] = orig - eps; lm, _ = model.loss(X, y)
            P[idx] = orig
            g_num[idx] = (lp - lm) / (2 * eps)
            it.iternext()
        num = np.linalg.norm(analytic[name] - g_num)
        den = np.linalg.norm(analytic[name]) + np.linalg.norm(g_num) + 1e-12
        rel = num / den
        worst = max(worst, rel); report.append((name, rel))
    return worst, report


# =============================================================================
#  SYNTHETIC "SUBSTANCES" — a Jabirian generative process
# =============================================================================
def make_world(n_classes=4, d_in=16, seed=1):
    """Fix ONE world: its manifestation transport, its surface embedding, and its
    hidden class recipes. Train and test are then sampled from the SAME world."""
    rng = np.random.default_rng(seed)
    T_true = col_softmax(rng.normal(0, 1.0, size=(K, K)))   # the world's balance
    R = rng.normal(0, 1.0, size=(d_in, K))                  # manifest -> surface
    # Distinct hidden recipes: each class is dominated by a different nature,
    # so the classes occupy well-separated regions of the simplex.
    base = np.full((n_classes, K), 0.1)
    for c in range(n_classes):
        base[c, c % K] += 0.9
    base = base / base.sum(axis=1, keepdims=True)
    return dict(T_true=T_true, R=R, base=base, d_in=d_in, n_classes=n_classes)


def sample_substances(world, n_per_class, noise=0.10, seed=0, mean=None, std=None):
    """Draw substances from a fixed world. Optionally reuse train-set feature
    statistics (mean/std) so the test set is standardised the same way."""
    rng = np.random.default_rng(seed)
    T_true, R, base = world["T_true"], world["R"], world["base"]
    X, y = [], []
    for c in range(world["n_classes"]):
        for _ in range(n_per_class):
            h = rng.dirichlet(base[c] * 30.0 + 0.5)   # hidden recipe (on simplex)
            manifest = T_true @ h                     # manifestation (mass kept)
            x = R @ manifest + noise * rng.normal(size=world["d_in"])
            X.append(x); y.append(c)
    X = np.asarray(X); y = np.asarray(y)
    if mean is None:
        mean, std = X.mean(0), X.std(0) + 1e-8
    X = (X - mean) / std
    perm = rng.permutation(len(y))
    return X[perm], y[perm], mean, std


# =============================================================================
#  TRAINING LOOP  (full-batch Adam, from scratch)
# =============================================================================
def train(model, Xtr, ytr, Xte, yte, epochs=600, lr=0.03, weight_decay=2e-4):
    params = model.get_params()
    m = {k: np.zeros_like(v) for k, v in params.items()}
    v = {k: np.zeros_like(v) for k, v in params.items()}
    b1, b2, eps = 0.9, 0.999, 1e-8
    history = []
    for t in range(1, epochs + 1):
        loss, c = model.loss(Xtr, ytr)
        g = model.backward(c)
        for k in params:
            m[k] = b1 * m[k] + (1 - b1) * g[k]
            v[k] = b2 * v[k] + (1 - b2) * g[k] ** 2
            mhat = m[k] / (1 - b1 ** t); vhat = v[k] / (1 - b2 ** t)
            step = lr * mhat / (np.sqrt(vhat) + eps)
            # decoupled weight decay on weight matrices (not the biases)
            if k in ("W_enc", "W_out", "M"):
                step += lr * weight_decay * params[k]
            params[k] -= step
        if t % 75 == 0 or t == 1:
            tr = (model.predict(Xtr) == ytr).mean()
            te = (model.predict(Xte) == yte).mean()
            history.append((t, loss, tr, te))
    return history


# =============================================================================
#  TAKWIN — "assemble a being to a target balance under the creator's control"
# =============================================================================
def takwin(model, d_in, target_class, steps=400, lr=0.3):
    x = 0.01 * RNG.normal(size=(1, d_in))
    tgt = np.array([target_class])
    for _ in range(steps):
        x = x - lr * model.grad_input(x, tgt)
    pred = int(model.predict(x)[0])
    prob = float(model.forward(x)["yhat"][0, target_class])
    mp, hidden = model.natures_of(x)
    return pred, prob, mp[0].mean(0), hidden[0].mean(0)   # mean over vessels


