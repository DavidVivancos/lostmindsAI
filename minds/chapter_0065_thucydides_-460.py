# 7. MAIN
# =============================================================================

def main():
    print("=" * 78)
    print("THE PROPHASIS FORECASTER  --  a Thucydidean cognitive architecture")
    print("=" * 78)

    world = ThucydideanWorld(obs_dim=12, n_pretext=6, seed=11)

    # ---- (a) gradient check on a tiny instance: correctness before everything ----
    print("\n[1] FINITE-DIFFERENCE GRADIENT CHECK")
    small = ProphasisForecaster(obs_dim=12, hidden=8, mem=6, seed=3)
    Xg, Pg, Yg = world.sample_sequence(T=7)
    worst, report = gradient_check(small, Xg, Pg, Yg)
    for k, v in report.items():
        print(f"    {k:>3} : max rel err {v:.2e}")
    print(f"    WORST relative error = {worst:.2e}  "
          f"({'PASS' if worst < 1e-4 else 'FAIL'}, tol 1e-4)")
    assert worst < 1e-4, "Gradient check failed -- backprop is wrong."

    # ---- (b) build data ----
    print("\n[2] BUILDING THE PELOPONNESIAN CORPUS")
    train_batch = world.sample_batch(n=140, T=18)
    val_batch = world.sample_batch(n=40, T=18)
    base_acc, maj = majority_baseline(val_batch)
    names = {DETER: "DETER", ESCALATE: "ESCALATE", SUBMIT: "SUBMIT"}
    print(f"    train sequences: {len(train_batch)}   val sequences: {len(val_batch)}")
    print(f"    chronicler's baseline (always '{names[maj]}'): {base_acc:.3f}")

    # ---- (c) train ----
    print("\n[3] TRAINING (forecast from invariant motives, not from pretext)")
    model = ProphasisForecaster(obs_dim=12, hidden=16, mem=12, seed=1)
    train(model, train_batch, val_batch, epochs=60, lr=0.05)
    final_val = accuracy(model, val_batch)

    # ---- (d) Thucydidean self-tests ----
    print("\n[4] SELF-TESTS")
    print(f"    (i)  forecast beats baseline : {final_val:.3f} vs {base_acc:.3f}  "
          f"({'PASS' if final_val > base_acc + 0.08 else 'FAIL'})")

    c_true, c_pre = prophasis_test(model, world)
    print(f"    (ii) prophasis test          : corr(motive code, TRUE cause)   = {c_true:+.3f}")
    print(f"                                   corr(motive code, PRETEXT noise) = {c_pre:+.3f}")
    print(f"                                   ({'PASS' if abs(c_true) > abs(c_pre) + 0.15 else 'FAIL'}"
          f": loads on cause, not pretext)")

    a_gate, a_nogate = melian_test(model, world)
    print(f"    (iii) Melian power law       : high-asym acc WITH gate    = {a_gate:.3f}")
    print(f"                                   high-asym acc gate ABLATED = {a_nogate:.3f}")
    print(f"                                   ({'PASS' if a_gate > a_nogate + 0.02 else 'FAIL'}"
          f": power gate carries weight)")

    print("\n[5] SUMMARY")
    ok = (worst < 1e-4 and final_val > base_acc + 0.08
          and abs(c_true) > abs(c_pre) + 0.15 and a_gate > a_nogate + 0.02)
    print(f"    gradient check ... {'PASS' if worst < 1e-4 else 'FAIL'}")
    print(f"    forecasting   ... {'PASS' if final_val > base_acc + 0.08 else 'FAIL'}")
    print(f"    prophasis     ... {'PASS' if abs(c_true) > abs(c_pre) + 0.15 else 'FAIL'}")
    print(f"    melian        ... {'PASS' if a_gate > a_nogate + 0.02 else 'FAIL'}")
    print(f"    >>> ALL THUCYDIDEAN TESTS {'PASSED' if ok else 'FAILED'} <<<")
    print("=" * 78)
    return ok


if __name__ == "__main__":
    main()
