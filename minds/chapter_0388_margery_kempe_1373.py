def xavier(rng, fan_in, fan_out, gain=1.0):
    lim = gain * np.sqrt(6.0 / (fan_in + fan_out))
    return rng.uniform(-lim, lim, (fan_in, fan_out))


class ACNParams:
    """All trainable weights, held as autodiff leaves in one flat dict.

    Grouping matters here. `body_*` is reachable ONLY from the witness loss;
    if the gradient check ever finds a path from the report loss into those
    weights, the non-forgeability guarantee is broken and the run aborts.
    """

    def __init__(self, d_hidden=24, d_affect=8, d_code=4, n_slots=4, seed=1438):
        rng = np.random.default_rng(seed)
        self.H, self.A, self.C, self.M = d_hidden, d_affect, d_code, n_slots
        d_in = D_VOL + d_affect + N_PANEL + d_hidden  # vol | affect | votes | ledger read
        P = {}

        # --- The body: involuntary channel (gradient-severed downstream) -----
        P["body_W"] = Node(xavier(rng, D_INV, d_affect))
        P["body_b"] = Node(np.zeros((1, d_affect)))
        P["body_U"] = Node(xavier(rng, d_affect, d_affect, 0.4))   # bodily persistence
        P["witness_W"] = Node(xavier(rng, d_affect, 1))            # predicts emission cost
        P["witness_b"] = Node(np.zeros((1, 1)))

        # --- The creature: recurrent inner state ------------------------------
        P["Wz"] = Node(xavier(rng, d_in, d_hidden));  P["Uz"] = Node(xavier(rng, d_hidden, d_hidden))
        P["bz"] = Node(np.zeros((1, d_hidden)))
        P["Wn"] = Node(xavier(rng, d_in, d_hidden));  P["Un"] = Node(xavier(rng, d_hidden, d_hidden))
        P["bn"] = Node(np.zeros((1, d_hidden)))

        # --- Three separate credence sources, never merged before the sum -----
        P["W_self"] = Node(xavier(rng, d_hidden, 3, 0.5))   # the voluntary report
        P["b_self"] = Node(np.zeros((1, 3)))
        P["W_wit"] = Node(xavier(rng, d_affect, 3))         # reads the tears
        P["b_wit"] = Node(np.zeros((1, 3)))
        P["W_pan"] = Node(xavier(rng, N_PANEL, 3))          # reads the examiners
        P["b_pan"] = Node(np.zeros((1, 3)))

        # --- Dissent reconstruction: the panel is never averaged --------------
        P["W_dis"] = Node(xavier(rng, d_hidden, N_PANEL))
        P["b_dis"] = Node(np.zeros((1, N_PANEL)))

        # --- Provenance ledger query -----------------------------------------
        P["W_q"] = Node(xavier(rng, d_hidden, d_hidden))

        # --- The de Worde head: compression that must keep the tail -----------
        n_tail = D_INV + 1          # involuntary means + mean cost
        n_common = D_VOL            # the tidy, articulate part
        P["Wc1"] = Node(xavier(rng, d_hidden, d_code));  P["bc1"] = Node(np.zeros((1, d_code)))
        P["Wc2"] = Node(xavier(rng, d_code, n_tail + n_common))
        P["bc2"] = Node(np.zeros((1, n_tail + n_common)))

        self.P = P
        self.n_tail, self.n_common = n_tail, n_common

    # Weights the report loss must never touch.
    BODY_KEYS = ("body_W", "body_b", "body_U")

    def zero_grad(self):
        for p in self.P.values():
            p.grad = np.zeros_like(p.data)

    def items(self):
        return self.P.items()

    def __getitem__(self, k):
        return self.P[k]


