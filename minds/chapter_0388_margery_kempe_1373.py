def run_self_tests(net, corpus, history):
    results = []

    def check(name, ok, detail):
        results.append((name, bool(ok), detail))
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}\n         {detail}")

    # --- T1: the trap is real ------------------------------------------------
    fb_acc, pred, lab, polish_gap = corpus.fluency_baseline_accuracy(6000)
    # Confusion between the two classes that matter, among a generous baseline
    # that is even handed the true prototypes.
    mask = (lab == DIVINE) | (lab == COUNTERFEIT)
    dv_cf = float((pred[mask] == lab[mask]).mean())
    check("T1 the articulate channel cannot tell grace from forgery",
          fb_acc < 0.72 and dv_cf < 0.62 and polish_gap > 0.05,
          f"a prototype-perfect reader of the polished account scores {fb_acc:.1%} "
          f"overall and only {dv_cf:.1%} between DIVINE and COUNTERFEIT (chance "
          f"is 50%), while the counterfeit sits {polish_gap:+.3f} higher on the "
          f"articulacy axis — grading on fluency prefers the forgery")

    # --- T2: training converged ---------------------------------------------
    early, late = np.mean(history[:20]), np.mean(history[-20:])
    check("T2 optimisation reduced the objective",
          late < early * 0.75,
          f"mean loss {early:.4f} (first 20 steps) -> {late:.4f} (last 20), "
          f"a {100*(1-late/early):.1f}% reduction")

    # --- T3: the protocol beats the baseline --------------------------------
    acc, per_class, used = evaluate(net, corpus, n_seq=384, seq_len=8, seed=2024)
    check("T3 attestation outperforms articulacy",
          acc > fb_acc + 0.15,
          f"held-out accuracy {acc:.1%} vs fluency baseline {fb_acc:.1%}  "
          f"(REPROVED {per_class['REPROVED']:.1%} / UNRESOLVED "
          f"{per_class['UNRESOLVED']:.1%} / ATTESTED {per_class['ATTESTED']:.1%})")

    # --- T4: when account and body disagree, the body wins -------------------
    acc_nowit, _, _ = evaluate(net, corpus, n_seq=384, seq_len=8, seed=2024, mode="no_witness")
    # Identical polished account in both rows; only the body differs.
    warm = conflict_probe(net, corpus, account_cls=COUNTERFEIT, body_cls=DIVINE)
    cold = conflict_probe(net, corpus, account_cls=DIVINE, body_cls=COUNTERFEIT)
    check("T4 the verdict follows the body, not the account",
          (warm - cold) > 0.45 and cold < 0.20,
          f"holding the articulate account fixed and swapping only the bodily "
          f"signal moves the attestation rate from {cold:.1%} to {warm:.1%}; a "
          f"flawless account with no tears behind it is attested {cold:.1%} of "
          f"the time. Deleting the bodily evidence entirely costs "
          f"{acc - acc_nowit:.1%} accuracy ({acc:.1%} -> {acc_nowit:.1%})")

    # --- T5: the third answer survives --------------------------------------
    check("T5 UNRESOLVED is a live destination, not a hedge",
          0.10 < used["UNRESOLVED"] < 0.55 and per_class["UNRESOLVED"] > 0.20,
          f"the network routes {used['UNRESOLVED']:.1%} of episodes to UNRESOLVED "
          f"and recovers {per_class['UNRESOLVED']:.1%} of the genuinely "
          f"undecidable ones instead of forcing a verdict")

    # --- T6: dissent is preserved, not averaged -----------------------------
    vol, inv, cost, votes, labels = corpus.batch(128, 6)
    P = net.p
    h = Node(np.zeros((128, P.H))); a = Node(np.zeros((128, P.A))); slots = []
    errs_model, errs_mean = [], []
    for t in range(6):
        h, a, lg, _, dis, _ = net.step(vol[t], inv[t], votes[t], h, a, slots)
        v = votes[t]
        errs_model.append(np.mean((dis.data - v) ** 2))
        errs_mean.append(np.mean((v.mean(1, keepdims=True) - v) ** 2))
        pr = np.exp(lg.data - lg.data.max(1, keepdims=True)); pr /= pr.sum(1, keepdims=True)
        slots.append((h.data.copy(), h.data.copy(), pr[:, DIVINE:DIVINE + 1].copy()))
        if len(slots) > P.M:
            slots.pop(0)
    em, ea = float(np.mean(errs_model)), float(np.mean(errs_mean))
    check("T6 disagreement is reconstructed, not collapsed",
          em < ea * 0.85,
          f"per-examiner reconstruction MSE {em:.4f} vs {ea:.4f} for the "
          f"consensus-scalar summary — a split panel stays visibly split")

    # --- T7: provenance outranks similarity ---------------------------------
    B, H = 16, P.H
    key = np.random.default_rng(3).normal(0, 1, (B, H))
    hq = Node(key.copy())                       # a perfect content match
    hot = net.ledger_read(hq, [(key, np.ones((B, H)), np.full((B, 1), 0.95)),
                               (key, np.zeros((B, H)), np.full((B, 1), 0.95))])
    cold = net.ledger_read(hq, [(key, np.ones((B, H)), np.full((B, 1), 0.001)),
                                (key, np.zeros((B, H)), np.full((B, 1), 0.95))])
    check("T7 an unattested memory cannot become evidence",
          hot.data.mean() > cold.data.mean() + 0.15,
          f"identical content, different provenance: attested slot contributes "
          f"{hot.data.mean():.3f}, unattested slot {cold.data.mean():.3f}")

    # --- T8: the de Worde head keeps the tail -------------------------------
    _, parts, _ = net.forward(vol, inv, cost, votes, labels)
    nt = net.p.n_tail
    tail_err = float(np.mean((parts["recon"][:, :nt] - parts["target"][:, :nt]) ** 2))
    tail_var = float(np.var(parts["target"][:, :nt]))
    tail_r2 = 1.0 - tail_err / (tail_var + 1e-9)
    check("T8 compression preserves what a fluent summary would drop",
          tail_r2 > 0.35,
          f"the {nt}-dimensional bodily tail is recovered from a "
          f"{net.p.C}-unit code with R^2 = {tail_r2:.3f}; a summary that kept "
          f"only the articulate mean would score near zero here")

    # --- T9: gradients still finite after training --------------------------
    finite = all(np.isfinite(p.data).all() for p in net.p.P.values())
    check("T9 parameters remain finite and usable",
          finite,
          f"{len(net.p.P)} tensors, "
          f"{sum(p.data.size for p in net.p.P.values())} scalars, all finite")

    return results


