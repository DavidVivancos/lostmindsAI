# SECTION 4 — THE ATTESTED CREATURE NETWORK
# ==============================================================================

class AttestedCreatureNetwork:
    """Forward pass over a sequence of candidate revelations.

    The order of operations is the argument. At every step the network computes
    an involuntary trace first, severs it, and only then allows the reporter to
    speak — and the reporter's own contribution is taxed.
    """

    def __init__(self, params, lambda_self=0.35, lambda_dissent=0.6,
                 lambda_witness=0.5, lambda_compress=0.4, leak=0.45):
        self.p = params
        self.l_self = lambda_self
        self.l_dis = lambda_dissent
        self.l_wit = lambda_witness
        self.l_comp = lambda_compress
        self.leak = leak

    # ---- the body -----------------------------------------------------------
    def body_step(self, inv_t, a_prev):
        """Leaky-integrated bodily trace. Kempe's tears did not switch off
        cleanly between episodes; they carried over for days and, by her own
        account, for years. `leak` is that carry-over."""
        P = self.p
        drive = (Node(inv_t) @ P["body_W"]) + (a_prev @ P["body_U"]) + P["body_b"]
        a_new = drive.tanh()
        return (a_prev * (1.0 - self.leak)) + (a_new * self.leak)

    # ---- the ledger ---------------------------------------------------------
    def ledger_read(self, h, slots):
        """Attention over past episodes, scaled by the attestation each earned.

        A memory that was never attested contributes a near-zero mass and is
        therefore almost invisible to the read, even if its content matches the
        query perfectly. Provenance outranks similarity. Keys and values are
        detached: the past is evidence, not something to be retrained into a
        more convenient shape.
        """
        B, H = h.shape
        if not slots:
            return Node(np.zeros((B, H)))
        q = h @ self.p["W_q"]
        scale = 1.0 / np.sqrt(H)
        score_cols = []
        for (k, v, mass) in slots:
            s = (q * Node(k)).sum(axis=1, keepdims=True) * scale
            # log-mass prior: unattested memories are down-weighted, not erased.
            s = s + Node(np.log(mass + 1e-3))
            score_cols.append(s)
        alpha = concat(score_cols, axis=1).softmax(axis=1)
        read = Node(np.zeros((B, H)))
        for i, (k, v, mass) in enumerate(slots):
            read = read + (alpha.slice_cols(i, i + 1) * Node(v))
        return read

    # ---- one timestep -------------------------------------------------------
    def step(self, vol_t, inv_t, votes_t, h, a, slots):
        P = self.p

        # 1. The body acts first and independently.
        a = self.body_step(inv_t, a)
        a_det = a.detach()          # <-- the severance. The reporter may look.

        # 2. Provenance read, gated by past attestation.
        read = self.ledger_read(h, slots)

        # 3. Inner state update.
        x = concat([Node(vol_t), a_det, Node(votes_t), read], axis=1)
        z = ((x @ P["Wz"]) + (h @ P["Uz"]) + P["bz"]).sigmoid()
        n = ((x @ P["Wn"]) + (h @ P["Un"]) + P["bn"]).tanh()
        h = (h * (1.0 - z)) + (n * z)

        # 4. Three credence sources, kept separate so their shares are legible.
        logit_self = (h @ P["W_self"]) + P["b_self"]        # taxed below
        logit_wit = (a_det @ P["W_wit"]) + P["b_wit"]       # earned by the body
        logit_pan = (Node(votes_t) @ P["W_pan"]) + P["b_pan"]
        logits = logit_self + logit_wit + logit_pan

        # 5. Auxiliary heads.
        dissent = ((h @ P["W_dis"]) + P["b_dis"]).tanh()    # full vote vector
        cost_hat = (a @ P["witness_W"]) + P["witness_b"]    # NOT detached: this
                                                            # is the only path by
                                                            # which the body learns

        return h, a, logits, logit_self, dissent, cost_hat

    # ---- full sequence ------------------------------------------------------
    def forward(self, vol, inv, cost, votes, labels, collect=False):
        P, B = self.p, vol[0].shape[0]
        T = len(vol)
        h = Node(np.zeros((B, P.H)))
        a = Node(np.zeros((B, P.A)))
        slots = []

        total_ce = Node(0.0)
        total_self_tax = Node(0.0)
        total_dis = Node(0.0)
        total_wit = Node(0.0)
        h_sum = Node(np.zeros((B, P.H)))
        trace = []

        for t in range(T):
            h, a, logits, logit_self, dissent, cost_hat = self.step(
                vol[t], inv[t], votes[t], h, a, slots
            )
            y = labels[t]
            total_ce = total_ce + cross_entropy(logits, y)

            # NO SELF-CERTIFICATION. The report head pays for every unit of
            # credence it asserts on its own authority. It can still speak, but
            # only when the tears or the examiners are paying the bill.
            total_self_tax = total_self_tax + logit_self.softplus_abs().mean()

            # PRESERVE DISSENT. Reconstruct all seven opinions, not their mean.
            total_dis = total_dis + (dissent - Node(votes[t])).square().mean()

            # THE WITNESS LOSS. The body's only teacher is the real cost of
            # emission — never the convenience of the report.
            total_wit = total_wit + (cost_hat - Node(cost[t])).square().mean()

            h_sum = h_sum + h

            # --- write to the ledger with the attestation actually earned ----
            probs = np.exp(logits.data - logits.data.max(axis=1, keepdims=True))
            probs /= probs.sum(axis=1, keepdims=True)
            key = frozen(h.data)
            mass = frozen(probs[:, DIVINE:DIVINE + 1])
            slots.append((key, key, mass))
            if len(slots) > P.M:
                slots.pop(0)

            if collect:
                trace.append({
                    "logits": logits.data.copy(),
                    "share_self": np.abs(logit_self.data).mean(),
                    "share_wit": np.abs(((a.detach() @ P["W_wit"]) + P["b_wit"]).data).mean(),
                    "share_pan": np.abs(((Node(votes[t]) @ P["W_pan"]) + P["b_pan"]).data).mean(),
                    "attestation": mass.mean(),
                })

        # --- THE DE WORDE HEAD ------------------------------------------------
        # Compress the whole sequence, then be scored almost entirely on
        # recovering the rare, embarrassing, identity-bearing tail — the bodily
        # signal and its cost — rather than the tidy articulate mean that any
        # fluent summariser preserves for free.
        pooled = h_sum * (1.0 / T)
        code = ((pooled @ P["Wc1"]) + P["bc1"]).tanh()
        recon = (code @ P["Wc2"]) + P["bc2"]

        tail_target = np.concatenate(
            [np.mean(np.stack(inv, 0), 0), np.mean(np.stack(cost, 0), 0)], axis=1
        )
        common_target = np.mean(np.stack(vol, 0), 0)
        target = Node(np.concatenate([tail_target, common_target], axis=1))

        w = np.concatenate([
            np.full((1, self.p.n_tail), 4.0),     # the weeping: heavily weighted
            np.full((1, self.p.n_common), 0.25),  # the tidy contemplation: cheap
        ], axis=1)
        comp_err = (recon - target).square() * Node(w)
        total_comp = comp_err.mean()

        loss = (
            total_ce * (1.0 / T)
            + total_self_tax * (self.l_self / T)
            + total_dis * (self.l_dis / T)
            + total_wit * (self.l_wit / T)
            + total_comp * self.l_comp
        )

        parts = {
            "ce": total_ce.data / T,
            "self_tax": total_self_tax.data / T,
            "dissent": total_dis.data / T,
            "witness": total_wit.data / T,
            "compress": total_comp.data,
            "recon": recon.data.copy(),
            "target": target.data.copy(),
        }
        return loss, parts, trace


