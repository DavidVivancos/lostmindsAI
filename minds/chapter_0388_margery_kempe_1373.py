# SECTION 1 — A MINIMAL REVERSE-MODE AUTODIFF ENGINE
# ==============================================================================
# Written from scratch so that the architecture below can express one thing that
# ordinary frameworks make easy to get silently wrong: a channel that is read by
# a downstream module but is NEVER updated by that module's error signal. In
# Kempe's terms, the reporter may look at the tears but may not learn to produce
# them. `Node.detach()` is the operation that enforces it, and the gradient
# check in Section 8 proves the severance actually holds.
# ==============================================================================


# ------------------------------------------------------------------------------
# THE DETACH TAPE
# ------------------------------------------------------------------------------
# A subtlety that turns out to be the whole point. Finite differences measure the
# TRUE total derivative of the loss, including the influence that flows through
# detached values. The analytic gradient deliberately excludes those routes —
# that exclusion IS the severance. So a naive FD check reports a mismatch on
# exactly the parameters the architecture is protecting, and reports it as a bug.
#
# The fix is to hold the severed record fixed while probing, which is precisely
# what an audit does: you re-examine the reasoning against a FIXED record of what
# was testified and what was attested, not against a record that helpfully
# rewrites itself to justify the new reasoning. Kempe's examiners could not
# revise her tears to fit their verdict either.
#
#   mode "record"  — run once, cache every detached value in call order.
#   mode "replay"  — reuse the cached values, ignoring recomputation.
#   mode "off"     — ordinary training behaviour.
# ------------------------------------------------------------------------------
_TAPE = {"mode": "off", "cache": [], "idx": 0}


def tape_record():
    _TAPE["mode"], _TAPE["cache"], _TAPE["idx"] = "record", [], 0


def tape_replay():
    _TAPE["mode"], _TAPE["idx"] = "replay", 0


def tape_off():
    _TAPE["mode"], _TAPE["cache"], _TAPE["idx"] = "off", [], 0


def frozen(arr):
    """Pass an array through the detach tape.

    Used for every value that leaves the differentiable graph: the involuntary
    trace read by the reporter, and each ledger write with the attestation mass
    it earned.
    """
    if _TAPE["mode"] == "record":
        v = np.array(arr, dtype=np.float64, copy=True)
        _TAPE["cache"].append(v)
        return v
    if _TAPE["mode"] == "replay":
        v = _TAPE["cache"][_TAPE["idx"]]
        _TAPE["idx"] += 1
        return v
    return np.array(arr, dtype=np.float64, copy=True)


def _unbroadcast(grad, shape):
    """Sum a gradient back down to `shape`, undoing NumPy broadcasting.

    If a (3,) bias was broadcast across a (32,3) batch during the forward pass,
    its gradient arrives as (32,3) and must be summed over axis 0 to match.
    """
    if grad.shape == shape:
        return grad
    # Collapse any leading axes that broadcasting introduced.
    while grad.ndim > len(shape):
        grad = grad.sum(axis=0)
    # Collapse any axis that was size-1 in the original and expanded.
    for axis, size in enumerate(shape):
        if size == 1 and grad.shape[axis] != 1:
            grad = grad.sum(axis=axis, keepdims=True)
    return grad.reshape(shape)


class Node:
    """A value on the tape: an array plus the recipe for its gradient.

    `_backward` closes over the parents and writes into their `.grad`.
    `_parents` lets us topologically sort the graph when backward() is called.
    """

    __slots__ = ("data", "grad", "_backward", "_parents", "_op")

    def __init__(self, data, parents=(), op="leaf"):
        self.data = np.asarray(data, dtype=np.float64)
        self.grad = np.zeros_like(self.data)
        self._backward = lambda: None
        self._parents = tuple(parents)
        self._op = op

    # ---- graph construction helpers ------------------------------------------
    @property
    def shape(self):
        return self.data.shape

    def __repr__(self):
        return f"Node(shape={self.data.shape}, op={self._op})"

    # ---- core arithmetic -----------------------------------------------------
    def __add__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        out = Node(self.data + other.data, (self, other), "add")

        def _bw():
            self.grad += _unbroadcast(out.grad, self.data.shape)
            other.grad += _unbroadcast(out.grad, other.data.shape)

        out._backward = _bw
        return out

    def __mul__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        out = Node(self.data * other.data, (self, other), "mul")

        def _bw():
            self.grad += _unbroadcast(out.grad * other.data, self.data.shape)
            other.grad += _unbroadcast(out.grad * self.data, other.data.shape)

        out._backward = _bw
        return out

    def __neg__(self):
        return self * -1.0

    def __sub__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        return self + (-other)

    def __radd__(self, other):
        return self + other

    def __rmul__(self, other):
        return self * other

    def __rsub__(self, other):
        return (-self) + other

    def matmul(self, other):
        out = Node(self.data @ other.data, (self, other), "matmul")

        def _bw():
            self.grad += out.grad @ other.data.T
            other.grad += self.data.T @ out.grad

        out._backward = _bw
        return out

    def __matmul__(self, other):
        return self.matmul(other)

    # ---- nonlinearities ------------------------------------------------------
    def tanh(self):
        t = np.tanh(self.data)
        out = Node(t, (self,), "tanh")

        def _bw():
            self.grad += out.grad * (1.0 - t * t)

        out._backward = _bw
        return out

    def sigmoid(self):
        s = 1.0 / (1.0 + np.exp(-np.clip(self.data, -60, 60)))
        out = Node(s, (self,), "sigmoid")

        def _bw():
            self.grad += out.grad * s * (1.0 - s)

        out._backward = _bw
        return out

    def square(self):
        out = Node(self.data ** 2, (self,), "square")

        def _bw():
            self.grad += out.grad * 2.0 * self.data

        out._backward = _bw
        return out

    def softplus_abs(self):
        """A smooth stand-in for |x|, used for the no-self-certification penalty.

        The L1 penalty on the self-asserted credence term needs a subgradient at
        zero that finite differences can verify; sqrt(x^2 + eps) is smooth and
        agrees with |x| everywhere it matters.
        """
        v = np.sqrt(self.data ** 2 + 1e-8)
        out = Node(v, (self,), "smooth_abs")

        def _bw():
            self.grad += out.grad * (self.data / v)

        out._backward = _bw
        return out

    # ---- reductions and shaping ---------------------------------------------
    def sum(self, axis=None, keepdims=False):
        out = Node(self.data.sum(axis=axis, keepdims=keepdims), (self,), "sum")

        def _bw():
            g = out.grad
            if axis is not None and not keepdims:
                g = np.expand_dims(g, axis)
            self.grad += np.broadcast_to(g, self.data.shape).copy()

        out._backward = _bw
        return out

    def mean(self, axis=None, keepdims=False):
        n = self.data.size if axis is None else self.data.shape[axis]
        return self.sum(axis=axis, keepdims=keepdims) * (1.0 / n)

    def log_softmax(self, axis=-1):
        x = self.data
        m = x.max(axis=axis, keepdims=True)
        shifted = x - m
        lse = np.log(np.exp(shifted).sum(axis=axis, keepdims=True))
        ls = shifted - lse
        out = Node(ls, (self,), "log_softmax")
        probs = np.exp(ls)

        def _bw():
            self.grad += out.grad - probs * out.grad.sum(axis=axis, keepdims=True)

        out._backward = _bw
        return out

    def softmax(self, axis=-1):
        x = self.data
        e = np.exp(x - x.max(axis=axis, keepdims=True))
        p = e / e.sum(axis=axis, keepdims=True)
        out = Node(p, (self,), "softmax")

        def _bw():
            # Jacobian-vector product for softmax, done row-wise without
            # materialising the full Jacobian.
            dot = (out.grad * p).sum(axis=axis, keepdims=True)
            self.grad += p * (out.grad - dot)

        out._backward = _bw
        return out

    def slice_cols(self, start, stop):
        out = Node(self.data[:, start:stop], (self,), "slice")

        def _bw():
            g = np.zeros_like(self.data)
            g[:, start:stop] = out.grad
            self.grad += g

        out._backward = _bw
        return out

    def gather_rows_cols(self, idx):
        """Pick element idx[i] from row i — used for cross-entropy."""
        rows = np.arange(self.data.shape[0])
        out = Node(self.data[rows, idx], (self,), "gather")

        def _bw():
            g = np.zeros_like(self.data)
            g[rows, idx] += out.grad
            self.grad += g

        out._backward = _bw
        return out

    # ---- THE OPERATION THIS WHOLE ARCHITECTURE TURNS ON -----------------------
    def detach(self):
        """Return the same values with the tape cut.

        Downstream modules can READ this value; no error signal from them will
        ever reach the parameters that produced it. This is how the involuntary
        body channel stays involuntary: the report head sees the tears and
        cannot learn to counterfeit them.
        """
        return Node(frozen(self.data), (), "detached")

    # ---- backward pass -------------------------------------------------------
    def backward(self):
        topo, seen = [], set()

        def build(v):
            if id(v) in seen:
                return
            seen.add(id(v))
            for p in v._parents:
                build(p)
            topo.append(v)

        build(self)
        self.grad = np.ones_like(self.data)
        for node in reversed(topo):
            node._backward()


def concat(nodes, axis=1):
    """Concatenate Nodes along `axis`, tracking gradients back to each piece."""
    out = Node(np.concatenate([n.data for n in nodes], axis=axis), tuple(nodes), "concat")
    sizes = [n.data.shape[axis] for n in nodes]

    def _bw():
        offset = 0
        for n, s in zip(nodes, sizes):
            sl = [slice(None)] * out.grad.ndim
            sl[axis] = slice(offset, offset + s)
            n.grad += out.grad[tuple(sl)]
            offset += s

    out._backward = _bw
    return out


def cross_entropy(logits, targets):
    """Mean negative log-likelihood over a batch. `targets` are int class ids."""
    ls = logits.log_softmax(axis=-1)
    picked = ls.gather_rows_cols(targets)
    return -picked.mean()


