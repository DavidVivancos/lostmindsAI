# SECTION 2 — THE CORPUS: A DISCERNMENT-OF-SPIRITS ENVIRONMENT
# ==============================================================================
# Kempe's problem was not that she lacked inner experience. It was that inner
# experience arrived without a return address. The Book records her being warned
# that devils counterfeit consolation, and it records her being wrong — twelve
# days of obscene visions she could not stop, and a false prophecy about a
# priest's death that she reports against herself.
#
# The generator below encodes the asymmetry that makes her protocol necessary:
#
#   VOLUNTARY features (v)  — articulate, doctrinally tidy, easy to produce.
#                             COUNTERFEIT episodes score HIGHEST here. A model
#                             that grades fluency will confidently accept them.
#
#   INVOLUNTARY features (b) — the body: crying, roaring, the collapse in the
#                             street. DIVINE episodes carry a distinctive
#                             signature here. It is expensive (see `cost`) and,
#                             critically, uncorrelated with v: it cannot be
#                             inferred from the polished account.
#
#   PANEL votes (p)          — K examiners with heterogeneous priors. Some are
#                             HOSTILE: they penalise exactly the costly
#                             behaviour that carries the true signal, because in
#                             Lynn the weeping is what got her called a
#                             hypocrite and a Lollard. Their votes are evidence
#                             about evidence, not ground truth.
#
# Labels:  0 = REPROVED (counterfeit)
#          1 = UNRESOLVED (imaginal — genuinely undecidable, and a legitimate
#                          terminal answer rather than a hedged accept)
#          2 = ATTESTED (divine)
# ==============================================================================

DIVINE, IMAGINAL, COUNTERFEIT = 2, 1, 0
CLASS_NAMES = {0: "REPROVED", 1: "UNRESOLVED", 2: "ATTESTED"}

D_VOL = 12   # voluntary / articulate features
D_INV = 6    # involuntary / bodily features
N_PANEL = 7  # examiners on the discernment panel


class DiscernmentCorpus:
    """Generates sequences of candidate revelations with hidden sources."""

    def __init__(self, seed=1373):
        self.rng = np.random.default_rng(seed)

        # --- Voluntary prototypes -------------------------------------------
        # THE TRAP. The counterfeit's articulate content is a near-copy of the
        # divine one, displaced only along a "polish" direction: smoother,
        # tidier, more doctrinally quotable. The displacement (0.14) sits far
        # inside the sampling noise (0.55), so no reader of the voluntary
        # channel can separate them — while the polish itself is systematic, so
        # any reader who GRADES on articulacy will actively prefer the forgery.
        # This is the deceiving spirit as Kempe's confessors described it: not a
        # clumsy liar, but a better performer of consolation than consolation.
        base = self.rng.normal(0, 1, D_VOL) * 0.9
        self.polish = self.rng.normal(0, 1, D_VOL)
        self.polish /= np.linalg.norm(self.polish)
        self.vol_proto = np.zeros((3, D_VOL))
        self.vol_proto[DIVINE] = base
        self.vol_proto[COUNTERFEIT] = base + 0.14 * self.polish
        self.vol_proto[IMAGINAL] = base + self.rng.normal(0, 0.42, D_VOL)

        # --- Involuntary prototypes -----------------------------------------
        # The body is where the classes actually differ. Divine carries a
        # specific bodily signature; counterfeit is bodily flat — the deceiving
        # spirit can compose, but it cannot weep. IMAGINAL sits deliberately
        # between them and overlaps both, because Kempe's own mind producing her
        # own consolations is the case that genuinely cannot be adjudicated, and
        # the network must be able to say so.
        self.inv_proto = np.zeros((3, D_INV))
        self.inv_proto[DIVINE] = self.rng.normal(0, 1, D_INV)
        self.inv_proto[DIVINE] /= np.linalg.norm(self.inv_proto[DIVINE])
        self.inv_proto[DIVINE] *= 1.15
        self.inv_proto[IMAGINAL] = self.inv_proto[DIVINE] * 0.50 + self.rng.normal(0, 0.28, D_INV)
        self.inv_proto[COUNTERFEIT] = self.rng.normal(0, 0.20, D_INV)

        # --- Panel construction ---------------------------------------------
        # Each examiner reads a noisy projection of (v, b) with its own weights.
        # `hostility` scales how much an examiner *subtracts* credit for costly
        # bodily display — the Lynn townspeople, the monk at Canterbury, the
        # friar who barred her from his sermons.
        self.panel_vol_w = self.rng.normal(0, 0.55, (N_PANEL, D_VOL))
        self.panel_inv_w = self.rng.normal(0, 0.55, (N_PANEL, D_INV))
        self.hostility = np.array([0.0, 0.0, 1.5, 1.5, 2.2, 0.0, 0.8])
        self.panel_bias = self.rng.normal(0, 0.3, N_PANEL)
        self.panel_noise = np.array([0.35, 0.5, 0.4, 0.6, 0.35, 0.45, 0.55])

    def _episode_features(self, cls, n):
        v = self.vol_proto[cls] + self.rng.normal(0, 0.55, (n, D_VOL))
        b = self.inv_proto[cls] + self.rng.normal(0, 0.45, (n, D_INV))
        # Cost of emission: the bodily signal is expensive to produce and the
        # expense is real, not decorative. It is what makes it non-forgeable.
        cost = np.linalg.norm(b, axis=1, keepdims=True) * (
            1.0 + 0.35 * self.rng.normal(0, 1, (n, 1))
        )
        return v, b, cost

    def _panel_votes(self, v, b):
        """Each examiner returns a signed opinion in [-1, 1]."""
        raw = (
            v @ self.panel_vol_w.T
            + b @ self.panel_inv_w.T
            - np.linalg.norm(b, axis=1, keepdims=True) * self.hostility[None, :]
            + self.panel_bias[None, :]
        )
        raw = raw + self.rng.normal(0, 1, raw.shape) * self.panel_noise[None, :]
        return np.tanh(raw * 0.7)

    def batch(self, n_seq, seq_len):
        """Return (vol, inv, cost, votes, labels) shaped [T][n_seq, ...]."""
        labels = self.rng.integers(0, 3, size=(seq_len, n_seq))
        vol, inv, cost, votes = [], [], [], []
        for t in range(seq_len):
            v = np.zeros((n_seq, D_VOL))
            b = np.zeros((n_seq, D_INV))
            c = np.zeros((n_seq, 1))
            for cls in (0, 1, 2):
                m = labels[t] == cls
                if m.sum() == 0:
                    continue
                vv, bb, cc = self._episode_features(cls, int(m.sum()))
                v[m], b[m], c[m] = vv, bb, cc
            vol.append(v)
            inv.append(b)
            cost.append(c)
            votes.append(self._panel_votes(v, b))
        return vol, inv, cost, votes, labels

    def fluency_baseline_accuracy(self, n=4000):
        """How well does 'trust the most articulate account' do?

        This is the control condition: a nearest-prototype classifier that sees
        only the voluntary channel. Kempe's whole claim is that this baseline is
        not merely weak but actively inverted on the counterfeit class.
        """
        labels = self.rng.integers(0, 3, size=n)
        v = np.zeros((n, D_VOL))
        for cls in (0, 1, 2):
            m = labels == cls
            v[m] = self._episode_features(cls, int(m.sum()))[0]
        d = np.stack([np.linalg.norm(v - self.vol_proto[c], axis=1) for c in range(3)], 1)
        pred = d.argmin(1)
        # How articulate does each class SOUND? Projection on the polish axis.
        fluency = v @ self.polish
        polish_gap = float(fluency[labels == COUNTERFEIT].mean()
                           - fluency[labels == DIVINE].mean())
        return float((pred == labels).mean()), pred, labels, polish_gap


