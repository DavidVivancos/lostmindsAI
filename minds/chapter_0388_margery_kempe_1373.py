def evaluate(net, corpus, n_seq=256, seq_len=8, seed=99, mode="full"):
    """Accuracy over held-out sequences.

    `mode` selects which credence sources are permitted to speak:
        full        — all three (self + witness + panel)
        self_only   — the voluntary report alone, as a modern model would do it
        no_witness  — report + examiners, but no bodily evidence
    The gap between `full` and `self_only` is the measurement of how much of the
    decision was never the reporter's to make.
    """
    ev = DiscernmentCorpus(seed=seed)
    ev.vol_proto, ev.inv_proto = corpus.vol_proto, corpus.inv_proto
    ev.panel_vol_w, ev.panel_inv_w = corpus.panel_vol_w, corpus.panel_inv_w
    ev.hostility, ev.panel_bias, ev.panel_noise = (
        corpus.hostility, corpus.panel_bias, corpus.panel_noise)
    vol, inv, cost, votes, labels = ev.batch(n_seq, seq_len)

    P = net.p
    h = Node(np.zeros((n_seq, P.H)))
    a = Node(np.zeros((n_seq, P.A)))
    slots = []
    preds, truth = [], []
    for t in range(seq_len):
        a = net.body_step(inv[t], a)
        a_det = a.detach()
        read = net.ledger_read(h, slots)
        x = concat([Node(vol[t]), a_det, Node(votes[t]), read], axis=1)
        z = ((x @ P["Wz"]) + (h @ P["Uz"]) + P["bz"]).sigmoid()
        n = ((x @ P["Wn"]) + (h @ P["Un"]) + P["bn"]).tanh()
        h = (h * (1.0 - z)) + (n * z)

        l_self = ((h @ P["W_self"]) + P["b_self"]).data
        l_wit = ((a_det @ P["W_wit"]) + P["b_wit"]).data
        l_pan = ((Node(votes[t]) @ P["W_pan"]) + P["b_pan"]).data
        if mode == "full":
            lg = l_self + l_wit + l_pan
        elif mode == "self_only":
            lg = l_self
        elif mode == "no_witness":
            lg = l_self + l_pan
        else:
            raise ValueError(mode)

        pr = np.exp(lg - lg.max(1, keepdims=True)); pr /= pr.sum(1, keepdims=True)
        preds.append(lg.argmax(1)); truth.append(labels[t])
        slots.append((h.data.copy(), h.data.copy(), pr[:, DIVINE:DIVINE + 1].copy()))
        if len(slots) > P.M:
            slots.pop(0)

    preds = np.concatenate(preds); truth = np.concatenate(truth)
    per_class = {CLASS_NAMES[c]: float((preds[truth == c] == c).mean()) for c in (0, 1, 2)}
    used = {CLASS_NAMES[c]: float((preds == c).mean()) for c in (0, 1, 2)}
    return float((preds == truth).mean()), per_class, used


def train(steps=420, n_seq=48, seq_len=6, lr=8e-3, seed=1373, verbose=True):
    corpus = DiscernmentCorpus(seed=seed)
    params = ACNParams(d_hidden=24, d_affect=8, d_code=4, n_slots=4, seed=1438)
    net = AttestedCreatureNetwork(params)
    opt = Adam(params, lr=lr)

    history = []
    for s in range(1, steps + 1):
        vol, inv, cost, votes, labels = corpus.batch(n_seq, seq_len)
        params.zero_grad()
        loss, parts, _ = net.forward(vol, inv, cost, votes, labels)
        loss.backward()
        gnorm = opt.step()
        history.append(float(loss.data))
        if verbose and (s == 1 or s % 60 == 0):
            acc, _, _ = evaluate(net, corpus, n_seq=96, seq_len=6)
            print(f"    step {s:4d}   loss {float(loss.data):7.4f}   ce {parts['ce']:6.4f}"
                  f"   self-tax {parts['self_tax']:6.4f}   dissent {parts['dissent']:6.4f}"
                  f"   witness {parts['witness']:6.4f}   |g| {gnorm:6.2f}   acc {acc:.3f}")
    return net, corpus, history


def conflict_probe(net, corpus, account_cls, body_cls, n=400, T=6, seed=808):
    """Put the polished account and the body in deliberate conflict.

    Build episodes whose ARTICULATE content is drawn from one source class and
    whose BODILY signal is drawn from another, then ask which one the verdict
    follows. This is the decisive experiment, and it is the one Kempe's
    examiners kept running on her: the account was orthodox and well-formed, so
    the question was never the words. It was whether the body agreed with them.

    Returns the attestation rate — how often the network answers ATTESTED.
    """
    rng = np.random.default_rng(seed)
    P = net.p
    h = Node(np.zeros((n, P.H))); a = Node(np.zeros((n, P.A))); slots = []
    attested = []
    for t in range(T):
        v = corpus.vol_proto[account_cls] + rng.normal(0, 0.55, (n, D_VOL))
        b = corpus.inv_proto[body_cls] + rng.normal(0, 0.45, (n, D_INV))
        votes = corpus._panel_votes(v, b)
        h, a, lg, _, _, _ = net.step(v, b, votes, h, a, slots)
        pr = np.exp(lg.data - lg.data.max(1, keepdims=True)); pr /= pr.sum(1, keepdims=True)
        attested.append((lg.data.argmax(1) == DIVINE).mean())
        slots.append((h.data.copy(), h.data.copy(), pr[:, DIVINE:DIVINE + 1].copy()))
        if len(slots) > P.M:
            slots.pop(0)
    return float(np.mean(attested))


