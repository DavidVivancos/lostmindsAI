# SECTION 5 — OPTIMISER
# ==============================================================================

class Adam:
    def __init__(self, params, lr=6e-3, b1=0.9, b2=0.999, eps=1e-8, clip=5.0):
        self.p, self.lr, self.b1, self.b2, self.eps, self.clip = params, lr, b1, b2, eps, clip
        self.m = {k: np.zeros_like(v.data) for k, v in params.items()}
        self.v = {k: np.zeros_like(v.data) for k, v in params.items()}
        self.t = 0

    def step(self):
        self.t += 1
        total_norm = np.sqrt(sum(float((p.grad ** 2).sum()) for p in self.p.P.values()))
        scale = min(1.0, self.clip / (total_norm + 1e-9))
        for k, p in self.p.items():
            g = p.grad * scale
            self.m[k] = self.b1 * self.m[k] + (1 - self.b1) * g
            self.v[k] = self.b2 * self.v[k] + (1 - self.b2) * (g ** 2)
            mh = self.m[k] / (1 - self.b1 ** self.t)
            vh = self.v[k] / (1 - self.b2 ** self.t)
            p.data -= self.lr * mh / (np.sqrt(vh) + self.eps)
        return total_norm


# ==============================================================================
# SECTION 6 — GRADIENT VERIFICATION (MANDATORY, RUNS BEFORE TRAINING)
# ==============================================================================
# Two checks, and the second is the one that matters.
#
#   CHECK A  Standard finite differences: do the analytic gradients match
#            (L(w+h) - L(w-h)) / 2h for every trainable tensor?
#
#   CHECK B  The severance proof. Remove the witness loss and re-run backward.
#            The body parameters must receive EXACTLY zero gradient — not small,
#            zero. If the reporter can nudge the tears even slightly, the
#            unforgeable channel is forgeable and the architecture's central
#            claim is false. This is the one test that is allowed to abort the
#            whole run.
# ==============================================================================

def make_tiny_setup(seed=7):
    corpus = DiscernmentCorpus(seed=seed)
    params = ACNParams(d_hidden=6, d_affect=4, d_code=3, n_slots=2, seed=seed)
    net = AttestedCreatureNetwork(params)
    data = corpus.batch(n_seq=4, seq_len=3)
    return corpus, params, net, data


def gradient_check(n_probe=4, eps=1e-6, tol=2e-5, verbose=True):
    corpus, params, net, data = make_tiny_setup()
    vol, inv, cost, votes, labels = data
    rng = np.random.default_rng(0)

    # Record the severed values once, then hold them fixed for every probe.
    tape_record()
    params.zero_grad()
    loss, _, _ = net.forward(vol, inv, cost, votes, labels)
    loss.backward()
    analytic = {k: p.grad.copy() for k, p in params.items()}

    def loss_value():
        tape_replay()
        return float(net.forward(vol, inv, cost, votes, labels)[0].data)

    # Sanity: replaying the unperturbed weights must reproduce the base loss.
    base = float(loss.data)
    assert abs(loss_value() - base) < 1e-12, "detach tape failed to replay"

    worst, worst_key, n_checked = 0.0, None, 0
    for k, p in params.items():
        flat = p.data.reshape(-1)
        idxs = rng.choice(flat.size, size=min(n_probe, flat.size), replace=False)
        for i in idxs:
            orig = flat[i]
            flat[i] = orig + eps; lp = loss_value()
            flat[i] = orig - eps; lm = loss_value()
            flat[i] = orig
            num = (lp - lm) / (2 * eps)
            ana = analytic[k].reshape(-1)[i]
            denom = max(1.0, abs(num), abs(ana))
            rel = abs(num - ana) / denom
            n_checked += 1
            if rel > worst:
                worst, worst_key = rel, f"{k}[{i}]"
    tape_off()
    if verbose:
        print(f"  CHECK A  finite differences over {n_checked} probes "
              f"across {len(params.P)} tensors")
        print(f"           worst relative error = {worst:.3e}  at {worst_key}")
        print(f"           tolerance = {tol:.1e}   ->  {'PASS' if worst < tol else 'FAIL'}")
    return worst < tol, worst


def severance_check(verbose=True):
    """Prove the report head cannot reach the body."""
    corpus, params, _, data = make_tiny_setup(seed=11)
    vol, inv, cost, votes, labels = data

    # Witness loss switched off: the ONLY remaining error signal is the report's.
    net_no_witness = AttestedCreatureNetwork(params, lambda_witness=0.0)
    params.zero_grad()
    loss, _, _ = net_no_witness.forward(vol, inv, cost, votes, labels)
    loss.backward()
    leaks = {k: float(np.abs(params[k].grad).max()) for k in ACNParams.BODY_KEYS}
    sealed = all(v == 0.0 for v in leaks.values())

    # Control: with the witness loss restored, the body MUST receive gradient,
    # otherwise it is merely disconnected rather than protected.
    net_full = AttestedCreatureNetwork(params, lambda_witness=0.5)
    params.zero_grad()
    loss2, _, _ = net_full.forward(vol, inv, cost, votes, labels)
    loss2.backward()
    taught = {k: float(np.abs(params[k].grad).max()) for k in ACNParams.BODY_KEYS}
    learns = all(v > 0.0 for v in taught.values())

    if verbose:
        print("  CHECK B  severance of the involuntary channel")
        for k in ACNParams.BODY_KEYS:
            print(f"           {k:10s}  |grad| from report alone = {leaks[k]:.3e}"
                  f"   |grad| with witness = {taught[k]:.3e}")
        print(f"           reporter cannot forge the body : {'PASS' if sealed else 'FAIL'}")
        print(f"           body still learns from cost    : {'PASS' if learns else 'FAIL'}")
    return sealed and learns


