def test_stillness_collapse():
    """Two different constant inputs give the SAME profile shape (up to scale):
    the fetter bank cannot tell one stillness from another."""
    bank = FetterBank(10, 6)
    U1 = np.full((1, T_STEPS, 10), 0.3); U2 = np.full((1, T_STEPS, 10), -0.9)
    P1, c1 = bank.forward(U1); P2, c2 = bank.forward(U2)
    # steady-state energies scale exactly with the square of the constant
    e1 = c1["E"][0, -1]; e2 = c2["E"][0, -1]
    ratio = e2 / np.maximum(e1, 1e-12)
    assert np.allclose(ratio, (0.9 / 0.3) ** 2, rtol=1e-6), ratio
    # the normalised shape across the bank is identical
    s1 = e1 / np.linalg.norm(e1); s2 = e2 / np.linalg.norm(e2)
    assert np.allclose(s1, s2, atol=1e-9)
    return "steady-state energy shape across the bank identical for two different constants (rel. err < 1e-9)"


