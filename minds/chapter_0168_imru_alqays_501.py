def per_family_simile(model, S):
    """Accuracy on SAME-motion pairs, per family (can the mind bind X to X across domains?)."""
    _, score = model.simile_loss(S, want_grad=False)
    out = {}
    for f in range(N_FAM):
        idx = (S["FA"] == f) & (S["Y"] > 0.5)
        out[FAMILIES[f]] = float((score[idx] > 0).mean()) if idx.any() else float("nan")
    return out


def confusion_pairs(model, S):
    """Which DIFFERENT motions does the mind most often mistake for the same?"""
    _, score = model.simile_loss(S, want_grad=False)
    rows = []
    for i in range(N_FAM):
        for j in range(i + 1, N_FAM):
            idx = ((S["FA"] == i) & (S["FB"] == j)) | ((S["FA"] == j) & (S["FB"] == i))
            if idx.any():
                rows.append((float((score[idx] > 0).mean()), FAMILIES[i], FAMILIES[j], int(idx.sum())))
    rows.sort(reverse=True)
    return rows


def atlal_by_keep(model, A, bins=((0.10, 0.22), (0.22, 0.34), (0.34, 0.60))):
    _, logits, recon, probs, target = model.atlal_loss(A, want_grad=False)
    pred = logits.argmax(1)
    var = target.var(0).mean() + 1e-6
    out = []
    for lo, hi in bins:
        idx = (A["KEEP"] >= lo) & (A["KEEP"] < hi)
        acc = float((pred[idx] == A["F"][idx]).mean())
        r2 = float(1.0 - ((recon[idx] - target[idx]) ** 2).mean() / var)
        out.append((lo, hi, int(idx.sum()), acc, r2))
    return out


def atlal_by_family(model, A):
    _, logits, _, probs, _ = model.atlal_loss(A, want_grad=False)
    pred = logits.argmax(1)
    ent = -(probs * np.log(probs + 1e-12)).sum(1)
    out = []
    for f in range(N_FAM):
        idx = A["F"] == f
        out.append((FAMILIES[f], float((pred[idx] == f).mean()), float(ent[idx].mean())))
    return out


def faces_of_resemblance(model, S, fa, fb, topn=4):
    """For same-motion pairs of family `fa` — the horse in one domain and the boulder
    in another — which aspects carry the binding?"""
    idx = (S["FA"] == fa) & (S["FB"] == fb) & (S["Y"] > 0.5)
    if not idx.any():
        return None
    PA, _ = model.profile(S["XA"][idx], S["DA"][idx]); PB, _ = model.profile(S["XB"][idx], S["DB"][idx])
    _, c = model.simile_forward(PA, PB)
    contrib = (c["d2"] * c["wgt"]).mean(0)                     # penalty per aspect
    order = np.argsort(contrib)
    return [(int(h), float(c["wgt"][h]), float(contrib[h])) for h in order[:topn]], float(c["wgt"].sum())


def exhibit_similes(model, S):
    """Concrete held-out similes, reported as the mind's probability that they hold."""
    _, score = model.simile_loss(S, want_grad=False)
    p = sigmoid(score)
    def pick(fa, da, fb, db):
        idx = (((S["FA"] == fa) & (S["DA"] == da) & (S["FB"] == fb) & (S["DB"] == db)) |
               ((S["FA"] == fb) & (S["DA"] == db) & (S["FB"] == fa) & (S["DB"] == da)))
        return (float(p[idx].mean()), int(idx.sum())) if idx.any() else (float("nan"), 0)
    rows = [
        ("the horse charging and wheeling (the living)  ~  a boulder in the torrent (the inert)", pick(0, 0, 0, 1)),
        ("the horse charging and wheeling (the living)  ~  a hopping boulder, closing hops (the inert)", pick(0, 0, 1, 1)),
        ("the night letting down its curtains (the sky) ~  a swell in the flood-bed (the inert)", pick(2, 2, 2, 1)),
        ("the night letting down its curtains (the sky) ~  the flash of lightning (the inert)", pick(2, 2, 4, 1)),
        ("the flood at Kutayfa (the inert)             ~  the same surge seen in the sky", pick(5, 1, 5, 2)),
        ("the tethered stars (the sky)                 ~  a still stone (the inert)", pick(3, 2, 3, 1)),
        ("the tethered stars (the sky)                 ~  the horse (the living)", pick(3, 2, 0, 0)),
    ]
    return rows


def energy_by_family(model, A):
    """How much the fetter bank catches, per motion: the total captured energy
    (sum over neurons of the soft-peak energy). Stillness should catch nothing."""
    P, _ = model.profile(A["XC"], A["D"])
    K = model.K
    cap = np.expm1(P[:, :K]).sum(1)
    return [(FAMILIES[f], float(cap[A["F"] == f].mean())) for f in range(N_FAM)]


