def softplus(x):
    """Numerically safe log(1+exp(x))."""
    x = np.asarray(x, dtype=np.float64)
    return np.where(x > 30.0, x, np.log1p(np.exp(np.minimum(x, 30.0))))


def sigmoid(x):
    x = np.asarray(x, dtype=np.float64)
    return 1.0 / (1.0 + np.exp(-x))


def bce_with_logits(logits, y):
    """Mean binary cross-entropy from logits and its gradient w.r.t. logits."""
    z = logits
    loss = np.maximum(z, 0) - z * y + np.log1p(np.exp(-np.abs(z)))
    grad = (sigmoid(z) - y) / z.size
    return loss.mean(), grad


def softmax_ce(logits, y):
    """Mean cross-entropy from logits (N,F) and integer labels (N,)."""
    m = logits.max(1, keepdims=True)
    ex = np.exp(logits - m)
    p = ex / ex.sum(1, keepdims=True)
    n = logits.shape[0]
    loss = -np.log(p[np.arange(n), y] + 1e-12).mean()
    g = p.copy()
    g[np.arange(n), y] -= 1.0
    return loss, g / n, p


