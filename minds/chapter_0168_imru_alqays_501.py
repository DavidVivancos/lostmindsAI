# 5.  ADAM, TRAINING, EVALUATION
# ==============================================================================

class Adam:
    def __init__(self, params, lr=3e-3, b1=0.9, b2=0.999, eps=1e-8):
        self.lr, self.b1, self.b2, self.eps = lr, b1, b2, eps
        self.m = {k: np.zeros_like(v) for k, v in params.items()}
        self.v = {k: np.zeros_like(v) for k, v in params.items()}
        self.t = 0

    def step(self, params, grads, clip=5.0):
        self.t += 1
        gn = np.sqrt(sum(float((np.asarray(g) ** 2).sum()) for g in grads.values()))
        sc = min(1.0, clip / (gn + 1e-12))
        for k, g in grads.items():
            g = np.asarray(g) * sc
            self.m[k] = self.b1 * self.m[k] + (1 - self.b1) * g
            self.v[k] = self.b2 * self.v[k] + (1 - self.b2) * g * g
            mh = self.m[k] / (1 - self.b1 ** self.t)
            vh = self.v[k] / (1 - self.b2 ** self.t)
            params[k] -= self.lr * mh / (np.sqrt(vh) + self.eps)


def sub(d, idx):
    return {k: (v[idx] if isinstance(v, np.ndarray) and v.shape and v.shape[0] == len(next(iter(d.values()))) else v)
            for k, v in d.items()}


def train(model, S_tr, A_tr, S_va, A_va, epochs=30, bs=64, lr=3e-3, seed=0, log_every=5, verbose=True):
    rng = np.random.default_rng(seed)
    opt = Adam(model.params(), lr=lr)
    nS, nA = len(S_tr["Y"]), len(A_tr["F"])
    steps = max(nS, nA) // bs
    hist = []
    for ep in range(1, epochs + 1):
        pS = rng.permutation(nS); pA = rng.permutation(nA)
        ls = la = 0.0
        for i in range(steps):
            iS = pS[(i * bs) % nS:(i * bs) % nS + bs]
            iA = pA[(i * bs) % nA:(i * bs) % nA + bs]
            if len(iS) < 8: iS = pS[:bs]
            if len(iA) < 8: iA = pA[:bs]
            l1, g1 = model.simile_loss(sub(S_tr, iS))
            opt.step(model.params(), g1)
            l2, g2 = model.atlal_loss(sub(A_tr, iA))
            opt.step(model.params(), g2)
            ls += l1; la += l2
        ls /= steps; la /= steps
        if verbose and (ep % log_every == 0 or ep == 1 or ep == epochs):
            sa = simile_accuracy(model, S_va)
            aa = atlal_accuracy(model, A_va)
            print(f"    epoch {ep:3d}   simile-loss {ls:.4f}   ruins-loss {la:.4f}   "
                  f"| held-out: simile {sa:.3f}   ruins {aa:.3f}")
        hist.append((ep, ls, la))
    return hist


def simile_accuracy(model, S, idx=None):
    if idx is not None:
        S = sub(S, idx)
    _, score = model.simile_loss(S, want_grad=False)
    return float(((score > 0) == (S["Y"] > 0.5)).mean())


def atlal_accuracy(model, A, idx=None):
    if idx is not None:
        A = sub(A, idx)
    _, logits, _, _, _ = model.atlal_loss(A, want_grad=False)
    return float((logits.argmax(1) == A["F"]).mean())


def atlal_restoration_r2(model, A):
    """1 - (restoration error / variance of the clean profile): how much of the
    full resonance signature the mind recovers from the residue alone."""
    _, _, recon, _, target = model.atlal_loss(A, want_grad=False)
    var = target.var(0).mean() + 1e-6
    return float(1.0 - ((recon - target) ** 2).mean() / var)


