# 3.  THE SURFACE READER  — appearance statistics, no dynamics (the baseline)
# ==============================================================================

class SurfaceBank:
    """profile = [mean, std, max, min] of each drive channel over time  (4K)."""
    def __init__(self, K, seed):
        self.K = K
        self.p = {}

    def forward(self, U):
        mu = U.mean(1)
        var = U.var(1) + 1e-6
        sd = np.sqrt(var)
        mx = U.max(1); mn = U.min(1)
        P = np.concatenate([mu, sd, mx, mn], -1)
        cache = dict(U=U, mu=mu, sd=sd, imx=U.argmax(1), imn=U.argmin(1))
        return P, cache

    def backward(self, dP, cache):
        U, mu, sd, imx, imn = cache["U"], cache["mu"], cache["sd"], cache["imx"], cache["imn"]
        B, T, K = U.shape
        dmu, dsd, dmx, dmn = dP[:, :K], dP[:, K:2 * K], dP[:, 2 * K:3 * K], dP[:, 3 * K:]
        dU = np.zeros_like(U)
        dU += dmu[:, None, :] / T
        dU += dsd[:, None, :] * (U - mu[:, None, :]) / (T * sd[:, None, :])
        bi = np.arange(B)[:, None]; ki = np.arange(K)[None, :]
        dU[bi, imx, ki] += dmx
        dU[bi, imn, ki] += dmn
        return {}, dU


