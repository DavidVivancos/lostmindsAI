# 4.  THE WHOLE MIND  — adapters, bank, and the two heads
# ==============================================================================

class QaydNetwork:
    """
    kind = "QAYD"     : FetterBank   (the architecture of this chapter)
    kind = "SURFACE"  : SurfaceBank  (the appearance baseline)
    """
    def __init__(self, kind="QAYD", K=24, H=12, HID=48, seed=1):
        rng = np.random.default_rng(seed)
        self.kind = kind
        self.K = K
        self.bank = FetterBank(K, seed + 100) if kind == "QAYD" else SurfaceBank(K, seed + 100)
        PDIM = 3 * K if kind == "QAYD" else 4 * K
        self.PDIM = PDIM
        self.p = {}
        # domain adapters (private surfaces)
        for d in range(len(DOMAINS)):
            self.p[f"Wa{d}"] = rng.standard_normal((MAXD, K)) * (1.0 / np.sqrt(MAXD))
            self.p[f"ba{d}"] = np.zeros(K)
        # simile head (tashbīh): aspect projection + non-negative aspect weights
        self.p["Wg"] = rng.standard_normal((PDIM, H)) * (1.0 / np.sqrt(PDIM))
        self.p["bg"] = np.zeros(H)
        self.p["v"] = np.zeros(H) + 0.5            # softplus(v) = aspect weights
        self.p["c0"] = np.array([1.0])             # bias of the simile score
        # ruins head (aṭlāl): hidden layer -> family logits + latent reconstruction
        self.p["W1"] = rng.standard_normal((PDIM, HID)) * (1.0 / np.sqrt(PDIM))
        self.p["b1"] = np.zeros(HID)
        self.p["W2"] = rng.standard_normal((HID, N_FAM)) * (1.0 / np.sqrt(HID))
        self.p["b2"] = np.zeros(N_FAM)
        SIGDIM = 3 * _Reference.K
        self.p["W3"] = rng.standard_normal((HID, SIGDIM)) * (1.0 / np.sqrt(HID))
        self.p["b3"] = np.zeros(SIGDIM)
        # bank parameters live inside the bank; expose them under a prefix
        for k, v in self.bank.p.items():
            self.p["bank." + k] = v

    # --- parameter plumbing --------------------------------------------------
    def params(self):
        return self.p

    def _sync_bank(self):
        for k in list(self.bank.p.keys()):
            self.bank.p[k] = self.p["bank." + k]

    # --- the profile of a set of observations --------------------------------
    def profile(self, X, Dm):
        """X: (B, T, MAXD), Dm: (B,) domain ids. Returns P (B, PDIM), cache."""
        self._sync_bank()
        B = X.shape[0]
        U = np.zeros((B, T_STEPS, self.K))
        for d in range(len(DOMAINS)):
            idx = np.where(Dm == d)[0]
            if idx.size:
                U[idx] = np.tanh(X[idx] @ self.p[f"Wa{d}"] + self.p[f"ba{d}"])
        P, bc = self.bank.forward(U)
        return P, dict(X=X, Dm=Dm, U=U, bc=bc)

    def profile_backward(self, dP, cache, grads):
        gb, dU = self.bank.backward(dP, cache["bc"])
        for k, v in gb.items():
            grads["bank." + k] = grads.get("bank." + k, 0) + v
        dpre = dU * (1.0 - cache["U"] ** 2)
        X, Dm = cache["X"], cache["Dm"]
        for d in range(len(DOMAINS)):
            idx = np.where(Dm == d)[0]
            if idx.size:
                Xd = X[idx].reshape(-1, MAXD)
                Gd = dpre[idx].reshape(-1, self.K)
                grads[f"Wa{d}"] = grads.get(f"Wa{d}", 0) + Xd.T @ Gd
                grads[f"ba{d}"] = grads.get(f"ba{d}", 0) + Gd.sum(0)

    # --- the simile head ------------------------------------------------------
    def simile_forward(self, PA, PB):
        Wg, bg, v, c0 = self.p["Wg"], self.p["bg"], self.p["v"], self.p["c0"]
        GA = PA @ Wg + bg
        GB = PB @ Wg + bg
        dif = GA - GB
        d2 = dif ** 2
        wgt = softplus(v)
        score = -(d2 @ wgt) + c0[0]
        return score, dict(PA=PA, PB=PB, GA=GA, GB=GB, dif=dif, d2=d2, wgt=wgt)

    def simile_backward(self, dscore, cache, grads):
        PA, PB, dif, d2, wgt = cache["PA"], cache["PB"], cache["dif"], cache["d2"], cache["wgt"]
        v = self.p["v"]
        grads["c0"] = grads.get("c0", 0) + np.array([dscore.sum()])
        dwgt = -(dscore[:, None] * d2).sum(0)
        grads["v"] = grads.get("v", 0) + dwgt * sigmoid(v)
        dd2 = -dscore[:, None] * wgt[None, :]
        ddif = 2.0 * dd2 * dif
        dGA = ddif; dGB = -ddif
        grads["Wg"] = grads.get("Wg", 0) + PA.T @ dGA + PB.T @ dGB
        grads["bg"] = grads.get("bg", 0) + dGA.sum(0) + dGB.sum(0)
        dPA = dGA @ self.p["Wg"].T
        dPB = dGB @ self.p["Wg"].T
        return dPA, dPB

    # --- the ruins head --------------------------------------------------------
    def atlal_forward(self, P):
        h = np.tanh(P @ self.p["W1"] + self.p["b1"])
        logits = h @ self.p["W2"] + self.p["b2"]
        recon = h @ self.p["W3"] + self.p["b3"]
        return logits, recon, dict(P=P, h=h)

    def atlal_backward(self, dlogits, drecon, cache, grads):
        P, h = cache["P"], cache["h"]
        grads["W2"] = grads.get("W2", 0) + h.T @ dlogits
        grads["b2"] = grads.get("b2", 0) + dlogits.sum(0)
        grads["W3"] = grads.get("W3", 0) + h.T @ drecon
        grads["b3"] = grads.get("b3", 0) + drecon.sum(0)
        dh = dlogits @ self.p["W2"].T + drecon @ self.p["W3"].T
        dpre = dh * (1.0 - h ** 2)
        grads["W1"] = grads.get("W1", 0) + P.T @ dpre
        grads["b1"] = grads.get("b1", 0) + dpre.sum(0)
        return dpre @ self.p["W1"].T

    # --- losses --------------------------------------------------------------
    def simile_loss(self, batch, want_grad=True):
        PA, cA = self.profile(batch["XA"], batch["DA"])
        PB, cB = self.profile(batch["XB"], batch["DB"])
        score, cs = self.simile_forward(PA, PB)
        loss, dscore = bce_with_logits(score, batch["Y"])
        if not want_grad:
            return loss, score
        grads = {}
        dPA, dPB = self.simile_backward(dscore, cs, grads)
        self.profile_backward(dPA, cA, grads)
        self.profile_backward(dPB, cB, grads)
        return loss, grads

    RECON_WEIGHT = 1.0

    def atlal_loss(self, batch, want_grad=True, target=None):
        """Name the motion from its residue, and RESTORE the reference signature of
        the unwound observation — the full motion, imagined from what it left."""
        target = batch["SIG"] if target is None else target
        P, cP = self.profile(batch["X"], batch["D"])
        logits, recon, ca = self.atlal_forward(P)
        ce, dlogits, probs = softmax_ce(logits, batch["F"])
        diff = recon - target
        mse = (diff ** 2).mean()
        loss = ce + self.RECON_WEIGHT * mse
        if not want_grad:
            return loss, logits, recon, probs, target
        drecon = self.RECON_WEIGHT * 2.0 * diff / diff.size
        grads = {}
        dP = self.atlal_backward(dlogits, drecon, ca, grads)
        self.profile_backward(dP, cP, grads)
        return loss, grads

    def total_loss(self, sb, ab, target=None):
        """Joint loss used by the gradient check: simile + ruins on one batch each."""
        l1, g1 = self.simile_loss(sb)
        l2, g2 = self.atlal_loss(ab, target=target)
        grads = {}
        for g in (g1, g2):
            for k, v in g.items():
                grads[k] = grads.get(k, 0) + v
        return l1 + l2, grads


