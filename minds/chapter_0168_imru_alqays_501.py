# ==============================================================================
# 1.  THE SIX MOTIONS OF THE MU'ALLAQA  (synthetic latent-dynamics generator)
# ==============================================================================
#
# Each "family" is a way of moving, taken from a scene of the ode. Every sample
# is a 2-dimensional latent trajectory ξ of length T (a position-like and a
# velocity-like coordinate). The families are engineered so that their
# marginal statistics overlap and only their TEMPORAL structure separates them.

T_STEPS = 64
LATENT = 2

FAMILIES = [
    "KARR_FARR",     # 0  the horse: charge / retreat, fast reversals
    "TORRENT",       # 1  the boulder hurled by the flood: bounces, closing spacing
    "NIGHT_WAVE",    # 2  the night: a slow swell letting down its curtains
    "TETHERED",      # 3  the stars tethered to the rock: stillness + jitter
    "LIGHTNING",     # 4  the lightning: sparse flashes, sharp decay
    "FLOOD",         # 5  the torrent at Kutayfa: onset, surge, turbulent plateau
]
N_FAM = len(FAMILIES)


def _karr_farr(rng, t):
    f = rng.uniform(0.09, 0.14)
    ph = rng.uniform(0, 2 * np.pi)
    x = np.tanh(3.0 * np.sin(2 * np.pi * f * t + ph))
    # random reversal bursts: the horse "wheeling and fleeing... all at once"
    n_rev = rng.integers(1, 4)
    for _ in range(n_rev):
        t0 = rng.integers(5, T_STEPS - 5)
        x[t0:] *= -1.0
    v = np.gradient(x) * 4.0
    return x, v


def _torrent(rng, t):
    # bounces with geometrically closing spacing and decaying height
    gap = rng.uniform(9.0, 13.0)
    ratio = rng.uniform(0.72, 0.84)
    amp = 1.0
    tt = rng.uniform(0.0, 4.0)
    x = np.zeros(T_STEPS)
    v = np.zeros(T_STEPS)
    while tt < T_STEPS and gap > 1.2:
        i0 = int(tt)
        seg = np.arange(i0, min(T_STEPS, int(tt + gap)))
        u = (seg - tt) / max(gap, 1.0)
        x[seg] = amp * 4.0 * u * (1.0 - u)          # parabolic hop
        v[seg] = amp * (1.0 - 2.0 * u) * 2.0
        tt += gap
        gap *= ratio
        amp *= ratio
    x = x * 2.0 - 0.8
    return x, v


def _night_wave(rng, t):
    f = rng.uniform(0.02, 0.035)
    ph = rng.uniform(0, 2 * np.pi)
    env = 0.5 + 0.5 * (t / T_STEPS) ** rng.uniform(0.6, 1.6)
    x = env * np.sin(2 * np.pi * f * t + ph)
    v = np.gradient(x) * 8.0
    return x, v


def _tethered(rng, t):
    c = rng.uniform(-1.0, 1.0)
    x = c + 0.03 * rng.standard_normal(T_STEPS)
    v = 0.03 * rng.standard_normal(T_STEPS)
    return x, v


def _lightning(rng, t):
    rate = rng.uniform(0.05, 0.11)
    x = np.zeros(T_STEPS)
    flashes = np.where(rng.random(T_STEPS) < rate)[0]
    if flashes.size == 0:
        flashes = np.array([rng.integers(3, T_STEPS - 3)])
    for f0 in flashes:
        dec = rng.uniform(0.35, 0.6)
        k = np.arange(f0, T_STEPS)
        x[k] += rng.uniform(0.7, 1.3) * dec ** (k - f0)
    x = x - 0.4
    v = np.gradient(x) * 3.0
    return x, v


def _flood(rng, t):
    on = rng.uniform(12, 36)
    width = rng.uniform(2.5, 6.0)
    x = -1.0 + 2.0 * sigmoid((t - on) / width)
    turb = 0.18 * np.sin(2 * np.pi * rng.uniform(0.25, 0.4) * t + rng.uniform(0, 6.28))
    x = x + turb * (t > on)
    v = np.gradient(x) * 6.0
    return x, v


GENERATORS = [_karr_farr, _torrent, _night_wave, _tethered, _lightning, _flood]


# A fixed marginal template: every MOVING trajectory is rank-mapped onto exactly
# this set of values, so its mean, spread, maximum and minimum are identical to
# every other moving trajectory's. Only the ORDER in time survives. This is the
# experimental control that makes the question sharp: appearance is equalised,
# dynamics is all that is left. (Stillness is exempt: the tethered stars keep
# their tiny variance, because stillness is visible to anyone.)
_U = (np.arange(T_STEPS) + 0.5) / T_STEPS
TEMPLATE = np.tanh(2.2 * (2.0 * _U - 1.0)) / np.tanh(2.2)          # S-shaped, in [-1, 1]


def equalise(rng, y):
    """Rank-map y onto TEMPLATE (ties broken at random)."""
    jitter = 1e-6 * rng.standard_normal(y.shape)
    order = np.argsort(y + jitter)
    out = np.empty_like(y)
    out[order] = TEMPLATE
    return out


def latent_trajectory(rng, fam):
    t = np.arange(T_STEPS, dtype=np.float64)
    x, v = GENERATORS[fam](rng, t)
    if FAMILIES[fam] != "TETHERED":
        x = equalise(rng, x)
        v = equalise(rng, v)
    xi = np.stack([x, v], -1)                       # (T, 2)
    return xi


# ------------------------------------------------------------------------------
# 1b. DOMAINS  — the surfaces through which motion is seen
# ------------------------------------------------------------------------------
# Domain 0 "the living"  : observes position-like features         (5 channels)
# Domain 1 "the inert"   : observes velocity-like features          (6 channels)
# Domain 2 "the sky"     : observes a mixture with a sign flip      (4 channels)
# Each domain has a fixed random mixing matrix; each SAMPLE additionally carries
# a random static appearance vector (the coat of the horse, the colour of the
# rock) that dominates the mean of the observation and says nothing about how
# the thing moves.

DOMAINS = ["the living", "the inert", "the sky"]
DOM_DIM = [5, 6, 4]


def make_domain_mixers(seed=11):
    rng = np.random.default_rng(seed)
    mixers = []
    for d, D in enumerate(DOM_DIM):
        A = rng.standard_normal((D, LATENT)) * 0.9
        if d == 1:                       # the inert watches velocity mostly
            A[:, 0] *= 0.25
            A[:, 1] *= 1.6
        if d == 2:                       # the sky flips the sign of position
            A[:, 0] *= -1.0
        mixers.append(A)
    return mixers


MIXERS = make_domain_mixers()


def render(rng, xi, dom):
    """Observe a latent trajectory through domain `dom`. Returns (T, D_dom)."""
    A = MIXERS[dom]
    D = A.shape[0]
    coat = rng.uniform(-1.0, 1.0, size=D)          # static appearance confound
    gain = rng.uniform(0.7, 1.3)
    x = np.tanh(gain * xi @ A.T + coat)            # (T, D)
    x = x + 0.05 * rng.standard_normal(x.shape)
    return x


def ground(x, mask):
    """The halt reads marks relative to the ground: subtract, per channel, the mean
    over the samples that survive, then silence the erased samples. Erased means
    'no evidence', not 'zero' — after grounding, a gap sits at the resting level
    and injects no energy of its own. Applied identically to every model."""
    m = mask[:, None]
    n = max(m.sum(), 1.0)
    mu = (x * m).sum(0, keepdims=True) / n
    return (x - mu) * m


def wind(rng, x, keep_frac=None):
    """The aṭlāl operator: erase most samples, fade the rest, bury in sand.
    Returns the residue (T, D+1): grounded observed channels, plus the mask."""
    if keep_frac is None:
        keep_frac = rng.uniform(0.15, 0.50)
    mask = (rng.random(T_STEPS) < keep_frac).astype(np.float64)
    if mask.sum() < 3:                             # a trace must have a few marks
        mask[rng.choice(T_STEPS, 3, replace=False)] = 1.0
    fade = np.exp(-rng.uniform(0.0, 1.5) * np.arange(T_STEPS) / T_STEPS)
    sand = 0.15 * rng.standard_normal(x.shape)
    res = ground(x * fade[:, None] + sand, mask)
    return np.concatenate([res, mask[:, None]], -1), mask


def pad_channels(x, width):
    """Right-pad a (T, D) observation with zeros to (T, width)."""
    out = np.zeros((x.shape[0], width))
    out[:, : x.shape[1]] = x
    return out


MAXD = max(DOM_DIM) + 1                            # +1 for the mask channel


def make_simile_set(n, seed):
    """Cross-domain pairs. Label 1 iff both were generated by the same motion."""
    rng = np.random.default_rng(seed)
    XA = np.zeros((n, T_STEPS, MAXD)); XB = np.zeros((n, T_STEPS, MAXD))
    DA = np.zeros(n, int); DB = np.zeros(n, int)
    FA = np.zeros(n, int); FB = np.zeros(n, int)
    Y = np.zeros(n)
    for i in range(n):
        fa = rng.integers(N_FAM)
        same = rng.random() < 0.5
        fb = fa if same else rng.choice([f for f in range(N_FAM) if f != fa])
        da = rng.integers(len(DOMAINS))
        db = rng.choice([d for d in range(len(DOMAINS)) if d != da])
        full = np.ones(T_STEPS)
        xa = ground(render(rng, latent_trajectory(rng, fa), da), full)
        xb = ground(render(rng, latent_trajectory(rng, fb), db), full)
        XA[i] = pad_channels(np.concatenate([xa, full[:, None]], -1), MAXD)
        XB[i] = pad_channels(np.concatenate([xb, full[:, None]], -1), MAXD)
        DA[i], DB[i], FA[i], FB[i], Y[i] = da, db, fa, fb, float(same)
    return dict(XA=XA, XB=XB, DA=DA, DB=DB, FA=FA, FB=FB, Y=Y)


def make_atlal_set(n, seed):
    """Residues of single trajectories, with the motion label, the clean latent and
    the clean (unwound) observation XC. SIG (filled in by attach_signatures) is the
    restoration target: a fixed reference signature of the unwound observation."""
    rng = np.random.default_rng(seed)
    X = np.zeros((n, T_STEPS, MAXD)); XC = np.zeros((n, T_STEPS, MAXD))
    D = np.zeros(n, int); F = np.zeros(n, int)
    XI = np.zeros((n, T_STEPS, LATENT)); KEEP = np.zeros(n)
    for i in range(n):
        f = rng.integers(N_FAM)
        d = rng.integers(len(DOMAINS))
        xi = latent_trajectory(rng, f)
        x = render(rng, xi, d)
        res, mask = wind(rng, x)
        X[i] = pad_channels(res, MAXD)
        XC[i] = pad_channels(np.concatenate([ground(x, np.ones(T_STEPS)), np.ones((T_STEPS, 1))], -1), MAXD)
        D[i], F[i], XI[i], KEEP[i] = d, f, xi, mask.mean()
    A = dict(X=X, XC=XC, D=D, F=F, XI=XI, KEEP=KEEP)
    A["SIG"] = reference_signature(XC, D)
    return A


# ------------------------------------------------------------------------------
# 1c. THE REFERENCE SIGNATURE  — "the camp as it stood"
# ------------------------------------------------------------------------------
# A FIXED, untrained resonator bank with fixed random adapters. Its response to the
# unwound observation is what the ruins head must restore from the residue. It is
# a label, not a moving target, and it is identical for both models, so the
# restoration score is comparable between the fetter bank and the surface reader.

class _Reference:
    K = 16
    def __init__(self):
        rng = np.random.default_rng(777)
        self.W = [rng.standard_normal((MAXD, self.K)) / np.sqrt(MAXD) for _ in DOMAINS]
        self.bank = None            # built lazily, after FetterBank is defined
        self.mu = None; self.sd = None

    def raw(self, XC, D):
        if self.bank is None:
            self.bank = FetterBank(self.K, 778)
        U = np.zeros((len(XC), T_STEPS, self.K))
        for d in range(len(DOMAINS)):
            idx = np.where(D == d)[0]
            if idx.size:
                U[idx] = np.tanh(XC[idx] @ self.W[d])
        P, _ = self.bank.forward(U)
        return P

    def __call__(self, XC, D):
        P = self.raw(XC, D)
        if self.mu is None:                       # standardise on the first (training) set
            self.mu = P.mean(0); self.sd = P.std(0) + 1e-6
        return (P - self.mu) / self.sd


REFERENCE = _Reference()


def reference_signature(XC, D):
    return REFERENCE(XC, D)


# ==============================================================================
# 2.  THE FETTER NEURON  — a damped rotor with a soft-peak readout
# ==============================================================================
#
#   z_t = a_k · R(ω_k) · z_{t-1} + b_k · u_{t,k}          z ∈ R²
#   a_k = exp(-(softplus(r_k) + 0.02))   ∈ (0, 0.98]      (always stable)
#   R(ω) = [[cos ω, -sin ω], [sin ω, cos ω]]
#   e_t  = |z_t|²                                          (energy)
#   capture_k = (1/β) log Σ_t exp(β e_{t,k})               (soft peak: the catch)
#   hold_k    = mean_t e_{t,k}                             (how long it was held)
#   profile   = [log1p(capture), log1p(hold)]              ∈ R^{2K}
#
# The backward pass is hand-derived BPTT through the recurrence.

class FetterBank:
    def __init__(self, K, seed):
        rng = np.random.default_rng(seed)
        self.K = K
        self.beta = 0.5
        # spread initial tempos across the band the six motions live in
        self.p = {
            "r": rng.uniform(-1.0, 2.0, size=K),                       # damping (pre-softplus)
            "w": np.sort(rng.uniform(0.05, 1.6, size=K)),              # angular tempo
            "b": rng.standard_normal((K, 2)) * 0.5,                    # input coupling
        }

    # ---- forward ----------------------------------------------------------
    def forward(self, U):
        """U: (B, T, K) drive. Returns profile (B, 3K) and a cache.
        profile = [log1p(capture), log1p(hold), moment]  per neuron, where
        capture = soft peak of energy, hold = mean energy, moment = soft-argmax
        time of the energy peak in [0,1] — WHEN the wild thing was caught."""
        B, T, K = U.shape
        r, w, b = self.p["r"], self.p["w"], self.p["b"]
        tgrid = (np.arange(T) + 0.5) / T                       # normalised time
        s = softplus(r) + 0.02
        a = np.exp(-s)
        c, sn = np.cos(w), np.sin(w)
        z = np.zeros((B, K, 2))
        Z = np.zeros((B, T, K, 2))
        for t in range(T):
            zx = a * (c * z[..., 0] - sn * z[..., 1]) + b[:, 0] * U[:, t, :]
            zy = a * (sn * z[..., 0] + c * z[..., 1]) + b[:, 1] * U[:, t, :]
            z = np.stack([zx, zy], -1)
            Z[:, t] = z
        E = (Z ** 2).sum(-1)                                   # (B, T, K)
        hold = E.mean(1)
        mx = E.max(1, keepdims=True)
        sm = np.exp(self.beta * (E - mx))
        sm = sm / sm.sum(1, keepdims=True)                     # softmax over time
        capture = mx[:, 0, :] + np.log(np.exp(self.beta * (E - mx)).sum(1)) / self.beta
        moment = (sm * tgrid[None, :, None]).sum(1)           # (B, K)
        P = np.concatenate([np.log1p(capture), np.log1p(hold), moment], -1)
        cache = dict(U=U, s=s, a=a, c=c, sn=sn, Z=Z, E=E, hold=hold, capture=capture,
                     mx=mx, sm=sm, moment=moment, tgrid=tgrid)
        return P, cache

    # ---- backward ---------------------------------------------------------
    def backward(self, dP, cache):
        """dP: (B, 3K). Returns grads dict and dU (B, T, K)."""
        U, a, c, sn, Z, E = cache["U"], cache["a"], cache["c"], cache["sn"], cache["Z"], cache["E"]
        hold, capture, sm, moment = cache["hold"], cache["capture"], cache["sm"], cache["moment"]
        tgrid = cache["tgrid"]
        B, T, K = U.shape
        r, w, b = self.p["r"], self.p["w"], self.p["b"]
        dcap = dP[:, :K] / (1.0 + capture)
        dhold = dP[:, K:2 * K] / (1.0 + hold)
        dmom = dP[:, 2 * K:]
        # d capture / dE_t = sm_t ;  d hold / dE_t = 1/T ;
        # d moment / dE_t = beta * sm_t * (t~ - moment)
        dE = (dcap[:, None, :] * sm
              + dhold[:, None, :] / T
              + dmom[:, None, :] * self.beta * sm * (tgrid[None, :, None] - moment[:, None, :]))
        dZ = 2.0 * dE[..., None] * Z
        dz_next = np.zeros((B, K, 2))
        dA = np.zeros((K, 2, 2)); db = np.zeros((K, 2)); dU = np.zeros_like(U)
        for t in range(T - 1, -1, -1):
            g = dZ[:, t] + dz_next
            zprev = Z[:, t - 1] if t > 0 else np.zeros((B, K, 2))
            dA += np.einsum("bki,bkj->kij", g, zprev)
            db += (g * U[:, t, :, None]).sum(0)
            dU[:, t, :] = (g * b[None]).sum(-1)
            gx = a * (c * g[..., 0] + sn * g[..., 1])
            gy = a * (-sn * g[..., 0] + c * g[..., 1])
            dz_next = np.stack([gx, gy], -1)
        R = np.stack([np.stack([c, -sn], -1), np.stack([sn, c], -1)], -2)
        Rp = np.stack([np.stack([-sn, -c], -1), np.stack([c, -sn], -1)], -2)
        dw = (dA * (a[:, None, None] * Rp)).sum((1, 2))
        da = (dA * R).sum((1, 2))
        dr = da * (-a) * sigmoid(r)
        return {"r": dr, "w": dw, "b": db}, dU

    # ---- descriptive --------------------------------------------------------
    def spectrum(self):
        s = softplus(self.p["r"]) + 0.02
        a = np.exp(-s)
        w = np.mod(self.p["w"], 2 * np.pi)
        w = np.where(w > np.pi, 2 * np.pi - w, w)          # fold to [0, π]
        period = np.where(w > 1e-6, 2 * np.pi / np.maximum(w, 1e-6), np.inf)
        return w, a, period


