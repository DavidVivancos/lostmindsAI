def gradient_check(kind, seed=7, n=5, eps=1e-5, tol=1e-6, max_entries=48):
    """Central finite differences over EVERY parameter tensor of the joint loss.
    For each tensor a random subset of entries (max_entries) is compared and the
    relative error is measured in the 2-norm, ||num - ana|| / (||num|| + ||ana||),
    which is the right statistic when many entries are legitimately near zero.
    Also reports the largest absolute entry-wise discrepancy seen anywhere."""
    model = QaydNetwork(kind=kind, K=8, H=6, HID=10, seed=seed)
    sb = make_simile_set(n, seed + 1)
    ab = make_atlal_set(n, seed + 2)
    # perturb the parameters so nothing sits at a symmetric point
    rng = np.random.default_rng(seed + 3)
    for k, v in model.p.items():
        v += 0.05 * rng.standard_normal(v.shape)
    tgt = ab["SIG"]                                    # a fixed label
    _, grads = model.total_loss(sb, ab, target=tgt)
    worst = 0.0; worst_name = ""; worst_abs = 0.0; n_entries = 0
    for name, P in model.p.items():
        G = np.broadcast_to(np.asarray(grads.get(name, np.zeros_like(P))), P.shape).reshape(-1)
        flat = P.reshape(-1)
        idxs = np.arange(flat.size)
        if flat.size > max_entries:
            idxs = rng.choice(flat.size, max_entries, replace=False)
        nums = np.zeros(len(idxs)); anas = np.zeros(len(idxs))
        for j, i in enumerate(idxs):
            o = flat[i]
            flat[i] = o + eps; lp, _ = model.total_loss(sb, ab, target=tgt)
            flat[i] = o - eps; lm, _ = model.total_loss(sb, ab, target=tgt)
            flat[i] = o
            nums[j] = (lp - lm) / (2 * eps)
            anas[j] = G[i]
        rel = np.linalg.norm(nums - anas) / (np.linalg.norm(nums) + np.linalg.norm(anas) + 1e-12)
        worst_abs = max(worst_abs, float(np.abs(nums - anas).max()))
        n_entries += len(idxs)
        if rel > worst:
            worst, worst_name = rel, name
    return worst, worst_name, worst < tol, worst_abs, n_entries


