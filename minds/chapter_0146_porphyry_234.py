# 3. SYNTHETIC WORLD:  classes generated by a latent tree of differentiae
# =============================================================================
def make_world(n_features=8, depth=3, n_per_class=60, indiv_frac=0.25, noise=0.35):
    """Build a dataset whose K = 2**depth species live at the leaves of a latent
    differentia tree.  Each internal node contributes a differentia direction;
    a leaf prototype is the signed sum of the differentiae on its path (exactly
    the Porphyrian "definition = genus + differentiae").  We then add:
      * definable species points  (t=1): prototype + gaussian jitter
      * ineffable individuals      (t=0): off-manifold points (large random shift)
      * summit points              (t=0): near-zero blends (undivided, generic)
    """
    K = 2 ** depth
    n_int = 2 ** depth - 1
    diffs = RNG.normal(0, 1.0, size=(n_int, n_features))

    def leaf_prototype(l):
        node, proto = 0, np.zeros(n_features)
        for d in range(depth):
            bit = (l >> (depth - 1 - d)) & 1     # 0 -> left(-), 1 -> right(+)
            proto += (1.0 if bit else -1.0) * diffs[node]
            node = 2 * node + 2 if bit else 2 * node + 1
        return proto

    protos = np.stack([leaf_prototype(l) for l in range(K)])

    X, Y, T = [], [], []
    for l in range(K):
        for _ in range(n_per_class):
            X.append(protos[l] + RNG.normal(0, noise, n_features))
            Y.append(l); T.append(1)
    # ineffable individuals: real but un-generic points far off the manifold
    n_indiv = int(indiv_frac * len(X))
    for _ in range(n_indiv):
        base = protos[RNG.integers(0, K)]
        X.append(base + RNG.normal(0, 2.5, n_features))  # accident-heavy, off-manifold
        Y.append(0); T.append(0)
    # summit points: generic, near the undivided genus
    for _ in range(n_indiv // 2):
        X.append(RNG.normal(0, 0.15, n_features))
        Y.append(0); T.append(0)

    X = np.array(X); Y = np.array(Y); T = np.array(T)
    perm = RNG.permutation(len(X))
    return X[perm], Y[perm], T[perm], protos


# =============================================================================
# 4. TRAINING LOOP  (Adam, from scratch)
# =============================================================================
def train():
    print("\n" + "-" * 74)
    print("TRAINING  the Diairetic Differentia Network on a latent-tree world")
    print("-" * 74)
    X, Y, T, protos = make_world(n_features=8, depth=3, n_per_class=60)
    ntr = int(0.8 * len(X))
    Xtr, Ytr, Ttr = X[:ntr], Y[:ntr], T[:ntr]
    Xte, Yte, Tte = X[ntr:], Y[ntr:], T[ntr:]

    net = DiaireticDifferentiaNetwork(n_features=8, depth=3)

    # Adam state
    m = {p: np.zeros_like(getattr(net, p)) for p in net.params}
    v = {p: np.zeros_like(getattr(net, p)) for p in net.params}
    b1, b2, lr, epsA = 0.9, 0.999, 0.02, 1e-8
    step = 0
    batch = 32
    epochs = 60

    def evaluate(Xs, Ys, Ts):
        correct = tot_def = 0
        pdef_species, pdef_indiv, recon_species = [], [], []
        for i in range(len(Xs)):
            _, c = net.forward(Xs[i], int(Ys[i]), int(Ts[i]))
            if Ts[i] == 1:
                tot_def += 1
                recon_species.append(c["recon_err"])   # essence only definable for species
                if np.argmax(c["leaf_prob"]) == Ys[i]:
                    correct += 1
                pdef_species.append(c["p_def"])
            else:
                pdef_indiv.append(c["p_def"])
        acc = correct / max(1, tot_def)
        return acc, float(np.mean(recon_species)), np.mean(pdef_species), np.mean(pdef_indiv)

    print(f"  train={len(Xtr)}  test={len(Xte)}  features=8  depth=3  "
          f"species(K)={net.K}  differentiae={net.n_int}")
    print(f"  {'epoch':>5} | {'loss':>7} | {'test_acc':>8} | {'recon':>7} | "
          f"{'p_def(species)':>14} | {'p_def(individual)':>16}")

    for ep in range(epochs):
        perm = RNG.permutation(len(Xtr))
        Xtr, Ytr, Ttr = Xtr[perm], Ytr[perm], Ttr[perm]
        ep_loss = 0.0
        nb = 0
        for s in range(0, len(Xtr), batch):
            xb, yb, tb = Xtr[s:s + batch], Ytr[s:s + batch], Ttr[s:s + batch]
            loss, grads = net.loss_and_grads(xb, yb, tb)
            ep_loss += loss; nb += 1
            step += 1
            for p in net.params:
                m[p] = b1 * m[p] + (1 - b1) * grads[p]
                v[p] = b2 * v[p] + (1 - b2) * grads[p] ** 2
                mhat = m[p] / (1 - b1 ** step)
                vhat = v[p] / (1 - b2 ** step)
                getattr(net, p)[...] -= lr * mhat / (np.sqrt(vhat) + epsA)
        if ep % 5 == 0 or ep == epochs - 1:
            acc, rec, ps, pi = evaluate(Xte, Yte, Tte)
            print(f"  {ep:5d} | {ep_loss/nb:7.3f} | {acc:8.3f} | {rec:7.3f} | "
                  f"{ps:14.3f} | {pi:16.3f}")

    return net, (Xte, Yte, Tte), evaluate


