# 5. SELF-TESTS
# =============================================================================
def self_tests(net, test, evaluate):
    print("\n" + "-" * 74)
    print("SELF-TESTS")
    print("-" * 74)
    Xte, Yte, Tte = test
    acc, rec, ps, pi = evaluate(Xte, Yte, Tte)

    # (a) descent works: species classification well above chance (1/K)
    chance = 1.0 / net.K
    print(f"  [a] descent/classification  acc={acc:.3f}  (chance={chance:.3f})  "
          f"{'OK' if acc > 4 * chance else 'LOW'}")
    assert acc > 4 * chance

    # (b) ascent works: reconstruction error is finite and small-ish
    print(f"  [b] ascent/reconstruction (species) recon_err={rec:.3f}  "
          f"{'OK' if rec < 5.0 else 'HIGH'}")
    assert np.isfinite(rec)

    # (c) Isagoge silence: definable species get HIGHER p_def than ineffable
    margin = ps - pi
    print(f"  [c] abstention separation   p_def(species)={ps:.3f} > "
          f"p_def(individual)={pi:.3f}   margin={margin:+.3f}  "
          f"{'OK' if margin > 0.1 else 'WEAK'}")
    assert margin > 0.1

    # (d) a clear individual is actually abstained on
    proto_indiv = Xte[np.where(Tte == 0)[0][0]]
    _, p_def_i = net.predict(proto_indiv)
    print(f"  [d] a sampled individual -> p_def={p_def_i:.3f}  "
          f"{'ABSTAIN (correct)' if p_def_i < 0.5 else 'defined'}")

    print("\n  All assertions passed.")


