# 6. DEMONSTRATION: read a single division off the trained tree
# =============================================================================
def demo_division(net, test):
    print("\n" + "-" * 74)
    print("A SINGLE DIAIRETIC DESCENT  (how the mind places one being)")
    print("-" * 74)
    Xte, Yte, Tte = test
    # choose a definable example the trained tree places correctly, for clarity
    i = np.where(Tte == 1)[0][0]
    for j in np.where(Tte == 1)[0]:
        _, cj = net.forward(Xte[j], int(Yte[j]), 1)
        if np.argmax(cj["leaf_prob"]) == Yte[j]:
            i = j
            break
    x = Xte[i]
    _, c = net.forward(x, int(Yte[i]), 1)
    g = c["g"]
    # walk the most-probable path from root to a leaf
    node, path = 0, []
    for d in range(net.D):
        go_right = g[node] > 0.5
        path.append((node, "present(+)" if go_right else "privation(-)", float(g[node])))
        node = net.right(node) if go_right else net.left(node)
    leaf = node - net.n_int
    print(f"  true species (leaf)     : {int(Yte[i])}")
    print(f"  predicted species (leaf): {leaf}   p_def={c['p_def']:.3f}")
    print("  chain of differentiae traversed (the definition):")
    for nid, sense, gate in path:
        print(f"     node {nid:2d}: differentia {sense:12s}  gate={gate:.2f}")
    print(f"  reconstruction residual (essence rebuilt from definition): "
          f"{c['recon_err']:.3f}")


