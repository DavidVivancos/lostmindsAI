# 2. FINITE-DIFFERENCE GRADIENT CHECK  (mandatory)
# =============================================================================
def gradient_check():
    print("-" * 74)
    print("GRADIENT CHECK  (analytic backprop vs central finite differences)")
    print("-" * 74)
    net = DiaireticDifferentiaNetwork(n_features=4, depth=2)   # tiny: 3 diffs, 4 leaves
    n = 5
    X = RNG.normal(size=(n, net.F))
    Y = RNG.integers(0, net.K, size=n)
    T = RNG.integers(0, 2, size=n)

    _, grads = net.loss_and_grads(X, Y, T)

    eps = 1e-6
    max_rel = 0.0
    for p in net.params:
        arr = getattr(net, p)
        flat = arr.reshape(-1)
        gflat = grads[p].reshape(-1)
        # check a handful of coordinates per parameter tensor
        idxs = range(flat.size) if flat.size <= 12 else RNG.choice(flat.size, 12, replace=False)
        for i in idxs:
            orig = flat[i]
            flat[i] = orig + eps
            lp, _ = net.loss_and_grads(X, Y, T)
            flat[i] = orig - eps
            lm, _ = net.loss_and_grads(X, Y, T)
            flat[i] = orig
            num = (lp - lm) / (2 * eps)
            ana = gflat[i]
            denom = max(1e-8, abs(num) + abs(ana))
            rel = abs(num - ana) / denom
            max_rel = max(max_rel, rel)
    print(f"  parameters checked : {', '.join(net.params)}")
    print(f"  max relative error : {max_rel:.3e}")
    ok = max_rel < 1e-5
    print(f"  RESULT             : {'PASS' if ok else 'FAIL'}  (threshold 1e-5)")
    assert ok, "Gradient check failed."
    return ok


