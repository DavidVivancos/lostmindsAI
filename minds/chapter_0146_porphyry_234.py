import numpy as np

RNG = np.random.default_rng(234)  # Porphyry's birth year, for reproducibility


# =============================================================================
# 1. THE MODEL: Diairetic Differentia Network
# =============================================================================
class DiaireticDifferentiaNetwork:
    """A soft binary division tree with a definition-decoder and an abstention
    (Isagoge-silence) head.

    Heap layout for a perfect binary tree of depth D:
      * internal nodes: indices 0 .. (2**D - 2)          (n_int = 2**D - 1)
      * leaves        : indices n_int .. n_int + 2**D - 1 (n_leaf = 2**D = K classes)
      * children of internal node n: left = 2n+1, right = 2n+2
    Each internal node n holds a differentia (W[n], b[n]); the gate
        g_n = sigmoid(x . W[n] + b[n])
    is the probability of taking the RIGHT branch ("the differentia is present").
    """

    def __init__(self, n_features, depth):
        self.F = n_features
        self.D = depth
        self.n_int = 2 ** depth - 1          # internal nodes (differentiae)
        self.K = 2 ** depth                  # leaves == infima species == classes
        s = 0.5 / np.sqrt(n_features)

        # --- Descent parameters: one differentia per internal node -----------
        self.W = RNG.normal(0, s, size=(self.n_int, self.F))   # differentia directions
        self.b = np.zeros(self.n_int)                          # differentia thresholds

        # --- Ascent parameters: decoder that rebuilds essence from the -------
        #     signed sum of traversed differentiae (the "definition") ---------
        self.Ddec = RNG.normal(0, s, size=(self.F, self.F))    # r -> x_hat
        self.edec = np.zeros(self.F)

        # --- Isagoge-silence head: definability logit from two signals -------
        #     [decisiveness, reconstruction_error, bias] -----------------------
        self.q = np.array([4.0, -4.0, 0.0])   # sensible init: decisive+low-error => definable

        self.params = ["W", "b", "Ddec", "edec", "q"]

    # ---- helpers ------------------------------------------------------------
    @staticmethod
    def _sigmoid(z):
        return 1.0 / (1.0 + np.exp(-np.clip(z, -60, 60)))

    def left(self, n):
        return 2 * n + 1

    def right(self, n):
        return 2 * n + 2

    # -------------------------------------------------------------------------
    # FORWARD (single example).  Returns loss and a cache for backprop.
    # -------------------------------------------------------------------------
    def forward(self, x, y, t, lam_rec=0.5, lam_def=1.0, eps=1e-9):
        """
        x : (F,) feature vector of the being to be placed in the tree
        y : int   true infima-species (leaf) index, valid only when t == 1
        t : {0,1} definability label   (1 = definable species, 0 = ineffable/summit)
        """
        F, D, n_int, K = self.F, self.D, self.n_int, self.K
        n_nodes = 2 * K - 1

        # ---- gates at every internal node (the differentiae firing) ----------
        z = self.W @ x + self.b                     # (n_int,)
        g = self._sigmoid(z)                        # prob RIGHT branch

        # ---- top-down reach probabilities ------------------------------------
        reach = np.zeros(n_nodes)
        reach[0] = 1.0
        for n in range(n_int):
            reach[self.left(n)] += reach[n] * (1.0 - g[n])
            reach[self.right(n)] += reach[n] * g[n]
        leaf_prob = reach[n_int:n_int + K]          # (K,) sums to 1 by construction

        # ---- ASCENT: signed differentia sum -> reconstruction ("definition") -
        signed = (2.0 * g - 1.0)                    # (n_int,)  +present / -privation
        r = (reach[:n_int] * signed) @ self.W       # (F,) soft sum of traversed diffs
        x_hat = self.Ddec @ r + self.edec           # (F,)
        diff = x_hat - x
        recon_err = 0.5 * float(diff @ diff)

        # ---- Isagoge-silence signals -----------------------------------------
        # decisiveness in [0,1]: how sharply the input was actually divided.
        # sum(reach over internal) == D exactly, so normalise by D.
        decis = float((reach[:n_int] * np.abs(signed)).sum()) / D
        logit_def = self.q[0] * decis + self.q[1] * recon_err + self.q[2]
        p_def = self._sigmoid(logit_def)

        # ---- losses ----------------------------------------------------------
        ce = -np.log(leaf_prob[y] + eps) if t == 1 else 0.0
        bce = -(t * np.log(p_def + eps) + (1 - t) * np.log(1.0 - p_def + eps))
        loss = t * (ce + lam_rec * recon_err) + lam_def * bce

        cache = dict(x=x, y=y, t=t, g=g, reach=reach, signed=signed, r=r,
                     x_hat=x_hat, diff=diff, recon_err=recon_err, decis=decis,
                     p_def=p_def, leaf_prob=leaf_prob, lam_rec=lam_rec,
                     lam_def=lam_def)
        return loss, cache

    # -------------------------------------------------------------------------
    # BACKWARD (single example).  Returns dict of gradients matching self.params
    # -------------------------------------------------------------------------
    def backward(self, cache, eps=1e-9):
        F, D, n_int, K = self.F, self.D, self.n_int, self.K
        n_nodes = 2 * K - 1
        x, y, t = cache["x"], cache["y"], cache["t"]
        g, reach, signed = cache["g"], cache["reach"], cache["signed"]
        r, x_hat, diff = cache["r"], cache["x_hat"], cache["diff"]
        recon_err, decis, p_def = cache["recon_err"], cache["decis"], cache["p_def"]
        lam_rec, lam_def = cache["lam_rec"], cache["lam_def"]

        gW = np.zeros_like(self.W)
        gb = np.zeros_like(self.b)
        gDdec = np.zeros_like(self.Ddec)
        gedec = np.zeros_like(self.edec)
        gq = np.zeros_like(self.q)

        # ---- head: definability BCE -> logit ---------------------------------
        dlogit = lam_def * (p_def - t)              # dL/dlogit_def
        gq[0] += dlogit * decis
        gq[1] += dlogit * recon_err
        gq[2] += dlogit * 1.0

        # ---- reconstruction error feeds BOTH the loss and the logit ----------
        # dL/drecon_err = t*lam_rec (loss term) + dlogit * q1 (silence signal)
        alpha_rec = t * lam_rec + dlogit * self.q[1]
        dxhat = alpha_rec * diff                    # dL/dx_hat = alpha_rec*(x_hat-x)
        gDdec += np.outer(dxhat, r)
        gedec += dxhat
        grad_r = self.Ddec.T @ dxhat                # dL/dr

        # ---- decisiveness signal ---------------------------------------------
        grad_decis = dlogit * self.q[0]             # dL/ddecis

        # ---- classification CE -> leaf probs ---------------------------------
        grad_leaf = np.zeros(K)
        if t == 1:
            grad_leaf[y] = -1.0 / (cache["leaf_prob"][y] + eps)

        # ---- reverse pass over the tree to get dL/dreach and dL/dg -----------
        grad_reach = np.zeros(n_nodes)
        grad_g = np.zeros(n_int)

        # leaves first
        for l in range(K):
            grad_reach[n_int + l] += grad_leaf[l]

        # internal nodes, children (higher index) before parents
        for n in range(n_int - 1, -1, -1):
            L, Rn = self.left(n), self.right(n)

            # reach[n] used directly in r and in decisiveness
            grad_reach[n] += grad_r @ (signed[n] * self.W[n])          # via r
            grad_reach[n] += grad_decis * (abs(signed[n]) / D)          # via decis
            # reach[n] propagates into children's reach
            grad_reach[n] += grad_reach[L] * (1.0 - g[n]) + grad_reach[Rn] * g[n]

            # g[n] uses:
            #  (i) via r term reach[n]*(2g-1)*W[n]  -> d/dg = reach[n]*2*W[n]
            grad_g[n] += grad_r @ (reach[n] * 2.0 * self.W[n])
            #  (ii) via decisiveness reach[n]*|2g-1|/D -> d/dg = reach[n]*2*sign/D
            grad_g[n] += grad_decis * (reach[n] * 2.0 * np.sign(signed[n]) / D)
            #  (iii) via children reach:  reach[L]=reach[n]*(1-g), reach[R]=reach[n]*g
            grad_g[n] += grad_reach[L] * (-reach[n]) + grad_reach[Rn] * (reach[n])

        # ---- g -> z -> (W, b), plus W's direct appearance in r ---------------
        gz = grad_g * g * (1.0 - g)                 # sigmoid'
        for n in range(n_int):
            gW[n] += gz[n] * x                                   # via gate pre-activation
            gW[n] += grad_r * (reach[n] * signed[n])            # W's direct role in r
            gb[n] += gz[n]

        return dict(W=gW, b=gb, Ddec=gDdec, edec=gedec, q=gq)

    # -------------------------------------------------------------------------
    # Batch convenience wrappers
    # -------------------------------------------------------------------------
    def loss_and_grads(self, X, Y, T, **kw):
        n = X.shape[0]
        total = 0.0
        grads = {p: np.zeros_like(getattr(self, p)) for p in self.params}
        for i in range(n):
            loss, cache = self.forward(X[i], int(Y[i]), int(T[i]), **kw)
            total += loss
            gi = self.backward(cache)
            for p in self.params:
                grads[p] += gi[p]
        for p in self.params:
            grads[p] /= n
        return total / n, grads

    def predict(self, x):
        """Return (species_index, p_def).  Abstain when p_def < 0.5."""
        _, cache = self.forward(x, 0, 1)
        return int(np.argmax(cache["leaf_prob"])), float(cache["p_def"])


