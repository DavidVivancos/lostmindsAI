# SECTION 5 — ProbeCommitGate  (encodes fact #1: Hiyodorigoe — cheap probe,
# then irreversible full commitment)
# ==============================================================================

class ProbeCommitGate:
    """Docstring fact: Hiyodorigoe descent, Ichi-no-Tani 1184 — riderless
    horses sent down first as a cheap probe; only a favorable probe licenses
    full, irreversible commitment of the mounted force.

    The probe is deliberately cheap (one linear map, no hidden layer) but it
    is NOT blind: it reads mean-pooled formation features PLUS a single
    scalar "feasibility" signal -- how confidently the LeverageScorer has
    already isolated a small set of high-leverage units (analogous to
    testing whether the slope will hold at all before committing riders).
    A probe fed only raw noise has nothing to decide with; a probe fed a
    feasibility read is a probe in the tactical sense Yoshitsune's scouts
    were performing."""

    def __init__(self, d_in, d_proj):
        d_probe_in = d_in + 1  # + feasibility scalar
        limit_p = np.sqrt(6.0 / (d_probe_in + 1))
        limit_s = np.sqrt(6.0 / (d_in + d_proj))
        limit_n = np.sqrt(6.0 / (d_in + d_proj))
        self.params = {
            "Wprobe": rng.uniform(-limit_p, limit_p, (d_probe_in, 1)),
            "bprobe": np.array([0.4]),  # mild prior toward committing
            "Wstrike": rng.uniform(-limit_s, limit_s, (d_in, d_proj)),
            "bstrike": np.zeros(d_proj),
            "Wnaive": rng.uniform(-limit_n, limit_n, (d_in, d_proj)),
            "bnaive": np.zeros(d_proj),
        }

    def forward(self, mean_pooled, strike_raw, feasibility, cache):
        """
        mean_pooled : (B, d_in) uniform mean of all unit features (the
                      "symmetric, aristocratic-duel" baseline representation)
        strike_raw  : (B, d_in) leverage-weighted sum of unit features (the
                      "asymmetric, function-targeting" representation)
        feasibility : (B,) scalar feasibility read (max leverage confidence)
        Returns blended: (B, d_proj)
        """
        Wprobe, bprobe = self.params["Wprobe"], self.params["bprobe"]
        Wstrike, bstrike = self.params["Wstrike"], self.params["bstrike"]
        Wnaive, bnaive = self.params["Wnaive"], self.params["bnaive"]

        probe_in = np.concatenate([mean_pooled, feasibility[:, None]], axis=1)  # (B, d_in+1)
        probe_logit = (probe_in @ Wprobe + bprobe)[..., 0]   # (B,)  <- CHEAP: linear only
        g = sigmoid(probe_logit)                              # (B,) probability of commitment

        strike_pre = strike_raw @ Wstrike + bstrike                # (B,d_proj)
        strike_repr = relu(strike_pre)
        naive_pre = mean_pooled @ Wnaive + bnaive                  # (B,d_proj)
        naive_repr = relu(naive_pre)

        blended = g[:, None] * strike_repr + (1.0 - g[:, None]) * naive_repr

        cache["pcg.mean_pooled"] = mean_pooled
        cache["pcg.strike_raw"] = strike_raw
        cache["pcg.probe_in"] = probe_in
        cache["pcg.g"] = g
        cache["pcg.strike_pre"] = strike_pre
        cache["pcg.strike_repr"] = strike_repr
        cache["pcg.naive_pre"] = naive_pre
        cache["pcg.naive_repr"] = naive_repr
        return blended, g

    def backward(self, d_blended, cache, grads):
        mean_pooled = cache["pcg.mean_pooled"]
        strike_raw = cache["pcg.strike_raw"]
        probe_in = cache["pcg.probe_in"]
        g = cache["pcg.g"]
        strike_pre, strike_repr = cache["pcg.strike_pre"], cache["pcg.strike_repr"]
        naive_pre, naive_repr = cache["pcg.naive_pre"], cache["pcg.naive_repr"]
        Wstrike, Wnaive, Wprobe = self.params["Wstrike"], self.params["Wnaive"], self.params["Wprobe"]

        d_strike_repr = d_blended * g[:, None]
        d_naive_repr = d_blended * (1.0 - g[:, None])
        d_g = np.sum(d_blended * (strike_repr - naive_repr), axis=1)  # (B,)

        d_strike_pre = d_strike_repr * d_relu_from_input(strike_pre)
        grads["pcg.bstrike"] = d_strike_pre.sum(axis=0)
        grads["pcg.Wstrike"] = strike_raw.T @ d_strike_pre
        d_strike_raw = d_strike_pre @ Wstrike.T

        d_naive_pre = d_naive_repr * d_relu_from_input(naive_pre)
        grads["pcg.bnaive"] = d_naive_pre.sum(axis=0)
        grads["pcg.Wnaive"] = mean_pooled.T @ d_naive_pre
        d_mean_pooled_from_naive = d_naive_pre @ Wnaive.T

        d_probe_logit = d_g * d_sigmoid_from_output(g)                 # (B,)
        grads["pcg.bprobe"] = d_probe_logit.sum(axis=0, keepdims=True)
        grads["pcg.Wprobe"] = probe_in.T @ d_probe_logit[:, None]
        d_probe_in = d_probe_logit[:, None] * Wprobe[:, 0]              # (B, d_in+1)
        d_mean_pooled_from_probe = d_probe_in[:, :-1]
        d_feasibility = d_probe_in[:, -1]

        d_mean_pooled = d_mean_pooled_from_naive + d_mean_pooled_from_probe
        return d_mean_pooled, d_strike_raw, d_feasibility


# ==============================================================================
# SECTION 6 — HiyodorigoeNet: assembles Sections 3-5 + a final classifier head
# + the economy-of-force loss (spread penalty on strike_weights)
# ==============================================================================

class HiyodorigoeNet:
    """
    Full model. Two auxiliary/primary heads:
      - outcome head:   P(strike breaks the formation)      <- primary
      - leverage head:  P(unit n is a true leverage unit)    <- auxiliary,
        supervises LeverageScorer directly so its targeting stays
        interpretable rather than collapsing to an unconstrained latent.

    Loss = BCE(outcome) + lam_leverage * BCE(leverage)
           + lam_econ * mean_entropy(strike_weights)
    The entropy term is the "economy of force" pressure: driving DOWN the
    entropy of strike_weights rewards concentrating the targeted-strike
    representation on as few units as necessary, mirroring the doctrine that
    a commander should not spend force beyond what the objective requires.
    """

    def __init__(self, feat_dim=FEATURE_DIM, n_units=N_UNITS, units_per_axis=UNITS_PER_AXIS,
                 h_lev=6, h_axis=10, h_proj=16, h_out=16,
                 lam_leverage=0.15, lam_econ=0.02):
        self.feat_dim = feat_dim
        self.n_units = n_units
        self.lam_leverage = lam_leverage
        self.lam_econ = lam_econ

        self.leverage_scorer = LeverageScorer(feat_dim, h_lev)
        self.multi_axis = MultiAxisRendezvous(units_per_axis, feat_dim, h_axis)
        self.probe_commit = ProbeCommitGate(feat_dim, h_proj)

        combine_dim = h_axis + h_proj
        limit1 = np.sqrt(6.0 / (combine_dim + h_out))
        limit2 = np.sqrt(6.0 / (h_out + 1))
        self.params_out = {
            "W1": rng.uniform(-limit1, limit1, (combine_dim, h_out)),
            "b1": np.zeros(h_out),
            "W2": rng.uniform(-limit2, limit2, (h_out, 1)),
            "b2": np.zeros(1),
        }

    # ---- parameter (de)serialization, needed by optimizer + gradcheck ----
    def all_params(self):
        d = {}
        for prefix, obj in (("lev", self.leverage_scorer), ("mar", self.multi_axis),
                             ("pcg", self.probe_commit)):
            for k, v in obj.params.items():
                d[f"{prefix}.{k}"] = v
        for k, v in self.params_out.items():
            d[f"out.{k}"] = v
        return d

    def set_param(self, name, value):
        prefix, key = name.split(".", 1)
        target = {"lev": self.leverage_scorer, "mar": self.multi_axis,
                  "pcg": self.probe_commit}.get(prefix)
        if target is not None:
            target.params[key] = value
        else:
            self.params_out[key] = value

    # ---- forward ----
    def forward(self, X, cache=None):
        """X: (B, N, feat_dim). Returns p_outcome (B,), leverage_prob (B,N)."""
        if cache is None:
            cache = {}
        B, N, d = X.shape

        lev_logit, strike_weights, leverage_prob = self.leverage_scorer.forward(X, cache)

        mean_pooled = X.mean(axis=1)                                    # (B,d)
        strike_raw = np.einsum("bn,bnd->bd", strike_weights, X)          # (B,d)

        feasibility_argmax = np.argmax(leverage_prob, axis=1)            # (B,)
        feasibility = leverage_prob[np.arange(B), feasibility_argmax]    # (B,)
        cache["out.feasibility_argmax"] = feasibility_argmax

        fused = self.multi_axis.forward(X, cache)                       # (B,h_axis)
        blended, g = self.probe_commit.forward(mean_pooled, strike_raw, feasibility, cache)  # (B,h_proj)

        combined = np.concatenate([fused, blended], axis=1)             # (B, h_axis+h_proj)
        W1, b1, W2, b2 = (self.params_out[k] for k in ("W1", "b1", "W2", "b2"))
        O1_pre = combined @ W1 + b1
        O1 = relu(O1_pre)
        logit_out = (O1 @ W2 + b2)[..., 0]
        p_outcome = sigmoid(logit_out)

        cache["out.mean_pooled"] = mean_pooled
        cache["out.strike_raw"] = strike_raw
        cache["out.combined"] = combined
        cache["out.O1_pre"] = O1_pre
        cache["out.O1"] = O1
        cache["out.p_outcome"] = p_outcome
        cache["out.strike_weights"] = strike_weights
        cache["out.leverage_prob"] = leverage_prob
        cache["out.commit_gate_g"] = g
        cache["X"] = X
        return p_outcome, leverage_prob, cache

    # ---- loss ----
    def compute_loss(self, X, y_outcome, y_leverage, cache=None):
        p_outcome, leverage_prob, cache = self.forward(X, cache)
        strike_weights = cache["out.strike_weights"]

        loss_outcome, dP_outcome = bce_loss_and_grad(p_outcome, y_outcome)
        loss_leverage, dLevProb = bce_loss_and_grad(leverage_prob, y_leverage)

        eps = 1e-9
        entropy_per_ex = -np.sum(strike_weights * np.log(strike_weights + eps), axis=1)  # (B,)
        loss_econ = np.mean(entropy_per_ex)
        # d(loss_econ)/d(strike_weights) : d/dw [-w log w] = -(log w + 1), averaged over B
        B = strike_weights.shape[0]
        d_entropy_d_w = -(np.log(strike_weights + eps) + 1.0) / B

        total = loss_outcome + self.lam_leverage * loss_leverage + self.lam_econ * loss_econ

        grad_signals = {
            "dP_outcome": dP_outcome,
            "dLevProb": dLevProb * self.lam_leverage,
            "d_entropy_d_w": d_entropy_d_w * self.lam_econ,
        }
        metrics = {
            "loss_total": total, "loss_outcome": loss_outcome,
            "loss_leverage": loss_leverage, "loss_econ": loss_econ,
        }
        return total, grad_signals, cache, metrics, p_outcome, leverage_prob

    # ---- backward ----
    def backward(self, grad_signals, cache):
        grads = {}
        dP_outcome = grad_signals["dP_outcome"]              # (B,)
        p_outcome = cache["out.p_outcome"]
        O1, O1_pre, combined = cache["out.O1"], cache["out.O1_pre"], cache["out.combined"]
        W1, W2 = self.params_out["W1"], self.params_out["W2"]

        d_logit_out = dP_outcome * d_sigmoid_from_output(p_outcome)     # (B,)
        grads["out.b2"] = d_logit_out.sum(axis=0, keepdims=True)
        grads["out.W2"] = O1.T @ d_logit_out[:, None]
        dO1 = d_logit_out[:, None] * W2[:, 0]                            # (B,h_out)
        dO1_pre = dO1 * d_relu_from_input(O1_pre)
        grads["out.b1"] = dO1_pre.sum(axis=0)
        grads["out.W1"] = combined.T @ dO1_pre
        d_combined = dO1_pre @ W1.T                                      # (B, h_axis+h_proj)

        h_axis = self.multi_axis.d_hidden
        d_fused = d_combined[:, :h_axis]
        d_blended = d_combined[:, h_axis:]

        d_mean_pooled_a, d_strike_raw, d_feasibility = self.probe_commit.backward(d_blended, cache, grads)
        d_Xg_from_axis = self.multi_axis.backward(d_fused, cache, grads)

        # ---- route gradient back into strike_weights and X ----
        # strike_raw = sum_n strike_weights[:,n] * X[:,n,:]
        X = cache["X"]
        B, N, d = X.shape
        d_strike_weights = np.einsum("bd,bnd->bn", d_strike_raw, X)      # (B,N)
        d_X_from_strike = np.einsum("bn,bd->bnd", cache["out.strike_weights"], d_strike_raw)

        # mean_pooled = mean_n X[:,n,:]
        d_X_from_meanpool = np.repeat((d_mean_pooled_a / N)[:, None, :], N, axis=1)

        # multi-axis path: Xg = X.reshape(B,G,units_per_axis*d) -> reshape back
        G = cache["mar.G"]
        d_X_from_axis = d_Xg_from_axis.reshape(B, N, d)

        # ---- leverage head: combine ALL gradients into lev_logit ----
        strike_weights = cache["out.strike_weights"]
        d_entropy_d_w = grad_signals["d_entropy_d_w"]            # (B,N) economy-of-force term
        d_w_total = d_strike_weights + d_entropy_d_w             # (B,N)
        d_lev_logit_from_strike = d_softmax_backward(
            strike_weights, d_w_total, axis=1
        ) / self.leverage_scorer.temperature

        leverage_prob = cache["out.leverage_prob"]
        d_lev_logit_from_aux = grad_signals["dLevProb"] * d_sigmoid_from_output(leverage_prob)

        feasibility_argmax = cache["out.feasibility_argmax"]
        d_leverage_prob_feas = np.zeros_like(leverage_prob)
        d_leverage_prob_feas[np.arange(B), feasibility_argmax] = d_feasibility
        d_lev_logit_from_feasibility = d_leverage_prob_feas * d_sigmoid_from_output(leverage_prob)

        d_lev_logit_total = d_lev_logit_from_strike + d_lev_logit_from_aux + d_lev_logit_from_feasibility
        d_X_from_lev = self.leverage_scorer.backward(d_lev_logit_total, cache, grads)

        # total dX not needed further (X is the input), but kept for
        # completeness / potential upstream layers:
        d_X_total = d_X_from_strike + d_X_from_meanpool + d_X_from_axis + d_X_from_lev
        return grads, d_X_total


