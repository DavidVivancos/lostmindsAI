# SECTION 7 — ADAM OPTIMIZER (from scratch)
# ==============================================================================

class Adam:
    def __init__(self, params_dict, lr=3e-3, beta1=0.9, beta2=0.999, eps=1e-8, weight_decay=0.0):
        self.lr, self.b1, self.b2, self.eps = lr, beta1, beta2, eps
        self.weight_decay = weight_decay
        self.m = {k: np.zeros_like(v) for k, v in params_dict.items()}
        self.v = {k: np.zeros_like(v) for k, v in params_dict.items()}
        self.t = 0

    def step(self, model, grads):
        self.t += 1
        params = model.all_params()
        for k, g in grads.items():
            if k not in params:
                continue
            p = params[k]
            if g.shape != p.shape:
                g = g.reshape(p.shape)
            self.m[k] = self.b1 * self.m[k] + (1 - self.b1) * g
            self.v[k] = self.b2 * self.v[k] + (1 - self.b2) * (g * g)
            m_hat = self.m[k] / (1 - self.b1 ** self.t)
            v_hat = self.v[k] / (1 - self.b2 ** self.t)
            # decoupled L2 weight decay (AdamW-style), keeps overfitting in
            # check without corrupting the analytic gradient used elsewhere
            new_p = p - self.lr * (m_hat / (np.sqrt(v_hat) + self.eps) + self.weight_decay * p)
            model.set_param(k, new_p)


# ==============================================================================
# SECTION 8 — FINITE-DIFFERENCE GRADIENT CHECK (mandatory before training)
# ==============================================================================

def gradient_check(model, X, y_outcome, y_leverage, n_probes_per_param=3,
                    epsilon=1e-5, tolerance=3e-3, verbose=True):
    """
    For a random sample of scalar entries within EVERY parameter array, compare
    the analytic gradient (from model.backward) against the central-difference
    numerical gradient of the total loss. Returns (all_passed: bool, report: list).
    """
    _, grad_signals, cache, _, _, _ = model.compute_loss(X, y_outcome, y_leverage)
    analytic_grads, _ = model.backward(grad_signals, cache)

    def loss_only(Xb, yob, ylb):
        total, _, _, _, _, _ = model.compute_loss(Xb, yob, ylb)
        return total

    params = model.all_params()
    report = []
    all_passed = True
    check_rng = np.random.default_rng(0)

    for name, p in params.items():
        if name not in analytic_grads:
            continue
        a_grad_full = analytic_grads[name]
        if a_grad_full.shape != p.shape:
            a_grad_full = a_grad_full.reshape(p.shape)
        flat_size = p.size
        n_probe = min(n_probes_per_param, flat_size)
        idxs = check_rng.choice(flat_size, size=n_probe, replace=False)

        for flat_idx in idxs:
            multi_idx = np.unravel_index(flat_idx, p.shape)
            orig = p[multi_idx]

            p[multi_idx] = orig + epsilon
            loss_plus = loss_only(X, y_outcome, y_leverage)
            p[multi_idx] = orig - epsilon
            loss_minus = loss_only(X, y_outcome, y_leverage)
            p[multi_idx] = orig

            numeric_grad = (loss_plus - loss_minus) / (2 * epsilon)
            analytic = a_grad_full[multi_idx]
            denom = max(abs(numeric_grad), abs(analytic), 1e-8)
            rel_err = abs(numeric_grad - analytic) / denom
            passed = rel_err < tolerance
            all_passed &= passed
            report.append((name, multi_idx, numeric_grad, analytic, rel_err, passed))

    if verbose:
        print(f"{'param':<12}{'index':<14}{'numeric':>13}{'analytic':>13}{'rel_err':>12}  ok")
        for name, idx, num, ana, err, ok in report:
            print(f"{name:<12}{str(idx):<14}{num:>13.6f}{ana:>13.6f}{err:>12.2e}  {ok}")
        n_ok = sum(1 for r in report if r[-1])
        print(f"\nGradient check: {n_ok}/{len(report)} probes within tolerance {tolerance}.")
    return all_passed, report


