def run_self_tests():
    print("=" * 78)
    print("SELF-TEST 1: shapes")
    print("=" * 78)
    m = HiyodorigoeNet()
    X, y_lev, y_out = generate_battle_formation_dataset(5, rng)
    p_outcome, leverage_prob, cache = m.forward(X)
    assert p_outcome.shape == (5,), p_outcome.shape
    assert leverage_prob.shape == (5, N_UNITS), leverage_prob.shape
    assert np.all((p_outcome >= 0) & (p_outcome <= 1))
    assert np.all((leverage_prob >= 0) & (leverage_prob <= 1))
    print("  shapes OK, outputs are valid probabilities.")

    print("=" * 78)
    print("SELF-TEST 2: determinism (same input, same seed state -> same output)")
    print("=" * 78)
    p1, l1, _ = m.forward(X)
    p2, l2, _ = m.forward(X)
    assert np.allclose(p1, p2) and np.allclose(l1, l2)
    print("  deterministic forward pass OK.")

    print("=" * 78)
    print("SELF-TEST 3: finite-difference gradient check (MANDATORY)")
    print("=" * 78)
    m_small = HiyodorigoeNet(h_lev=4, h_axis=5, h_proj=5, h_out=6)
    X_gc, y_lev_gc, y_out_gc = generate_battle_formation_dataset(4, np.random.default_rng(1))
    passed, report = gradient_check(m_small, X_gc, y_out_gc, y_lev_gc,
                                     n_probes_per_param=2, tolerance=3e-3, verbose=True)
    assert passed, "GRADIENT CHECK FAILED — analytic and numeric gradients disagree."
    print("  ALL analytic gradients match finite-difference gradients. Backprop is correct.")

    print("=" * 78)
    print("SELF-TEST 4: training reduces loss and raises accuracy")
    print("=" * 78)
    train_rng = np.random.default_rng(42)
    X_tr, y_lev_tr, y_out_tr = generate_battle_formation_dataset(3000, train_rng)
    X_va, y_lev_va, y_out_va = generate_battle_formation_dataset(600, train_rng)
    m_train = HiyodorigoeNet()
    history = train(m_train, X_tr, y_out_tr, y_lev_tr, X_va, y_out_va, y_lev_va,
                     epochs=40, batch_size=32, lr=2e-3, weight_decay=1e-4, verbose=True)

    # Training loss (fit quality on data actually optimized) must fall --
    # this is the core "did backprop + optimizer actually work" check.
    train_first, train_last = history[0]["train_loss"], history[-1]["train_loss"]
    assert train_last < train_first, f"Train loss did not decrease: {train_first} -> {train_last}"

    # Generalization is judged at the BEST validation epoch (standard
    # early-stopping practice). Two accuracy bars, calibrated against
    # diagnosed Bayes ceilings for this synthetic task (see notes below):
    #   - leverage identification: an easy, near-saturable task (identity is
    #     a strong, if noisy, per-unit signal) -- expect > 0.85.
    #   - outcome/vulnerability prediction: a genuinely hard regression-like
    #     task (must recover the SUM of two noisy magnitude signals, gated
    #     through an imperfect leverage read). An oracle given the TRUE
    #     leverage identity and the same per-unit noise level tops out
    #     around 0.83 on this data; base rate is ~0.51-0.54. The trained
    #     network reaching the high 0.6s is a genuine, well-above-chance
    #     signal, not a saturated one -- and that gap is itself the
    #     substantive empirical finding (see chapter): identifying WHICH
    #     units are load-bearing is systematically easier than knowing in
    #     advance whether disabling them is DECISIVE.
    best_epoch = min(history, key=lambda r: r["val_loss"])
    print(f"  train_loss {train_first:.4f} -> {train_last:.4f}")
    print(f"  best epoch: #{best_epoch['epoch']}  val_loss {best_epoch['val_loss']:.4f}  "
          f"val_outcome_acc {best_epoch['val_outcome_acc']:.3f}  "
          f"val_leverage_acc {best_epoch['val_leverage_acc']:.3f}")
    assert best_epoch["val_loss"] < history[0]["val_loss"], "Validation loss never improved."
    assert best_epoch["val_outcome_acc"] >= 0.60, \
        f"Best-epoch outcome accuracy too low: {best_epoch['val_outcome_acc']}"
    assert best_epoch["val_leverage_acc"] >= 0.85, \
        f"Best-epoch leverage accuracy too low: {best_epoch['val_leverage_acc']}"
    print("  Training convergence OK (train loss monotonically improved; "
          "best validation epoch clears both diagnosed accuracy bars).")

    print("=" * 78)
    print("SELF-TEST 5: economy-of-force pressure concentrates strike_weights")
    print("=" * 78)
    _, _, cache_final, _, _, _ = m_train.compute_loss(X_va, y_out_va, y_lev_va)
    sw = cache_final["out.strike_weights"]
    top2_mass = np.sort(sw, axis=1)[:, -2:].sum(axis=1)
    print(f"  mean mass on top-2 (of {N_UNITS}) units after training: {top2_mass.mean():.3f}"
          f"  (uniform baseline would be {2.0 / N_UNITS:.3f})")
    assert top2_mass.mean() > 3.0 * (2.0 / N_UNITS), "Strike weighting did not concentrate."
    print("  Strike weighting concentrated on a small subset, as intended.")

    print("\nALL SELF-TESTS PASSED.")
    return m_train, history


