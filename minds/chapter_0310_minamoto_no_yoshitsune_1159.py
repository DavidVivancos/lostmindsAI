# SECTION 9 — TRAINING LOOP
# ==============================================================================

def accuracy_metrics(p_outcome, y_outcome, leverage_prob, y_leverage):
    outcome_acc = np.mean((p_outcome > 0.5).astype(np.float64) == y_outcome)
    leverage_acc = np.mean((leverage_prob > 0.5).astype(np.float64) == y_leverage)
    return outcome_acc, leverage_acc


def train(model, X_train, y_out_train, y_lev_train, X_val, y_out_val, y_lev_val,
          epochs=60, batch_size=32, lr=3e-3, weight_decay=0.0, verbose=True):
    optimizer = Adam(model.all_params(), lr=lr, weight_decay=weight_decay)
    n = X_train.shape[0]
    history = []

    for epoch in range(epochs):
        perm = rng.permutation(n)
        epoch_loss = 0.0
        n_batches = 0
        for start in range(0, n, batch_size):
            idx = perm[start:start + batch_size]
            Xb, yob, ylb = X_train[idx], y_out_train[idx], y_lev_train[idx]
            total, grad_signals, cache, metrics, _, _ = model.compute_loss(Xb, yob, ylb)
            grads, _ = model.backward(grad_signals, cache)
            optimizer.step(model, grads)
            epoch_loss += metrics["loss_total"]
            n_batches += 1
        epoch_loss /= n_batches

        p_val, lev_val, _ = model.forward(X_val)
        val_loss, _, _, val_metrics, _, _ = model.compute_loss(X_val, y_out_val, y_lev_val)
        outcome_acc, leverage_acc = accuracy_metrics(p_val, y_out_val, lev_val, y_lev_val)
        history.append({
            "epoch": epoch, "train_loss": epoch_loss, "val_loss": val_metrics["loss_total"],
            "val_outcome_acc": outcome_acc, "val_leverage_acc": leverage_acc,
        })
        if verbose and (epoch % 5 == 0 or epoch == epochs - 1):
            print(f"epoch {epoch:3d}  train_loss {epoch_loss:.4f}  val_loss {val_metrics['loss_total']:.4f}"
                  f"  val_outcome_acc {outcome_acc:.3f}  val_leverage_acc {leverage_acc:.3f}")
    return history


