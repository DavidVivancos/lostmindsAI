# SECTION 4 — MultiAxisRendezvous  (encodes fact #3: Ichi-no-Tani, geographically
# separated forces that fuse only at a scheduled convergence, not continuous
# cross-observation)
# ==============================================================================

class MultiAxisRendezvous:
    """Docstring fact: Ichi-no-Tani, 1184 — Noriyori's front force and
    Yoshitsune's cliff detachment strike on separate axes and converge on a
    schedule; they do not continuously observe each other mid-engagement."""

    def __init__(self, units_per_axis, feat_dim, d_hidden):
        d_in = units_per_axis * feat_dim
        limit1 = np.sqrt(6.0 / (d_in + d_hidden))
        limit2 = np.sqrt(6.0 / (d_hidden + d_hidden))
        limit3 = np.sqrt(6.0 / (d_hidden + 1))
        self.params = {
            "W1": rng.uniform(-limit1, limit1, (d_in, d_hidden)),
            "b1": np.zeros(d_hidden),
            "W2": rng.uniform(-limit2, limit2, (d_hidden, d_hidden)),
            "b2": np.zeros(d_hidden),
            "Wr": rng.uniform(-limit3, limit3, (d_hidden, 1)),
            "br": np.zeros(1),
        }
        self.units_per_axis = units_per_axis
        self.d_hidden = d_hidden

    def forward(self, X, cache):
        """
        X: (B, N, feat_dim) -> grouped into G axes of `units_per_axis` units.
        Each axis is encoded independently (SAME shared weights, but the
        forward pass never lets axis g see axis g' — no cross terms) into an
        axis vector. A learned "rendezvous" gate (softmax over axes) then
        fuses the axis vectors into one representation.
        Returns fused: (B, d_hidden)
        """
        W1, b1, W2, b2, Wr, br = (self.params[k] for k in ("W1", "b1", "W2", "b2", "Wr", "br"))
        B, N, d = X.shape
        G = N // self.units_per_axis
        Xg = X.reshape(B, G, self.units_per_axis * d)      # (B,G,d_in) -- no cross-axis mixing

        H1 = tanh(Xg @ W1 + b1)                             # (B,G,h)
        axis_vec = tanh(H1 @ W2 + b2)                        # (B,G,h)
        rendez_logit = (axis_vec @ Wr + br)[..., 0]          # (B,G)
        rendez_w = softmax(rendez_logit, axis=1)             # (B,G)
        fused = np.einsum("bg,bgh->bh", rendez_w, axis_vec)  # (B,h)

        cache["mar.Xg"] = Xg
        cache["mar.H1"] = H1
        cache["mar.axis_vec"] = axis_vec
        cache["mar.rendez_w"] = rendez_w
        cache["mar.G"] = G
        return fused

    def backward(self, d_fused, cache, grads):
        Xg, H1, axis_vec, rendez_w = (
            cache["mar.Xg"], cache["mar.H1"], cache["mar.axis_vec"], cache["mar.rendez_w"]
        )
        W1, W2, Wr = self.params["W1"], self.params["W2"], self.params["Wr"]
        B, G, h = axis_vec.shape

        # fused = sum_g rendez_w[b,g] * axis_vec[b,g,:]
        d_rendez_w = np.einsum("bh,bgh->bg", d_fused, axis_vec)      # (B,G)
        d_axis_vec_from_fuse = np.einsum("bg,bh->bgh", rendez_w, d_fused)  # (B,G,h)

        d_rendez_logit = d_softmax_backward(rendez_w, d_rendez_w, axis=1)  # (B,G)
        grads["mar.br"] = d_rendez_logit.sum(axis=(0, 1), keepdims=False).reshape(1)
        grads["mar.Wr"] = np.einsum("bgh,bg->h", axis_vec, d_rendez_logit).reshape(h, 1)
        d_axis_vec_from_rendez = d_rendez_logit[..., None] * Wr[:, 0]  # (B,G,h)

        d_axis_vec = d_axis_vec_from_fuse + d_axis_vec_from_rendez     # (B,G,h)

        dH2 = d_axis_vec * d_tanh_from_output(axis_vec)                # (B,G,h) [pre-W2 tanh output grad]
        grads["mar.b2"] = dH2.sum(axis=(0, 1))
        grads["mar.W2"] = np.einsum("bgh,bgo->ho", H1, dH2)
        dH1_pre = dH2 @ W2.T                                            # (B,G,h)
        dH1 = dH1_pre * d_tanh_from_output(H1)
        grads["mar.b1"] = dH1.sum(axis=(0, 1))
        grads["mar.W1"] = np.einsum("bgd,bgh->dh", Xg, dH1)
        dXg = dH1 @ W1.T                                                 # (B,G,d_in)
        return dXg


