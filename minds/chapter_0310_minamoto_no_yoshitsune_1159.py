import numpy as np

RNG_SEED = 310  # the figure's corpus id, for reproducibility, not mysticism
rng = np.random.default_rng(RNG_SEED)


# ==============================================================================
# SECTION 1 — NUMERICAL PRIMITIVES
# ==============================================================================

def sigmoid(x):
    """Numerically stable logistic sigmoid."""
    out = np.empty_like(x, dtype=np.float64)
    pos = x >= 0
    out[pos] = 1.0 / (1.0 + np.exp(-x[pos]))
    ex = np.exp(x[~pos])
    out[~pos] = ex / (1.0 + ex)
    return out


def d_sigmoid_from_output(s):
    """Derivative of sigmoid, expressed in terms of its own output s = sigmoid(x)."""
    return s * (1.0 - s)


def tanh(x):
    return np.tanh(x)


def d_tanh_from_output(t):
    """Derivative of tanh, expressed in terms of its own output t = tanh(x)."""
    return 1.0 - t * t


def relu(x):
    return np.maximum(0.0, x)


def d_relu_from_input(x):
    return (x > 0.0).astype(np.float64)


def softmax(x, axis=-1):
    """Numerically stable softmax along `axis`."""
    x_max = np.max(x, axis=axis, keepdims=True)
    ex = np.exp(x - x_max)
    return ex / np.sum(ex, axis=axis, keepdims=True)


def d_softmax_backward(y, dy, axis=-1):
    """
    Backward pass through softmax.
    y  : softmax output, same shape as dy
    dy : upstream gradient dL/dy
    Returns dL/dz where y = softmax(z, axis=axis).
    Formula: dz = y * (dy - sum(dy * y, axis, keepdims=True))
    """
    s = np.sum(dy * y, axis=axis, keepdims=True)
    return y * (dy - s)


def bce_loss_and_grad(p, y, eps=1e-9):
    """
    Binary cross-entropy, elementwise, mean-reduced.
    p, y: same shape, p in (0,1) probabilities, y in {0,1}.
    Returns (scalar_loss, dL/dp array).
    """
    p_c = np.clip(p, eps, 1.0 - eps)
    loss = -np.mean(y * np.log(p_c) + (1.0 - y) * np.log(1.0 - p_c))
    n = p.size
    dp = (-(y / p_c) + (1.0 - y) / (1.0 - p_c)) / n
    return loss, dp


# ==============================================================================
# SECTION 2 — SYNTHETIC TASK: "Formation Outcome Prediction"
# ==============================================================================
#
# Ground-truth physical model (hidden from the network, used only to LABEL
# the data): each formation has N units, K of which are secretly "leverage"
# units (command / propulsion analogues). Each unit i carries a scalar
# "structural contribution" c_i to the formation's overall integrity. Leverage
# units contribute far more than ordinary units. A hypothetical small strike
# with a fixed budget B_strike removes the contribution of whichever units it
# hits. The formation "breaks" (label = 1, i.e. the strike succeeds) if the
# removed contribution exceeds a threshold fraction of total integrity.
#
# We generate two kinds of examples with EQUAL probability:
#   (a) "targeted" trials: the fixed strike budget is spent on the true
#       leverage units -> usually breaks the formation (label depends on
#       actual contributions, so still has to be inferred, not memorized).
#   (b) "symmetric" trials: the fixed strike budget is spent on a uniformly
#       random subset of units of the same size -> usually does NOT break
#       the formation, because mass, not leverage, was targeted.
# The network is never told which regime an example came from; it must infer
# leverage from the raw unit features alone (a small per-unit generative
# signature correlates with true leverage, buried in noise) and decide.
# ==============================================================================

N_UNITS = 12
FEATURE_DIM = 8
N_LEVERAGE = 2
N_AXES = 3
UNITS_PER_AXIS = N_UNITS // N_AXES
STRIKE_BUDGET = 2


def generate_battle_formation_dataset(n_examples, rng):
    """
    Returns:
      X            : (n_examples, N_UNITS, FEATURE_DIM) float64 raw unit features
      y_leverage   : (n_examples, N_UNITS) float64 in {0,1}, true leverage mask
      y_outcome    : (n_examples,) float64 in {0,1}, whether a strike
                     correctly TARGETED at the true leverage units would
                     break the formation (removed contribution exceeds 45%
                     of total structural integrity).

    Both labels must be inferred from the same noisy raw features; neither
    the leverage identity nor the exact contribution magnitudes are handed
    to the model directly. The "vulnerability" question (y_outcome) is
    harder than the "identity" question (y_leverage): two formations can
    have the same pair of leverage units yet differ in whether those units
    are load-bearing enough, relative to the rest of the formation, to
    actually break it if struck. That is the substantive prediction this
    task asks the network to make -- it mirrors the real asymmetry in
    Yoshitsune's problem: finding the command/propulsion nodes is only half
    the task; knowing whether disabling them is DECISIVE is the other half.
    """
    X = np.zeros((n_examples, N_UNITS, FEATURE_DIM), dtype=np.float64)
    y_leverage = np.zeros((n_examples, N_UNITS), dtype=np.float64)
    y_outcome = np.zeros(n_examples, dtype=np.float64)

    for i in range(n_examples):
        # base contributions: ordinary units are modest, leverage units are
        # boosted by a variable multiplier -- SOMETIMES enough to be
        # decisive if struck, sometimes not, which is exactly what the
        # network has to learn to distinguish.
        leverage_idx = rng.choice(N_UNITS, size=N_LEVERAGE, replace=False)
        # ordinary units: tight variance (a formation's "rank and file" are
        # fairly uniform in structural weight) -- this keeps the unlabeled
        # denominator from injecting irreducible noise into y_outcome.
        contributions = rng.uniform(0.85, 1.15, size=N_UNITS)
        mult = rng.uniform(1.5, 7.0, size=N_LEVERAGE)
        contributions[leverage_idx] = rng.uniform(0.8, 1.2, size=N_LEVERAGE) * mult
        total = contributions.sum()
        removed = contributions[leverage_idx].sum()
        breaks = 1.0 if (removed / total) > 0.45 else 0.0

        # Raw features: dims 0-1 carry a noisy IDENTITY signature (which
        # units are leverage units at all); dim 2 carries a noisy MAGNITUDE
        # signature correlated with `mult` (how load-bearing they are);
        # dims 3-7 are pure noise of comparable scale. The network must
        # learn to read both signals through the noise -- neither is an
        # explicit flag.
        feats = rng.normal(0.0, 1.0, size=(N_UNITS, FEATURE_DIM))
        identity_sig = rng.normal(2.0, 0.5, size=N_LEVERAGE)
        feats[leverage_idx, 0] += identity_sig
        feats[leverage_idx, 1] += rng.normal(1.2, 0.5, size=N_LEVERAGE)
        magnitude_sig = 0.45 * mult + rng.normal(0.0, 0.35, size=N_LEVERAGE)
        feats[leverage_idx, 2] += magnitude_sig

        X[i] = feats
        y_leverage[i, leverage_idx] = 1.0
        y_outcome[i] = breaks

    return X, y_leverage, y_outcome


# ==============================================================================
# SECTION 3 — LeverageScorer  (encodes fact #2: Dan-no-ura, target function
# not mass; "center of gravity" targeting rather than uniform engagement)
# ==============================================================================
#
# A 2-layer MLP applied per-unit (shared weights across the N units, like a
# 1x1 convolution) producing one scalar per unit: how much of a functional
# load-bearer is this unit? That scalar feeds TWO places:
#   - softmax over units -> a strike-weighting distribution (Section 3b),
#     used to build a "targeted strike representation" that concentrates on
#     the highest-leverage units instead of pooling everything equally.
#   - sigmoid -> a per-unit probability, trained directly against the
#     leverage ground truth (auxiliary supervised signal), so the score is
#     kept interpretable rather than becoming an unconstrained latent.
# ==============================================================================

class LeverageScorer:
    """Docstring fact: Dan-no-ura, 1185 — disable propulsion, not headcount."""

    def __init__(self, d_in, d_hidden, temperature=0.7):
        self.temperature = temperature
        limit1 = np.sqrt(6.0 / (d_in + d_hidden))
        limit2 = np.sqrt(6.0 / (d_hidden + 1))
        self.params = {
            "W1": rng.uniform(-limit1, limit1, (d_in, d_hidden)),
            "b1": np.zeros(d_hidden),
            "W2": rng.uniform(-limit2, limit2, (d_hidden, 1)),
            "b2": np.zeros(1),
        }

    def forward(self, X, cache):
        """
        X: (B, N, d_in)
        Returns:
          lev_logit        : (B, N)      raw scalar leverage logit per unit
          strike_weights    : (B, N)      softmax(lev_logit / T) over units
          leverage_prob      : (B, N)      sigmoid(lev_logit), for aux BCE head
        """
        W1, b1, W2, b2 = (self.params[k] for k in ("W1", "b1", "W2", "b2"))
        Z1 = X @ W1 + b1                    # (B,N,h)
        A1 = tanh(Z1)                       # (B,N,h)
        lev_logit = (A1 @ W2 + b2)[..., 0]  # (B,N)

        strike_weights = softmax(lev_logit / self.temperature, axis=1)  # (B,N)
        leverage_prob = sigmoid(lev_logit)                              # (B,N)

        cache["lev.X"] = X
        cache["lev.A1"] = A1
        cache["lev.lev_logit"] = lev_logit
        cache["lev.strike_weights"] = strike_weights
        cache["lev.leverage_prob"] = leverage_prob
        return lev_logit, strike_weights, leverage_prob

    def backward(self, d_lev_logit_total, cache, grads):
        """
        d_lev_logit_total: (B,N) — combined upstream gradient dL/d(lev_logit)
        from ALL consumers (strike-weight softmax path, leverage aux-BCE path,
        entropy-economy path — all already summed by the caller).
        """
        W2 = self.params["W2"]
        X, A1 = cache["lev.X"], cache["lev.A1"]
        B, N, h = A1.shape

        d_lev_logit = d_lev_logit_total[..., None]          # (B,N,1)
        grads["lev.b2"] = d_lev_logit.sum(axis=(0, 1))
        grads["lev.W2"] = np.einsum("bnh,bno->ho", A1, d_lev_logit)
        dA1 = d_lev_logit @ W2.T                             # (B,N,h)
        dZ1 = dA1 * d_tanh_from_output(A1)                   # (B,N,h)
        grads["lev.b1"] = dZ1.sum(axis=(0, 1))
        grads["lev.W1"] = np.einsum("bnd,bnh->dh", X, dZ1)
        dX = dZ1 @ self.params["W1"].T                       # (B,N,d)
        return dX


