import numpy as np

RNG_SEED = 12141292          # birth (traditional) and death years, concatenated
DEG = 180.0 / np.pi


# ==============================================================================
# PART I -- GEOMETRY OF THE MEDIUM
#
# Bacon's Perspectiva takes its geometry from Alhacen (Ibn al-Haytham) but makes
# one commitment that becomes an architectural gift: THE PERPENDICULAR RAY IS
# PRIMARY. Rays striking an interface square-on pass strongest and truest; all
# oblique rays are weakened and refracted, and are treated as cases of indirect,
# less certain vision. In this file that doctrine is not asserted -- it FALLS OUT
# of Beer-Lambert attenuation along a slanted path plus an obliquity factor.
# Self-test 2 verifies it emerged rather than being imposed.
# ==============================================================================

def softplus(z):
    """Smooth positive map. Used to keep indices >= 1 and opacities >= 0."""
    return np.logaddexp(0.0, z)


def d_softplus(z):
    """d/dz softplus(z) = sigmoid(z)."""
    return 1.0 / (1.0 + np.exp(-z))


def sigmoid(z):
    return 1.0 / (1.0 + np.exp(-np.clip(z, -60, 60)))


def snell_refract(sin_incident, n_from, n_into):
    """
    Snell's law, n1 sin(t1) = n2 sin(t2), returned as sin(t2).

    Kept as a standalone function on purpose: the SAME routine is used by the
    propagation engine and by the rainbow self-test (self-test 3). Bacon's one
    genuinely original quantitative result is his measurement of the rainbow's
    maximum elevation at 42 degrees -- probably taken with an astrolabe, and
    correct. If the optics inside this network are real, that number must be
    recoverable from them. It is.
    """
    return np.clip(sin_incident * n_from / n_into, -1.0, 1.0)


class Medium:
    """
    A stack of L plane-parallel layers between a source plane and a receiver
    plane -- Bacon's air / water / crystalline-humor chain, generalised.

    Layer l carries two learnable scalars:
        n_l = 1 + softplus(nu_l)    refractive index, >= 1
        k_l = softplus(omega_l)     opacity (extinction coefficient), >= 0

    These 2L numbers generate the ENTIRE K x D amplitude matrix. Nothing about
    the routing is stored; it is computed from geometry every forward pass. This
    is the concrete sense in which, for Bacon, what a mind has learned is the
    condition of the medium it thinks through.
    """

    def __init__(self, n_layers=4, thickness_total=1.6):
        self.L = n_layers
        # Equal-thickness layers summing to thickness_total.
        self.t = np.full(n_layers, thickness_total / n_layers)
        self.T = float(self.t.sum())

    # --- forward -------------------------------------------------------------

    def cosines(self, sin0):
        """
        cos(theta_l) in every layer, for launch sine sin0 (broadcastable array).

        sin(theta_l) = sin0 / n_l  by Snell chaining from vacuum (n_0 = 1).
        Since n_l >= 1 and |sin0| < 1 strictly, cos is always real and positive.

        Returns array of shape sin0.shape + (L,).
        """
        s = sin0[..., None] / self.n[None, :] if sin0.ndim else sin0 / self.n
        return np.sqrt(np.maximum(1.0 - s * s, 1e-9))

    def log_amplitude(self, sin0):
        """
        log A = sum_l [ log cos(theta_l)  -  k_l * t_l / cos(theta_l) ]

        Two terms, two doctrines:
          log cos(theta_l)      -- obliquity. The square-on ray loses nothing.
          -k_l t_l / cos(theta) -- Beer-Lambert. The slanted ray spends longer
                                   inside the dense layer and is eaten by it.
        Both are maximised at theta = 0. The perpendicular ray is primary.
        """
        c = self.cosines(sin0)                       # (..., L)
        return (np.log(c) - self.kap[None, :] * self.t[None, :] / c).sum(-1)

    def set_params(self, nu, omega):
        self.nu, self.omega = nu, omega
        self.n = 1.0 + softplus(nu)
        self.kap = softplus(omega)

    # --- backward ------------------------------------------------------------

    def grads(self, sin0, dlogA):
        """
        Gradients of sum(dlogA * logA) wrt the raw parameters nu, omega.

        d logA / d n_l    = (1/c_l + k_l t_l / c_l^2) * s0^2 / (n_l^3 c_l)
        d logA / d k_l    = - t_l / c_l
        then chain through n = 1 + softplus(nu), k = softplus(omega).
        """
        c = self.cosines(sin0)                                   # (...,L)
        s2 = (sin0 ** 2)[..., None]
        dn = (1.0 / c + self.kap * self.t / (c * c)) * s2 / (self.n ** 3 * c)
        dk = -self.t / c
        w = dlogA[..., None]
        gnu = (w * dn).reshape(-1, self.L).sum(0) * d_softplus(self.nu)
        gom = (w * dk).reshape(-1, self.L).sum(0) * d_softplus(self.omega)
        return gnu, gom


