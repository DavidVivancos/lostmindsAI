# PART III -- THE CORPUS
#
# Four latent natures, each announcing itself by WHERE on the source line its
# species originates. The model must clarify the medium enough to tell the
# arriving patterns apart. Alongside the real evidence ride the four offendicula,
# which in the world the model is trained in are all excellent predictors -- and
# in the world it is tested in, are not.
# ==============================================================================

def make_corpus(n=1600, n_src=24, n_cls=4, corrupt=False, obscured=0.20, seed=7):
    """
    Returns X (species amplitudes), O (the four offendicula), y, and a mask
    marking the OBSCURED samples -- those where the species never arrived.

    corrupt=False : the schools. Authority, custom, crowd and bluster all work
                    beautifully, and the real evidence is faint and overlapping.
                    Every incentive points at the shortcut.
    corrupt=True  : the world. Authority inverts, custom goes stale, the crowd
                    becomes a mob, and the bluster was always empty.

    OBSCURED samples are the reason the certification gate exists. In them the
    species is almost entirely extinguished before arrival and the label is
    genuinely unknowable. The right answer is not a guess; it is to decline. A
    network with a working certificatio should assert the readout on clear
    samples and fall back to the silent prior on these.
    """
    rng = np.random.default_rng(seed)
    y = rng.integers(0, n_cls, n)

    # --- real evidence: a class-specific bump of emitting agents --------------
    # Deliberately hard: the bumps are wide enough to overlap heavily and the
    # noise is large. The evidence is real but it has to be worked for.
    centres = np.linspace(-0.50, 0.50, n_cls)
    pos = np.linspace(-1, 1, n_src)
    width = 0.40
    X = np.exp(-((pos[None, :] - centres[y][:, None]) ** 2) / (2 * width ** 2))
    X += 0.42 * rng.standard_normal(X.shape)
    X = np.maximum(X, 0.0)

    # --- the obscured: species extinguished, label unknowable ----------------
    mask = rng.random(n) < obscured
    X[mask] = np.maximum(0.05 * rng.standard_normal((mask.sum(), n_src)), 0.0)
    y[mask] = rng.integers(0, n_cls, mask.sum())

    # --- offendicula ---------------------------------------------------------
    # Each shortcut arrives already shaped as a VOTE OVER THE CLASSES -- which
    # is how these things actually reach a mind. An authority names a thing; a
    # crowd divides over it; habit repeats last time's answer. None of them
    # hands you a scalar to be interpreted.
    O = np.zeros((n, 4, n_cls))
    eye = np.eye(n_cls)

    def wrong_of(labels):
        """A confidently named class that is not the right one."""
        return (labels + rng.integers(1, n_cls, labels.shape)) % n_cls

    # 1. auctoritas fragilis -- the example of frail and unworthy authority.
    #    In the schools the eminent name is right 95% of the time, far better
    #    than the murky evidence. In the world it is confidently, and therefore
    #    ruinously, wrong.
    claim = y.copy()
    bad = rng.random(n) < (0.90 if corrupt else 0.05)
    claim[bad] = wrong_of(y[bad])
    O[:, 0, :] = eye[claim]

    # 2. consuetudo diuturna -- long-standing custom: last time's answer,
    #    repeated. The corpus of the schools is ordered so that habit pays. The
    #    world has since been reordered and nobody sent word.
    prev = np.roll(y, 1)
    O[:, 1, :] = eye[rng.permutation(prev) if corrupt else prev]

    # 3. sensus vulgi imperiti -- the sense of the unlearned crowd. Bacon's
    #    charge is precise: the show of hands is not worthless because it is a
    #    crowd, but because it is an UNINSTRUCTED one, and from inside the two
    #    look identical. Here the informed crowd votes 88% right and the mob 20%.
    votes = 11
    acc = 0.20 if corrupt else 0.88
    right = rng.random((n, votes)) < acc
    guess = np.where(right, y[:, None], rng.integers(0, n_cls, (n, votes)))
    tally = np.stack([np.bincount(row, minlength=n_cls) for row in guess])
    O[:, 2, :] = tally / votes

    # 4. occultatio ignorantiae -- ignorance concealed behind a display of
    #    apparent wisdom. It names a class with total confidence and picks it at
    #    random. It carries no information in EITHER world, which is exactly
    #    Bacon's charge: a mind that gives it weight has been moved by manner
    #    alone. Note it is the hardest of the four to catch, because unlike the
    #    other three it never has a good season to be caught out of.
    O[:, 3, :] = eye[rng.integers(0, n_cls, n)]

    # --- what nobody saw, nobody can report ----------------------------------
    # On the obscured samples the species never arrived, so the authority did
    # not witness it either, the crowd is guessing, and habit is repeating an
    # unrelated case. Making the shortcuts still correct here would be dishonest
    # bookkeeping: it would hand the model a way to be right about an event no
    # one observed, and there would then be nothing for certification to do.
    O[mask] = eye[rng.integers(0, n_cls, (mask.sum(), 4))]
    return X, O, y, mask


