def check_gradients(tol=2e-5):
    """
    TEST 1 (MANDATORY): central finite differences against analytic gradients,
    every parameter group, several coordinates each.
    """
    net = Specularium(n_src=10, n_rec=8, n_sig=6, n_cls=3, n_layers=3, seed=5)
    rng = np.random.default_rng(3)
    x = np.abs(rng.standard_normal((7, 10)))
    o = rng.standard_normal((7, 4, 3))
    y = rng.integers(0, 3, 7)

    def L():
        return net.loss_and_grads(x, o, y)[0]

    _, g, _ = net.loss_and_grads(x, o, y)
    worst, worst_k = 0.0, ""
    for k, v in net.p.items():
        flat = v.ravel()
        picks = range(flat.size) if flat.size <= 4 else \
            rng.choice(flat.size, 4, replace=False)
        for i in picks:
            old = flat[i]
            h = 1e-6 * max(1.0, abs(old))
            flat[i] = old + h; lp = L()
            flat[i] = old - h; lm = L()
            flat[i] = old
            num = (lp - lm) / (2 * h)
            ana = g[k].ravel()[i]
            rel = abs(num - ana) / max(1e-8, abs(num) + abs(ana))
            if rel > worst:
                worst, worst_k = rel, f"{k}[{i}]"
    ok = worst < tol
    print(f"  [1] gradient check        max rel err {worst:.3e} at {worst_k:<10s}"
          f" {'PASS' if ok else 'FAIL'}")
    return ok


def check_perpendicular():
    """
    TEST 2: the perpendicular ray must be primary -- and must be so because of
    the physics, not because anyone wrote it in. Amplitude must peak at zero
    obliquity and fall monotonically with lateral offset.
    """
    net = Specularium(n_src=21, n_rec=21, n_sig=8, n_cls=3, seed=11)
    # A real medium rather than the murky initialisation: n = 1.34, close to
    # water and to the crystalline humor of Bacon's Perspectiva; and dense
    # enough that the length of the slanted path inside it actually costs.
    net.p["nu"][:] = -0.904        # 1 + softplus(nu) = 1.34
    net.p["omega"][:] = 1.62       # softplus(omega)  = 1.80
    A = net.amplitudes()
    k = 10                                   # centre receiver, faces source 10
    row = A[k]
    peak_ok = int(np.argmax(row)) == 10
    left = np.all(np.diff(row[:11]) > 0)
    right = np.all(np.diff(row[10:]) < 0)
    ratio = row[10] / row[0]
    ok = peak_ok and left and right
    print(f"  [2] perpendicular primacy peak at square-on source, "
          f"centre/edge = {ratio:5.1f}x        {'PASS' if ok else 'FAIL'}")
    return ok


def check_rainbow():
    """
    TEST 3: Bacon's own number. Opus maius VI reports the rainbow's maximum
    elevation as 42 degrees -- his single best quantitative result, and right.
    Using the same Snell routine the network propagates species with, compute
    the Descartes ray for one internal reflection in a water droplet
    (n = 1.333) and confirm 42 degrees emerges.

        deviation D(i) = 180 + 2i - 4r,   r = asin(sin i / n)
        rainbow elevation = 180 - min_i D(i)
    """
    n_water = 1.333
    i = np.linspace(1e-4, np.pi / 2 - 1e-4, 400001)
    r = np.arcsin(snell_refract(np.sin(i), 1.0, n_water))
    D = np.pi + 2 * i - 4 * r
    elev = (np.pi - D.min()) * DEG
    ok = 41.5 <= elev <= 42.5
    print(f"  [3] rainbow elevation     computed {elev:.2f} deg  "
          f"(Bacon measured 42)           {'PASS' if ok else 'FAIL'}")
    return ok


def check_eduction():
    """
    TEST 4: eduction, not inscription. Close a receiver's potency in some
    channels and those channels must stay dead no matter how violent the
    arriving species. The species cannot put in what the recipient could not
    have become.
    """
    net = Specularium(n_src=12, n_rec=6, n_sig=8, n_cls=3, seed=17)
    net.p["Pi"][:, :4] = -40.0                      # potency closed, channels 0-3
    rng = np.random.default_rng(2)
    x = np.abs(rng.standard_normal((5, 12))) * 500.0   # deafening species
    o = np.zeros((5, 4, 3))
    net.forward(x, o, cache=True)
    dead = np.abs(net._c["e"][:, :, :4]).max()
    live = np.abs(net._c["e"][:, :, 4:]).max()
    ok = dead < 1e-12 and live > 1e-3
    print(f"  [4] eduction constraint   closed-potency max {dead:.2e}, "
          f"open {live:.3f}   {'PASS' if ok else 'FAIL'}")
    return ok


def check_signs():
    """
    TEST 5: present appellation. A sign held while its referent is present keeps
    naming; the same sign rehearsed in the referent's absence goes void; and
    only a renewed imposition -- not memory, not repetition -- restores it.
    """
    rng = np.random.default_rng(4)
    reg = SignRegister(dim=16)
    ref = rng.standard_normal(16)
    reg.impose("stella", ref)
    for _ in range(5):
        reg.tick(present={"stella"})
    held = reg.signifies("stella")

    void = reg.rehearse("stella", times=10)          # talk without looking

    reg.impose("stella", ref)                        # go and look again
    renewed = reg.signifies("stella")

    ok = held > 0.95 and void < 0.01 and renewed > 0.95
    print(f"  [5] present appellation   present {held:.2f} -> absent {void:.4f}"
          f" -> reimposed {renewed:.2f}  {'PASS' if ok else 'FAIL'}")
    return ok


def check_certification(net, X, O, mask):
    """
    TEST 6: certification must discriminate, and it must do so on samples the
    network was never told apart. `mask` marks the obscured cases, where the
    species was extinguished and no conclusion can be certified. Nothing in
    training identifies them; the gate has to notice for itself that there is
    nothing there to assert.

    This is the first prerogative of the scientia experimentalis doing its job:
    the readout still produces an answer, and the certifier declines to publish
    it.
    """
    c_clear = net.certification(X[~mask], O[~mask])
    c_obsc = net.certification(X[mask], O[mask])
    ok = c_obsc < c_clear - 0.02
    print(f"  [6] certification gate    clear {c_clear:.3f}  >  obscured "
          f"{c_obsc:.3f}   (gap {c_clear-c_obsc:+.3f})   {'PASS' if ok else 'FAIL'}")
    return ok


