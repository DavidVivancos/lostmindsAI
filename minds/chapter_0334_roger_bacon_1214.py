def experiment():
    """
    TEST 7, and the point of the file. Two identical networks. One is trained
    with purgation of the four offendicula; one is not. Both see the same
    schools, where authority, custom, crowd and bluster all predict beautifully.
    Then both are taken outside.
    """
    Xtr, Otr, Ytr, _ = make_corpus(1600, corrupt=False, seed=7)
    Xte, Ote, Yte, Mte = make_corpus(700, corrupt=False, seed=8)   # same schools
    Xco, Oco, Yco, Mco = make_corpus(700, corrupt=True,  seed=9)   # the world

    print("\n  Training the unpurged mind (leans on whatever predicts) ...")
    lax = Specularium(seed=RNG_SEED)
    lax.fit(Xtr, Otr, Ytr, purgation=0.0)

    print("  Training the purged mind (must pay for every shortcut) ...")
    pur = Specularium(seed=RNG_SEED)
    k0 = pur.medium.kap.copy() if hasattr(pur.medium, "kap") else None
    pur._sync(); k0 = pur.medium.kap.copy(); n0 = pur.medium.n.copy()
    pur.fit(Xtr, Otr, Ytr, purgation=0.15)
    pur._sync()

    print("\n  --- the medium, before and after learning -----------------------")
    print(f"      opacity  kappa : {np.array2string(k0, precision=3)}"
          f"  ->  {np.array2string(pur.medium.kap, precision=3)}")
    print(f"      index      n   : {np.array2string(n0, precision=3)}"
          f"  ->  {np.array2string(pur.medium.n, precision=3)}")

    print("\n  --- gains on the four offendicula ------------------------------")
    for j, nm in enumerate(Specularium.OFFENDICULA):
        print(f"      {nm:<26s} unpurged {lax.gains()[j]:.3f}    "
              f"purged {pur.gains()[j]:.3f}")

    print("\n  --- accuracy on decidable samples ------------------------------")
    rows = []
    for nm, net in (("unpurged", lax), ("purged  ", pur)):
        a_sch = net.accuracy(Xte[~Mte], Ote[~Mte], Yte[~Mte])
        a_wld = net.accuracy(Xco[~Mco], Oco[~Mco], Yco[~Mco])
        rows.append((nm, a_sch, a_wld))
        print(f"      {nm}   in the schools {a_sch:.3f}   "
              f"in the world {a_wld:.3f}   drop {a_wld-a_sch:+.3f}")

    lax_drop = rows[0][1] - rows[0][2]
    pur_drop = rows[1][1] - rows[1][2]
    ok7 = pur_drop < lax_drop and rows[1][2] > rows[0][2]
    print(f"  [7] purgation of error    purged mind survives the world "
          f"({rows[1][2]:.3f} vs {rows[0][2]:.3f})  {'PASS' if ok7 else 'FAIL'}")
    return pur, Xte, Ote, Mte, ok7


