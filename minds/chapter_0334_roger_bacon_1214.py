class Specularium:
    """
    Forward pass, stage by stage, with Bacon's own name for each stage.

      0  AGENTES        D sources on a line, each with a FIXED univocal
                        signature. Never learned. Species is the agent's own
                        likeness, not a projection chosen for convenience.

      1  MULTIPLICATIO  A[k,d] = exp(logA(sin0[k,d])), generated by the medium.

      2  RECEPTIO       r[k] = sum_d A[k,d] * x[d] * signature[d]
                        Superposition of arriving species. No mixing matrix.

      3  EDUCTIO        e[k] = tanh(r[k]) * sigmoid(potency[k])
                        The species draws out only what the recipient already
                        had the potency to become.

      4  SENSUS COMMUNIS  h = mean_k e[k]
                        Bacon's common nerve, where the single visual judgement
                        is made from many arriving species.

      5  OFFENDICULA    q = sum_j tanh(lam_j) * o_j * B_j
                        The four social shortcuts, gated and penalised.

      6  CERTIFICATIO   c = sigmoid(wc . h + bc)
                        logits = c*(u + q) + (1-c)*prior
                        Argument does not certify. Only the certified part of a
                        conclusion is asserted; the rest defaults to silence.
    """

    OFFENDICULA = ("auctoritas fragilis",   # frail and unworthy authority
                   "consuetudo diuturna",   # long-standing custom
                   "sensus vulgi",          # the sense of the ignorant crowd
                   "occultatio ignorantiae")  # ignorance hidden by display

    def __init__(self, n_src=24, n_rec=20, n_sig=16, n_cls=4,
                 n_layers=4, seed=RNG_SEED):
        rng = np.random.default_rng(seed)
        self.D, self.K, self.G, self.C = n_src, n_rec, n_sig, n_cls
        self.medium = Medium(n_layers)

        # --- fixed geometry ---------------------------------------------------
        self.u = np.linspace(-1.0, 1.0, self.D)          # source positions
        self.v = np.linspace(-1.0, 1.0, self.K)          # receiver positions
        delta = self.v[:, None] - self.u[None, :]        # (K,D) lateral offset
        T = self.medium.T
        self.sin0 = delta / np.sqrt(delta ** 2 + T ** 2)  # launch sine, |.| < 1

        # --- fixed univocal signatures (NOT parameters) -----------------------
        sig = rng.standard_normal((self.D, self.G))
        self.SIG = sig / np.linalg.norm(sig, axis=1, keepdims=True)

        # --- learnable parameters --------------------------------------------
        # Medium starts murky and over-refracting: the mind begins in a bad
        # medium and must clarify it. Watch kappa fall during training.
        self.p = {
            "nu":    np.full(n_layers, 0.55),                       # n ~ 2.0
            "omega": np.full(n_layers, 0.30),                       # k ~ 0.85
            "Pi":    rng.standard_normal((self.K, self.G)) * 0.30,  # potency
            "W":     rng.standard_normal((self.C, self.G)) * 0.30,  # readout
            "b":     np.zeros(self.C),
            # Reliance on each offendiculum. There is deliberately NO learnable
            # direction to pair with it: each shortcut arrives already shaped as
            # a vote over the classes, so gain_j = softplus(lam_j) IS the amount
            # of credit extended to that source, in logits, and cannot be hidden
            # by rescaling something else. A penalty on a gameable quantity
            # measures nothing.
            "lam":   np.full(4, 0.60),                              # offend. gains
            "wc":    np.abs(rng.standard_normal(self.G)) * 0.30,     # certifier
            "bc":    np.full(1, -1.0),
            "bp":    np.zeros(self.C),                              # silent prior
        }

    # -- convenience ----------------------------------------------------------

    def _sync(self):
        self.medium.set_params(self.p["nu"], self.p["omega"])

    def amplitudes(self):
        self._sync()
        return np.exp(self.medium.log_amplitude(self.sin0))       # (K,D)

    # -- forward --------------------------------------------------------------

    def forward(self, x, o, cache=False):
        """x: (N,D) source amplitudes.  o: (N,4) offendicula channels."""
        A = self.amplitudes()                                     # (K,D)
        M = A[None, :, :] * x[:, None, :]                         # (N,K,D)
        r = M @ self.SIG                                          # (N,K,G)
        tr = np.tanh(r)
        pot = sigmoid(self.p["Pi"])                               # (K,G)
        e = tr * pot[None]                                        # (N,K,G)
        h = e.mean(axis=1)                                        # (N,G)

        u = h @ self.p["W"].T + self.p["b"]                       # (N,C)
        gam = softplus(self.p["lam"])                             # (4,) >= 0
        # o is (N,4,C): each shortcut arrives as a vote over the classes.
        q = np.einsum("j,njc->nc", gam, o)                        # (N,C)
        # The certifier reads the SQUARED magnitude of the congregated species,
        # not its direction. This matters: the question certification asks is
        # not "which conclusion?" but "did any evidence arrive at all?" A
        # direction-reading gate cannot tell an absent species from one pointing
        # at another class, because the classes point every which way. Squaring
        # makes the gate class-symmetric and magnitude-sensitive, which is what
        # "certified by experience" has to mean.
        h2 = h * h                                                # (N,G)
        cz = h2 @ self.p["wc"] + self.p["bc"][0]                  # (N,)
        c = sigmoid(cz)
        logits = c[:, None] * (u + q) + (1.0 - c)[:, None] * self.p["bp"][None]

        if cache:
            self._c = dict(x=x, o=o, A=A, r=r, tr=tr, pot=pot, e=e, h=h, h2=h2,
                           u=u, q=q, gam=gam, c=c)
        return logits

    # -- loss and gradients ---------------------------------------------------

    def loss_and_grads(self, x, o, y, purgation=0.02, l2=1e-4, med_prior=0.05):
        """
        Softmax cross-entropy
          + purgation  * L1(offendicula gains)      <- Opus maius, Part One
          + l2         * L2(readout and offendicula dirs)
          + med_prior  * (n_l - 1.4)^2              <- media that actually exist

        PURGATION is the whole moral of Part One expressed as a penalty: a
        shortcut through authority, custom, crowd or bluster must pay for itself
        in evidence before the mind is allowed to lean on it.

        MED_PRIOR keeps the learned medium inside the range of the media a body
        can actually stand in -- air, water, glass, the crystalline humor. Left
        unconstrained the network discovers a cheat available to no animal:
        drive the index arbitrarily high, which straightens every ray toward the
        normal and makes the medium free to cross. Bacon's optics is an optics
        of real substances, and the constraint is part of the doctrine.
        """
        N = x.shape[0]
        logits = self.forward(x, o, cache=True)
        C = self._c
        z = logits - logits.max(1, keepdims=True)
        ez = np.exp(z)
        P = ez / ez.sum(1, keepdims=True)
        nll = -np.log(np.maximum(P[np.arange(N), y], 1e-12)).mean()

        gam = C["gam"]
        n_l = self.medium.n
        # Gains are non-negative by construction, so the L1 purgation term is
        # simply their sum -- and therefore smooth, with no subgradient at zero.
        loss = (nll
                + purgation * gam.sum()
                + l2 * np.sum(self.p["W"] ** 2)
                + med_prior * np.sum((n_l - 1.4) ** 2))

        # ---- backward --------------------------------------------------------
        g = {k: np.zeros_like(v) for k, v in self.p.items()}
        dlog = P.copy()
        dlog[np.arange(N), y] -= 1.0
        dlog /= N                                                  # (N,C)

        c = C["c"]
        g["bp"] += ((1.0 - c)[:, None] * dlog).sum(0)
        duq = c[:, None] * dlog                                    # (N,C)
        dc = (dlog * (C["u"] + C["q"] - self.p["bp"][None])).sum(1)
        dcz = dc * c * (1.0 - c)                                   # (N,)

        g["wc"] += C["h2"].T @ dcz
        g["bc"] += dcz.sum()
        dh = dcz[:, None] * self.p["wc"][None] * 2.0 * C["h"]      # (N,G)

        g["W"] += duq.T @ C["h"] + 2.0 * l2 * self.p["W"]
        g["b"] += duq.sum(0)
        dh += duq @ self.p["W"]

        dgam = np.einsum("nc,njc->j", duq, C["o"]) + purgation
        g["lam"] += dgam * d_softplus(self.p["lam"])

        de = np.repeat(dh[:, None, :], self.K, axis=1) / self.K    # (N,K,G)
        g["Pi"] += (de * C["tr"]).sum(0) * C["pot"] * (1.0 - C["pot"])
        dtr = de * C["pot"][None]
        dr = dtr * (1.0 - C["tr"] ** 2)                            # (N,K,G)
        dM = dr @ self.SIG.T                                       # (N,K,D)
        dA = (dM * C["x"][:, None, :]).sum(0)                      # (K,D)
        dlogA = dA * C["A"]

        gnu, gom = self.medium.grads(self.sin0, dlogA)
        g["nu"] += gnu + 2.0 * med_prior * (n_l - 1.4) * d_softplus(self.p["nu"])
        g["omega"] += gom
        return loss, g, P

    # -- optimiser ------------------------------------------------------------

    def fit(self, X, O, Y, epochs=260, lr=0.08, purgation=0.02,
            batch=128, seed=RNG_SEED, verbose_every=0):
        """Adam. Plain, small, and sufficient -- the interest is in the model."""
        rng = np.random.default_rng(seed)
        m = {k: np.zeros_like(v) for k, v in self.p.items()}
        s = {k: np.zeros_like(v) for k, v in self.p.items()}
        b1, b2, eps, t = 0.9, 0.999, 1e-8, 0
        hist = []
        N = X.shape[0]
        for ep in range(epochs):
            idx = rng.permutation(N)
            tot = 0.0
            for i in range(0, N, batch):
                j = idx[i:i + batch]
                loss, g, _ = self.loss_and_grads(X[j], O[j], Y[j], purgation)
                t += 1
                for k in self.p:
                    m[k] = b1 * m[k] + (1 - b1) * g[k]
                    s[k] = b2 * s[k] + (1 - b2) * g[k] ** 2
                    mh = m[k] / (1 - b1 ** t)
                    sh = s[k] / (1 - b2 ** t)
                    self.p[k] -= lr * mh / (np.sqrt(sh) + eps)
                tot += loss * len(j)
            hist.append(tot / N)
            if verbose_every and (ep + 1) % verbose_every == 0:
                print(f"      epoch {ep+1:4d}   loss {hist[-1]:.4f}   "
                      f"gains {np.abs(np.tanh(self.p['lam'])).sum():.3f}")
        return hist

    def accuracy(self, X, O, Y):
        return float((self.forward(X, O).argmax(1) == Y).mean())

    def certification(self, X, O):
        """Mean certification gate -- how much of its conclusion it will assert."""
        self.forward(X, O, cache=True)
        return float(self._c["c"].mean())

    def gains(self):
        return softplus(self.p["lam"])


