# PART IV -- DE SIGNIS: PRESENT APPELLATION
#
# Bacon's most radical and least-quoted doctrine, from De signis (recovered only
# in 1978) and the Summulae dialectices. A sign is in the category of RELATION,
# and it is a sign essentially with respect to the one for whom it signifies:
# "unless some were able to conceive by means of this sign, it would be void and
# vain." He then draws the conclusion his contemporaries refused: a name imposed
# on a present thing does not univocally name that thing once it is gone. The
# dead Caesar is not what 'Caesar' names. Reference must be RENEWED by a second
# act of imposition; it does not survive on habit.
#
# For a system that learns language from text, this is the sharpest possible
# objection: an embedding trained on co-occurrence has exactly the "habitual
# being" Bacon denies. Below, a register that refuses it.
# ==============================================================================

class SignRegister:
    """Appellation decays when the referent is absent; only a new imposition
    restores it. Rehearsing the sign among other signs does nothing."""

    def __init__(self, dim=16, decay=0.55, seed=RNG_SEED):
        rng = np.random.default_rng(seed)
        self.dim, self.decay = dim, decay
        self.rng = rng
        self.vec, self.appellation = {}, {}

    def impose(self, name, referent):
        """An act of imposition. Requires the referent to be present."""
        self.vec[name] = referent / (np.linalg.norm(referent) + 1e-9)
        self.appellation[name] = 1.0

    def tick(self, present):
        """One step of the world. `present` is the set of names whose referents
        are actually here. Everything else loses hold."""
        for nm in self.appellation:
            if nm in present:
                self.appellation[nm] = min(1.0, self.appellation[nm] + 0.25)
            else:
                self.appellation[nm] *= self.decay

    def signifies(self, name):
        """Strength with which the sign currently names anything at all."""
        return self.appellation.get(name, 0.0)

    def rehearse(self, name, times=8):
        """Say the word to yourself repeatedly with no referent in view.
        Bacon's prediction: this accomplishes nothing."""
        for _ in range(times):
            self.tick(present=set())
        return self.signifies(name)


