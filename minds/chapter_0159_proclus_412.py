# PART 5 — MANDATORY FINITE-DIFFERENCE GRADIENT CHECK
# ----------------------------------------------------------------------------
# The whole architecture is only trustworthy if reversion (backprop) really is
# the inverse trace of procession (forward). We verify analytic gradients
# against numerical ones for a random subset of entries in every parameter.
# ============================================================================

def gradient_check(verbose=True):
    net = HenadicEmanationNet(one_dim=3, n_henads=3, intellect_dim=6,
                              soul_dim=7, nature_dim=8, scale=0.5)
    Xnp = np.random.randn(5, 8)

    def compute_loss():
        return net.loss(Node(Xnp), w_remain=1.0, w_eman=1.0, w_orth=1.0)[0]

    # analytic gradients
    net.zero_grad()
    L = compute_loss()
    L.backward()

    eps = 1e-6
    max_rel = 0.0
    worst = None
    checks = 0
    for p in net.parameters():
        size = p.data.size
        # .flat writes through to the underlying array even if it is a
        # non-contiguous view — essential for a correct numerical check.
        idxs = np.random.choice(size, size=min(6, size), replace=False)
        for idx in idxs:
            orig = p.data.flat[idx]
            p.data.flat[idx] = orig + eps
            Lp = compute_loss().data.item()
            p.data.flat[idx] = orig - eps
            Lm = compute_loss().data.item()
            p.data.flat[idx] = orig
            num = (Lp - Lm) / (2 * eps)
            ana = p.grad.flat[idx]
            denom = max(1e-8, abs(num) + abs(ana))
            rel = abs(num - ana) / denom
            checks += 1
            if rel > max_rel:
                max_rel, worst = rel, (num, ana)
    if verbose:
        print(f"[gradient check] coordinates tested : {checks}")
        print(f"[gradient check] max relative error : {max_rel:.3e}")
        if worst:
            print(f"[gradient check] worst (num, analytic): "
                  f"{worst[0]:+.6f}, {worst[1]:+.6f}")
    passed = max_rel < 1e-4
    print(f"[gradient check] {'PASS' if passed else 'FAIL'} "
          f"(threshold 1e-4)")
    return passed


