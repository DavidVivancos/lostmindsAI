# PART 2 — THE HENADIC EMANATION NETWORK
# ----------------------------------------------------------------------------
# Four hypostatic levels descend from the One to Nature. Downward maps are
# "procession" operators; upward maps are "reversion" operators. The henads sit
# between the One and Intellect as a small set of orthonormal unities.
# ============================================================================

class HenadicEmanationNet:
    """Proclus's cosmos rendered as a learnable, bidirectional hierarchy."""

    def __init__(self, one_dim=3, n_henads=4, intellect_dim=12,
                 soul_dim=16, nature_dim=20, scale=0.5):
        self.dims = dict(one=one_dim, henad=n_henads, intellect=intellect_dim,
                         soul=soul_dim, nature=nature_dim)

        rng = np.random.randn

        def P(shape):                          # a trainable Node parameter
            return Node(rng(*shape) * scale)

        # --- The One: a single seed vector, kept on the unit sphere --------
        self.one = Node(rng(1, one_dim))
        self._renorm_one()

        # --- Procession (downward) parameters ------------------------------
        # One -> henadic gates (how strongly the One "lights up" each henad)
        self.W_one_hen = P((one_dim, n_henads))
        # The henads themselves: n_henads distinct unities living in Intellect
        self.H = P((n_henads, intellect_dim))
        self._orthonormalize_henads()
        # Intellect -> Soul -> Nature (procession with tanh "bending")
        self.Wp_is, self.bp_is = P((intellect_dim, soul_dim)), Node(np.zeros((1, soul_dim)))
        self.Wp_sn, self.bp_sn = P((soul_dim, nature_dim)),   Node(np.zeros((1, nature_dim)))

        # --- Reversion (upward) parameters ---------------------------------
        self.Wr_ns, self.br_ns = P((nature_dim, soul_dim)),      Node(np.zeros((1, soul_dim)))
        self.Wr_si, self.br_si = P((soul_dim, intellect_dim)),   Node(np.zeros((1, intellect_dim)))
        self.Wr_ih, self.br_ih = P((intellect_dim, n_henads)),   Node(np.zeros((1, n_henads)))

    # ---- parameter bookkeeping --------------------------------------------
    def parameters(self):
        return [self.one, self.W_one_hen, self.H,
                self.Wp_is, self.bp_is, self.Wp_sn, self.bp_sn,
                self.Wr_ns, self.br_ns, self.Wr_si, self.br_si,
                self.Wr_ih, self.br_ih]

    def zero_grad(self):
        for p in self.parameters():
            p.grad = np.zeros_like(p.data)

    def _renorm_one(self):
        # The One is beyond multiplicity: we approximate simplicity by keeping
        # the seed on the unit sphere. (Done outside autograd, after each step.)
        n = np.linalg.norm(self.one.data)
        if n > 0:
            self.one.data = self.one.data / n

    def _orthonormalize_henads(self):
        # Give the henads a clean orthonormal start (QR). A soft penalty keeps
        # them orthonormal during training; this just seeds them distinct.
        q, _ = np.linalg.qr(self.H.data.T)
        self.H.data = np.ascontiguousarray(q.T[:self.dims["henad"]])

    # ---- the two directions of the cosmos ---------------------------------
    def proceed(self, henad_code):
        """PROCESSION (proodos): a henadic code descends into a full world.
        henad_code: Node (B, n_henads) -> reconstruction Node (B, nature)."""
        intellect = henad_code @ self.H                      # the many from unities
        soul = (intellect @ self.Wp_is + self.bp_is).tanh()  # Intellect -> Soul
        nature = soul @ self.Wp_sn + self.bp_sn              # Soul -> Nature
        return nature, intellect

    def revert(self, x):
        """REVERSION (epistrophE): a sensible datum returns toward its cause.
        x: Node (B, nature) -> (henad_code, intellect_recovered)."""
        soul = (x @ self.Wr_ns + self.br_ns).tanh()          # Nature -> Soul
        intellect = (soul @ self.Wr_si + self.br_si).tanh()  # Soul -> Intellect
        henad_code = (intellect @ self.Wr_ih + self.br_ih).tanh()   # -> henads
        return henad_code, intellect

    def emanate_template(self):
        """The One, by procession through the henads, unfolds the ordered
        whole. Returns the world-template the source should regenerate."""
        gates = (self.one @ self.W_one_hen).tanh()           # (1, n_henads)
        template, _ = self.proceed(gates)                    # (1, nature)
        return template, gates

    # ---- the Procline loss ------------------------------------------------
    def loss(self, X, w_remain=1.0, w_eman=1.0, w_orth=1.0):
        """X: Node (B, nature). Returns (total_loss, parts dict)."""
        B = X.data.shape[0]

        # (1) PARTICIPATION: revert up, proceed back down, reconstruct.
        code, intellect_up = self.revert(X)
        x_hat, intellect_down = self.proceed(code)
        diff = X - x_hat
        L_recon = (diff.sq()).mean()

        # (2) REMAINING (monE): reversion and procession must AGREE about the
        #     intellect. The cause is undiminished — what returns equals what
        #     was given. This is the metaphysical heart of the objective.
        rem = intellect_up - intellect_down
        L_remain = (rem.sq()).mean()

        # (3) EMANATION: the single One regenerates the world-template (its
        #     ordered mean). All-from-one, by necessary procession.
        template, _ = self.emanate_template()
        world_mean = Node(X.data.mean(axis=0, keepdims=True))  # constant target
        eman = template - world_mean
        L_eman = (eman.sq()).mean()

        # (4) DISTINCTNESS: henads orthonormal -> Gram(H) == I. We need
        #     H @ H^T; build the transpose as a first-class autodiff op.
        Ht = _transpose(self.H)
        gram = self.H @ Ht                                   # (n_henads,n_henads)
        I = Node(np.eye(self.dims["henad"]))
        L_orth = ((gram - I).sq()).mean()

        total = L_recon + w_remain * L_remain + w_eman * L_eman + w_orth * L_orth
        parts = dict(recon=L_recon.data.item(), remain=L_remain.data.item(),
                     eman=L_eman.data.item(), orth=L_orth.data.item(),
                     total=total.data.item())
        return total, parts


def _transpose(node):
    """Transpose op for a 2D Node (needed for the Gram matrix H @ H^T)."""
    out = Node(node.data.T, (node,))

    def _backward():
        node.grad += out.grad.T
    out._backward = _backward
    return out


