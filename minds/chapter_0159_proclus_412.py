# PART 6 — TRAINING (the cosmos learns to return to its source)
# ============================================================================

def train(net, X, epochs=250, batch=64, lr=0.01,
          w_remain=1.0, w_eman=0.5, w_orth=1.0, log_every=50):
    opt = Adam(net.parameters(), lr=lr)
    N = X.shape[0]
    history = []
    for ep in range(1, epochs + 1):
        perm = np.random.permutation(N)
        ep_parts = None
        n_batches = 0
        for i in range(0, N, batch):
            xb = Node(X[perm[i:i + batch]])
            net.zero_grad()
            total, parts = net.loss(xb, w_remain, w_eman, w_orth)
            total.backward()
            opt.step()
            net._renorm_one()          # keep the One simple (unit sphere)
            if ep_parts is None:
                ep_parts = {k: 0.0 for k in parts}
            for k in parts:
                ep_parts[k] += parts[k]
            n_batches += 1
        for k in ep_parts:
            ep_parts[k] /= n_batches
        history.append(ep_parts)
        if ep % log_every == 0 or ep == 1:
            print(f"  epoch {ep:4d} | total {ep_parts['total']:.4f} "
                  f"| recon {ep_parts['recon']:.4f} "
                  f"| remain {ep_parts['remain']:.4f} "
                  f"| eman {ep_parts['eman']:.4f} "
                  f"| orth {ep_parts['orth']:.4f}")
    return history


