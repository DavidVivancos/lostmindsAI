# PART 4 — SYNTHETIC "COSMOS": DATA WITH A GENUINE HENADIC STRUCTURE
# ----------------------------------------------------------------------------
# We build a world that really does proceed from a few unities, so that the
# network's job — rediscovering the ordered emanation — is a real inference,
# not a trivial fit. Each sample belongs to one of K "henadic classes"; within
# a class it varies along a couple of subordinate directions ("the manifold").
# ============================================================================

def make_cosmos(n_per_class=120, K=4, nature_dim=20, noise=0.10, seed=7):
    rng = np.random.RandomState(seed)
    # K orthonormal "henadic" directions embedded in Nature-space.
    A = rng.randn(nature_dim, nature_dim)
    Q, _ = np.linalg.qr(A)
    henad_dirs = Q[:, :K]                       # (nature_dim, K)
    # Two subordinate "manifold" directions per class.
    sub_dirs = [Q[:, K + 2 * k: K + 2 * k + 2] for k in range(K)]

    X, y = [], []
    for k in range(K):
        base = 1.6 * henad_dirs[:, k]           # the class's abiding unity
        coeffs = rng.randn(n_per_class, 2) * 0.6
        manifold = coeffs @ sub_dirs[k].T       # spread within the class
        pts = base[None, :] + manifold + noise * rng.randn(n_per_class, nature_dim)
        X.append(pts); y += [k] * n_per_class
    X = np.vstack(X)
    y = np.array(y)
    # center a touch (keeps the "template" meaningful, not degenerate)
    X = X - X.mean(axis=0, keepdims=True) * 0.0
    perm = rng.permutation(len(X))
    return X[perm], y[perm], henad_dirs


