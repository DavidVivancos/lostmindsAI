# PART 1 — A MINIMAL REVERSE-MODE AUTODIFF ENGINE
# ----------------------------------------------------------------------------
# Proclus insists that every effect must be able to RETURN to its cause. A
# reverse-mode autodiff tape is, quite literally, a machine for return: the
# forward pass is procession (proodos); .backward() is reversion (epistrophE),
# tracing each value home to the parameters that caused it. We build our own so
# nothing about the learning is hidden inside a framework.
# ============================================================================

class Node:
    """A tensor node on the autodiff tape. Wraps an ndarray + its gradient."""

    __slots__ = ("data", "grad", "_backward", "_parents")

    def __init__(self, data, _parents=()):
        self.data = np.asarray(data, dtype=np.float64)
        self.grad = np.zeros_like(self.data)
        self._backward = lambda: None          # local grad rule, set by ops
        self._parents = _parents               # nodes this one was built from

    # -- helper: undo NumPy broadcasting so grads match parent shapes --------
    @staticmethod
    def _unbroadcast(grad, shape):
        # Sum out leading dims that broadcasting added ...
        while grad.ndim > len(shape):
            grad = grad.sum(axis=0)
        # ... then sum out dims that were size-1 in the parent.
        for ax, size in enumerate(shape):
            if size == 1:
                grad = grad.sum(axis=ax, keepdims=True)
        return grad.reshape(shape)

    # -- elementwise add (with broadcasting) --------------------------------
    def __add__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        out = Node(self.data + other.data, (self, other))

        def _backward():
            self.grad += self._unbroadcast(out.grad, self.data.shape)
            other.grad += self._unbroadcast(out.grad, other.data.shape)
        out._backward = _backward
        return out

    def __sub__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        return self + (-other)

    def __neg__(self):
        out = Node(-self.data, (self,))

        def _backward():
            self.grad += -out.grad
        out._backward = _backward
        return out

    # -- elementwise multiply (with broadcasting) ---------------------------
    def __mul__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        out = Node(self.data * other.data, (self, other))

        def _backward():
            self.grad += self._unbroadcast(other.data * out.grad, self.data.shape)
            other.grad += self._unbroadcast(self.data * out.grad, other.data.shape)
        out._backward = _backward
        return out

    __radd__ = __add__
    __rmul__ = __mul__

    # -- matrix multiply -----------------------------------------------------
    def __matmul__(self, other):
        other = other if isinstance(other, Node) else Node(other)
        out = Node(self.data @ other.data, (self, other))

        def _backward():
            self.grad += out.grad @ other.data.T
            other.grad += self.data.T @ out.grad
        out._backward = _backward
        return out

    # -- tanh nonlinearity (the "bending" of procession into a manifold) -----
    def tanh(self):
        t = np.tanh(self.data)
        out = Node(t, (self,))

        def _backward():
            self.grad += (1.0 - t * t) * out.grad
        out._backward = _backward
        return out

    # -- reductions to a scalar loss ----------------------------------------
    def sum(self):
        out = Node(self.data.sum(), (self,))

        def _backward():
            self.grad += np.ones_like(self.data) * out.grad
        out._backward = _backward
        return out

    def mean(self):
        out = Node(self.data.mean(), (self,))
        n = self.data.size

        def _backward():
            self.grad += (np.ones_like(self.data) / n) * out.grad
        out._backward = _backward
        return out

    def sq(self):
        """Elementwise square; convenient for L2 losses."""
        return self * self

    # -- topological reverse pass (epistrophE: everything returns) ----------
    def backward(self):
        topo, seen = [], set()

        def build(v):
            if id(v) not in seen:
                seen.add(id(v))
                for p in v._parents:
                    build(p)
                topo.append(v)
        build(self)
        self.grad = np.ones_like(self.data)   # d(loss)/d(loss) = 1
        for v in reversed(topo):
            v._backward()


